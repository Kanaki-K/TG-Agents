"""Журнал обложек 🔭 «Под прицелом» — чтобы кадры не повторялись из поста в пост.

Зачем отдельный журнал. У флагмана анти-повтор обложек есть с 16.07 (`core/cover_variety.py`:
журнал `data/cover_log.jsonl` + окно памяти на 4 последних кадра), и он работает — там мы САМИ
рисуем картинку, поэтому знаем про неё всё. У скоупа не было НИЧЕГО: на диске лежал только
`data/scope_last_cover.txt` с путём к последнему файлу, то есть сравнивать было не с чем в
принципе. Владелец 28.08: «чтобы не повторялись — надо проверять, механизм есть на флагмане и он
работает». Это он.

Чем этот журнал отличается от флагманского. Там кадр описывается признаками ИЗ БАНКА СХЕМ (мы же
его и заказывали), тут кадр ЧУЖОЙ — он пришёл со страницы первоисточника, и заранее известного
описания у него нет. Поэтому ярлык кадра («лого Solana», «график Glassnode», «скрин партнёрства»)
даёт тот, кто картинку видит: vision возвращает его тем же вызовом, которым выбирает номер. Лишнего
запроса это не стоит — несколько токенов на выходе.

Как применяется: последние ярлыки уходят в промпт выбора как «такое уже было, не повторяй». Это
СОВЕТ, а не вето — единственный годный кадр повторить лучше, чем уйти текстом (правило «лучше
скучный настоящий кадр, чем ИИ-картинка» никуда не делось, а рисовать скоупу запрещено).
"""
from __future__ import annotations

import json
import logging
from datetime import date

from core import config

LOG = config.ROOT / "data" / "scope_cover_log.jsonl"
WINDOW = 6          # сколько последних обложек показываем выбору: ~2 недели скоупов (Пн/Ср/Пт)


def record(label: str, title: str = "") -> None:
    """Дописать выбранную обложку в журнал. Сбой журнала НЕ должен ронять публикацию."""
    try:
        label = " ".join((label or "").split())[:80]
        if not label:
            return
        LOG.parent.mkdir(parents=True, exist_ok=True)
        row = {"date": date.today().isoformat(), "label": label,
               "title": " ".join((title or "").split())[:120]}
        with LOG.open("a", encoding="utf-8", newline="\n") as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    except Exception:
        logging.exception("scope_cover_log: не смог записать обложку (не критично)")


def recent(n: int = WINDOW) -> list[str]:
    """Ярлыки последних обложек, свежие первыми. Пусто — журнала ещё нет (первый прогон)."""
    try:
        if not LOG.exists():
            return []
        rows = [json.loads(ln) for ln in LOG.read_text(encoding="utf-8").splitlines() if ln.strip()]
        return [r.get("label", "") for r in rows[-n:] if r.get("label")][::-1]
    except Exception:
        logging.exception("scope_cover_log: журнал не читается — иду без анти-повтора")
        return []


def avoid_hint(n: int = WINDOW) -> str:
    """Готовый блок для промпта выбора. Пусто — если истории ещё нет (не сорим в промпт)."""
    got = recent(n)
    if not got:
        return ""
    return ("\n\n🔁 УЖЕ БЫЛО на последних обложках (свежие первыми): " + "; ".join(got) +
            ".\nПри РАВНОМ качестве бери НЕ такой кадр — канал не должен выглядеть однообразно "
            "(повторяются и объект, и тип: лого за лого, график за график). Это СОВЕТ, а не запрет: "
            "если годный кадр в пуле ровно один — бери его, даже если похожий уже был. Уйти текстом "
            "из-за похожести НЕЛЬЗЯ.")
