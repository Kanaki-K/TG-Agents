"""Независимый фактчек — «2FA» по цифрам (флагман И scope).

Зачем отдельный модуль/проход: автор (Криейтор) СЛЕП к собственным цифрам — он уже «поверил» в
них, пока писал, поэтому его самоотчёт «я проверил» = та же рука. Настоящая вторая проверка —
НЕЗАВИСИМЫЙ свежий вызов: видит только финальный пост + бриф-источники и проходит ЧЕК-ЛИСТОМ по
цифрам. Не правит текст и не пишет пост. Цифры — самый дорогой класс ошибок (красная линия бренда).

ЧТО ЭТО НЕ ДЕЛАЕТ: НЕ переразведывает тему (разведку уже хорошо сделал Скаут). Сверяет цифры поста
С УЖЕ СОБРАННЫМ источником (бриф) + точный спот через market_price; web_search — лишь крайнее средство
для важной цифры, которой нет в брифе (жёсткий кап). Без «х2 скаутинга» — проход короткий.

МОДЕЛЬ 2FA — Sonnet (осознанно, см. verify_post): цифры — красная линия, Haiku пропускал тонкие
числовые конфликты. Экономия здесь идёт НЕ моделью, а thinking=OFF (чек-лист, не генерация). В /test
падает на Haiku через runmode. Вызывается АВТО-ГЕЙТОМ из /schedule (конфликт ⚠️ → пост в отложку не
уходит, Криейтор правит) и вручную /verify (по последнему драфту).
"""
from __future__ import annotations

import datetime

from core import config, cost, llm, market_tools, runmode


def _today_iso() -> str:
    """Сегодня в ISO (или '' если часы недоступны) — верификатору нужна точка отсчёта свежести."""
    try:
        return datetime.date.today().isoformat()
    except Exception:  # noqa: BLE001
        return ""


# Темпоральная свежесть — ТОЛЬКО для scope (новостной 🔭). Флагман = вечные темы банка, там ссылка
