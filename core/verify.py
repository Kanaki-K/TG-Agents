def has_issues(verdict: str) -> bool:
    """Есть ли КОНФЛИКТ (⚠️), требующий авто-правки. ❓ «не прослеживается» — НЕ блокирует
    (это флаг владельцу: он видит его в «Отложенных»; авто-правка не должна вырезать валидные числа).

    ⚠️-строка ПЕРЕВЕШИВАЕТ строку статуса: модель, нашедшая конфликт, но написавшая «СТАТУС: ЧИСТО»
    (рассогласование саму с собой), не должна протаскивать пост мимо гейта.

    ИСКЛЮЧЕНИЕ (баг 31.07): модель помечает пункт значком ⚠️, разбирает его и тут же закрывает как ✅
    («⚠️ «продала 218.4 млн$» — цифра верна, уточнение в мотиве… ✅ по цифре»), а в машинном итоге честно
    пишет «ИТОГ: 10✅ / 0⚠️ / 0❓» и «СТАТУС: ЧИСТО». Старая проверка видела значок в начале строки и
    объявляла конфликт: прогон 31.07 из-за этого сделал ЛИШНИЙ круг «правка + полная веб-сверка» (~$0.5)
    и отправил владельцу пометку «остался числовой нюанс» на ЧИСТОМ вердикте. Значку в тексте разбора
    больше не верим, если ОБА машинных поля говорят «чисто»: и счётчик ⚠️ равен нулю, и статус ЧИСТО.
    Два независимых поля должны солгать одновременно — этого достаточно.
    ⚠️ Красной линии (has_redline — выдуманный участник/источник) это послабление НЕ касается: там
    остаётся паранойя по значку, потому что цена ошибки — фабрикация в канале, а не лишний доллар.
    """
    v = verdict or ""
    m = re.search(r"ИТОГ\s*:\s*(\d+)\s*✅\s*/\s*(\d+)\s*⚠", v)
    if m and int(m.group(2)) == 0 and "СТАТУС: ЧИСТО" in v:
        return False
    if any(_starts_warn(ln) for ln in v.split("\n")):
        return True
    if "СТАТУС: ПРАВКИ" in v:
        return True
    return False


