# Маркеры ⚠️-строк КЛАССА «ПОЛНОТА» — единственного, который просит ДОПИСАТЬ в пост, а не убрать.
# Зачем отдельный класс (вред 05.08): все прочие замечания 2FA сужают пост (убрать выдумку, заменить
# число), и правка по ним безопасна. Полнота одна тянет в другую сторону — и цена ошибки у неё
# ОБРАТНАЯ: не назвать участника значит ослабить тезис (владелец допишет), а вписать неподтверждённого
# значит опубликовать фабрикацию. 05.08 фактчек потребовал дополнить список операторов Arc с пяти до
# десяти ПО БРИФУ, сам оговорившись «веб-поиск анонс не подтвердил», — и правка внесла в пост Sumitomo
# и Standard Chartered, которые были инвесторами предпродажи, а не операторами. Проход, который в логе
# назывался «сношу выдумку», выдумку ВПИСАЛ, и панель отчиталась владельцу «снёс».
# Поэтому такие строки: (1) не считаются красной линией, (2) вырезаются из вердикта перед авто-правкой,
# (3) уходят владельцу отдельной строкой — дописывать участников решает человек, а не fix-проход.
_COMPLETENESS_MARKERS = ("полнот", "неполный ряд", "ряд неполон", "неполнота ряда")
# ⚠️ КЛАСС УЗКИЙ НАМЕРЕННО — по слову-классу, которое ШАГ 0.6 предписывает писать явно, а не по общим
# «не назван»/«пропущен». Причина: ШАГ 0.8 (пост-ИНСТРУКЦИЯ) требует ОБРАТНОГО — там неназванная
# затронутая модель это КРАСНАЯ ЛИНИЯ, потому что читатель с ней решит «это не про меня» и не сделает
# ничего (Coldcard 31.07). Широкие маркеры сняли бы с таких строк снос и вернули бы тот баг. Поэтому
# ниже ещё и прямое исключение: строка про безопасность/затронутые версии полнотой НЕ считается.
_ADVICE_SAFETY_MARKERS = ("затронут", "уязвим", "прошивк", "firmware", "версия лечения", "патч",
                          "заплатк", "скомпрометир", "мигрир")

# Обёртки, которыми модель украшает начало строки: **жирный**, буллет, номер таблицы, заголовок.
_LINE_DECOR = "*_#>-–—•· \t|0123456789."


def _starts_warn(line: str) -> bool:
    """Строка НАЧИНАЕТСЯ со значка ⚠, если снять markdown-мишуру?

    БАГ 31.07 (пост ушёл в канал с непроверённой атрибуцией): 2FA написал
    «**⚠️ АТРИБУЦИЯ: «Coinkite сам делал AI-аудит» — не прослеживается, убрать**», а проверка требовала
    ⚠ ПЕРВЫМ символом строки. Строка начиналась с `**` — красная линия не сработала, снос не запустился,
    и утверждение, которое 2FA просил убрать, осталось в опубликованном посте.
    Это ровно тот же класс, что markdown-обёртка вокруг «ИСЧЕРПАНО: да» в гейте темы: код не должен
    зависеть от того, решила модель выделить строку жирным или нет.
    """
    return (line or "").strip().lstrip(_LINE_DECOR).startswith("⚠")


def has_redline(verdict: str) -> bool:
    """⚠️ КРАСНОЙ ЛИНИИ — выдуманный/непроверённый УЧАСТНИК, атрибуция, приписанный источник (класс
    «фабрикация фактов»). В отличие от числового конфликта (fix_facts чинит его подстановкой ВЕРНОГО
    значения из веба/брифа), непроверённую СУЩНОСТЬ нельзя «поправить» — её можно только УБРАТЬ. И её
    НЕЛЬЗЯ публиковать даже пометкой в отложку (правило владельца 29.07: выдумывание фактов ради поста =
    абсолютный стоп; баг: пост ушёл с невериф. «BlackRock — клиент», 2FA пометил, а ре-гейт опубликовал
    как «мелкий нюанс»). Такой остаток обязан быть снесён ДО публикации, а не отправлен владельцу «на глаз».
    """
    # Значок ищем ГДЕ УГОДНО в строке, а не только в начале (в отличие от has_issues). Причина — цена
    # ошибки НЕСИММЕТРИЧНА: ложное срабатывание стоит одного прицельного прохода снос-правки (~$0.04,
    # веб-сверку он больше не тянет), а пропуск = фабрикация в канале. 31.07 пропустили дважды: сначала
    # из-за `**` перед значком, а в таблице-итоге значок вообще стоял в ТРЕТЬЕЙ колонке строки
    # («| 11 | АТРИБУЦИЯ: … | ⚠️ не прослеживается — убрать |»). Пока формат вердикта свободный, ловим широко.
    # ИСКЛЮЧЕНИЕ (05.08): строка класса ПОЛНОТА содержит те же слова-маркеры («участник», «не
    # подтверждён»), но просит ПРОТИВОПОЛОЖНОГО — дописать, а не снести. Пускать её в снос-проход нельзя.
    for ln in (verdict or "").split("\n"):
        if "⚠" in ln and any(m in ln.lower() for m in _REDLINE_MARKERS) and not is_completeness(ln):
            return True
    return False


def is_completeness(line: str) -> bool:
    """⚠️-строка класса «ПОЛНОТА» — просит ДОПИСАТЬ недостающего участника ряда, а не убрать лишнего.

    Фабрикация ПЕРЕВЕШИВАЕТ: строка, где рядом с полнотой стоит «выдумано/не прослеживается/атрибуция»,
    остаётся красной линией. Причина — цена: пропустить снос дороже, чем лишний раз не дописать.
    БЕЗОПАСНОСТЬ ПЕРЕВЕШИВАЕТ ТОЖЕ: в посте-ИНСТРУКЦИИ (ШАГ 0.8) неполнота — сама по себе красная линия,
    там неназванная затронутая модель опаснее ненаписанного поста. Такие строки полнотой НЕ считаем.
    """
    s = (line or "").lower()
    if "⚠" not in s or not any(m in s for m in _COMPLETENESS_MARKERS):
        return False
    if any(m in s for m in _ADVICE_SAFETY_MARKERS):
        return False
    return not any(m in s for m in ("выдум", "фабрик", "приписан", "атрибуц"))


def completeness_notes(verdict: str) -> list:
    """Строки класса ПОЛНОТА — владельцу в отчёт (кого 2FA считает недостающим). Пост не правим."""
    return [" ".join(ln.split()).strip() for ln in (verdict or "").split("\n") if is_completeness(ln)]


def only_completeness(verdict: str) -> bool:
    """Все ⚠️ вердикта — про полноту ряда, править в посте нечего.

    Без этого правка всё равно заводилась бы: strip_completeness убирает сами строки, но «СТАТУС:
    ПРАВКИ» остаётся, и has_issues честно говорит «есть замечания». Проход получал бы вердикт, в
    котором ему нечего делать, — круг Sonnet за ~$0.05 и риск, что модель «поправит» что-нибудь от
    себя. Нет ⚠️-строк вовсе (модель дала только СТАТУС) → False: фолбэк в сторону обычной правки.
    """
    warns = [ln for ln in (verdict or "").split("\n")
             if "⚠" in ln and not ln.strip().lstrip(_LINE_DECOR).upper().startswith(("ИТОГ", "СТАТУС"))]
    return bool(warns) and all(is_completeness(ln) for ln in warns)


def strip_completeness(verdict: str) -> str:
    """Вердикт БЕЗ строк-полноты — именно он идёт в авто-правку.

    Раньше fix_facts получал вердикт ЦЕЛИКОМ и добросовестно выполнял ВСЕ требования сразу, включая
    «дополни список до десяти». Фильтр оставляет проходу только то, что он умеет делать безопасно:
    убрать непроверённое и поставить верное значение.
    """
    kept = [ln for ln in (verdict or "").split("\n") if not is_completeness(ln)]
    return "\n".join(kept)


# Цитата внутри ⚠️-строки: 2FA всегда закавычивает спорный фрагмент поста («…» или "…").
_QUOTED_RE = re.compile(r"[«\"]([^«»\"]{4,120})[»\"]")


def redline_targets(verdict: str) -> list:
    """Что именно велено снести — закавыченные фрагменты из строк красной линии.

    Нужны, чтобы КОДОМ проверить, состоялся ли снос. До 05.08 проверки не было вообще: пайплайн делал
    один прицельный проход и печатал владельцу «снёс», не заглянув в результат. В том прогоне проход не
    только не снёс, но и добавил — а отчёт всё равно сказал «снёс». Сверка стоит ноль и не даёт отчёту врать.
    """
    out, seen = [], set()
    for ln in (verdict or "").split("\n"):
        if "⚠" not in ln or is_completeness(ln):
            continue
        if not any(m in ln.lower() for m in _REDLINE_MARKERS):
            continue
        for frag in _QUOTED_RE.findall(ln):
            key = " ".join(frag.split()).lower()
            if key and key not in seen:
                seen.add(key)
                out.append(" ".join(frag.split()))
    return out


def targets_left(post: str, targets: list) -> list:
    """Какие из целей сноса ВСЁ ЕЩЁ в тексте (сравнение по нормализованным словам, без регистра)."""
    body = " ".join((post or "").split()).lower()
    return [t for t in (targets or []) if " ".join(t.split()).lower() in body]


# Имя собственное: латиница с заглавной/аббревиатура/тикер (BlackRock, DTCC, ICE, a16z, SBI, Sumitomo).
# Только латиница НАМЕРЕННО: кириллица с заглавной — это в основном начало предложения, шума было бы
# больше сигнала, а в крипто/финансовом посте участники почти всегда пишутся латиницей.
_ENTITY_RE = re.compile(r"\b(?:[A-Z][A-Za-z0-9&.\-]{2,}|[a-z]\d{1,2}[a-z])\b")
# Не имена: валюта, единицы, служебное — иначе страж флудит на каждой правке числа.
_ENTITY_STOP = {"USD", "EUR", "BTC", "ETH", "USDC", "USDT", "AI", "API", "CEO", "CFO", "ETF", "ETFs",
                "The", "This", "That", "And", "But", "For", "New", "Layer", "Level"}


def new_entities(before: str, after: str) -> list:
    """Имена собственные, которых в посте НЕ БЫЛО и которые появились после авто-правки.

    Детерминированный страж вокруг fix_facts (05.08). Класс ошибки «правка внесла в пост сущность»
    раньше ловился только глазами владельца — а именно он и есть фабрикация в канале. Код не решает,
    выдумка это или законное уточнение: он лишь называет новые имена, решает человек. Та же схема, что
    в find_attributions — код показывает, КУДА смотреть.
    """
    was = {m.group(0) for m in _ENTITY_RE.finditer(before or "")}
    out, seen = [], set()
    for m in _ENTITY_RE.finditer(after or ""):
        name = m.group(0)
        if name in was or name in _ENTITY_STOP or name.lower() in seen:
            continue
        seen.add(name.lower())
        out.append(name)
    return out


def _latest(subdir: str) -> str:
    """Содержимое самого свежего .md в memory/<subdir>/ (или '')."""
    d = config.ROOT / "memory" / subdir
    if not d.exists():
        return ""
    files = sorted(d.glob("*.md"), key=lambda p: p.stat().st_mtime, reverse=True)
    return files[0].read_text(encoding="utf-8") if files else ""


def latest_brief() -> str:
    return _latest("briefs")


def latest_draft() -> str:
    return _latest("drafts")


def _web_context(scope: bool, web: bool) -> tuple[str, dict]:
    """Какую веб-инструкцию и какой web_search-инструмент подмешать — по режиму (scope/флагман/дефолт).

    Вынесено из verify_post чистой функцией, чтобы покрыть ветвление тестом без LLM/сети:
      • scope+web  → SCOPE_SOURCE_CHECK  (новость, бриф Тир-3 не истина; кап 4);
      • web (флагман, без scope) → FLAGSHIP_SOURCE_CHECK (брифа под вечную тему НЕТ; сверяй с вебом; кап 4);
      • иначе → без спец-инструкции, дефолтный кап 1 (брифовый первый проход).
    """
    if scope and web:
        return SCOPE_SOURCE_CHECK, SCOPE_VERIFY_WEB
    if web:
        return FLAGSHIP_SOURCE_CHECK, FLAGSHIP_VERIFY_WEB
    return "", VERIFY_WEB


def verify_post(post: str, brief: str = "", api_key: str | None = None, model: str | None = None,
                scope: bool = False, web: bool = False) -> str:
    """Независимая проверка фактов поста. Возвращает вердикт-таблицу (текст для чата/лога).

    scope=True — добавляет проверку темпоральной свежести (новостной 🔭): не устарел ли повод и
    не подан ли свежий повод как старьё. Для флагмана (вечные темы) НЕ включаем.
    web=True — АВТОРИТЕТНАЯ веб-сверка: герой-цифры сверяются с РЕАЛЬНОСТЬЮ (Тир-1), а не с брифом. Для
    scope (баг 22.07: бриф из Тир-3 X дал выдуманные «900 часов»/«$957M за 6 дней»). Для флагмана (задача
    23.07: у вечной темы брифа под неё НЕТ — бриф на диске про другое, сверять надо с вебом). Дорого
    (web_search) — включаем в финальном ре-гейте run_pipeline, не во внутреннем проходе write()."""
    post = (post or "").split("[[SPLIT]]")[0].strip()  # только сам пост, без меты-заметки
    if not post:
        return "(нечего проверять — пустой пост)"
    # ceiling: 2FA — механическая роль, override/тест могут только удешевить её, не удорожить
    mdl = model or runmode.resolve("claude-sonnet-4-6", ceiling="claude-sonnet-4-6")
    cost.set_context("verify")
    today = _today_iso() or "(дата недоступна)"
    temporal = TEMPORAL_CHECK.format(today=today, fresh_days=SCOPE_FRESH_DAYS) if scope else ""
    source_check, web_tool = _web_context(scope, web)  # веб-сверка герой-цифр (не доверять брифу)
    # Атрибуции ищем КОДОМ и наводим на них модель поимённо (см. find_attributions): общего правила в
    # системном промпте мало — 2FA уже имел «сверь цитаты» и всё равно пропустил выдуманную Ламмис.
    attrs = find_attributions(post)
    attr_note = ATTRIBUTION_NOTE.format(items="\n".join(f"  • «{a}»" for a in attrs)) if attrs else ""
    user = (f"СЕГОДНЯ: {today}\n\nПОСТ ДЛЯ ПРОВЕРКИ:\n{post}\n\n"
            f"ИСХОДНЫЙ БРИФ СКАУТА (источники для сверки):\n{brief or '(бриф не найден)'}\n\n"
            f"Проверь КАЖДОЕ проверяемое утверждение. Выдай вердикт-список и ИТОГ."
            f"{attr_note}{temporal}{source_check}")
    try:
        # thinking ВЫКЛ намеренно: это ЧЕК-ЛИСТ (сверка по собранному), не генерация. Adaptive thinking
        # тут раздувал ВЫХОДНЫЕ токены — самую дорогую статью verify (~55% цены) — не добавляя точности.
        text, _ = llm.reply(mdl, VERIFIER_SYSTEM, [], user, [web_tool, market_tools.PRICE_TOOL],
                            lambda n, a: market_tools.handle(n, a) or "", api_key, None)
        return (text or "(пусто)").strip()
    except Exception as e:  # noqa: BLE001 — фактчек не должен ронять конвейер
        return f"(фактчек не удался: {e})"
