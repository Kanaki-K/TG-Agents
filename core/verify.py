# --- АТРИБУЦИИ: находим КОДОМ, сверяем МОДЕЛЬЮ (разделение ролей осознанное) ---
# Баг 15.07 (CLARITY): модель написала «по словам сенатора Ламмис, где-то в 2030-м». Ламмис в брифе не
# было ВООБЩЕ — имя выдумано, чтобы придать вес числу, утащенному из соседнего раздела брифа. 2FA это
# пропустил: он сверяет ЧИСЛА с брифом, а имя под цитатой в его чек-лист не входило.
# ПОЧЕМУ ОБНАРУЖЕНИЕ КОДОМ, А СВЕРКА МОДЕЛЬЮ: пропустить атрибуцию нельзя (цена = ложь про живого
# человека под нашим логотипом), поэтому ищем регуляркой — она не «забудет» и не устанет. А вот СВЕРЯТЬ
# имя с брифом регуляркой нельзя: бриф пишет источники латиницей («Lummis»), пост — кириллицей
# («Ламмис»), и русская транслитерация иностранных имён необратима (Lummis→Ламмис, а не Луммис). Код бы
# завалил такое ложной тревогой, а ложная ⚠️ портит верный пост (баг 30.06 с «почти 300 млрд»).
# Поэтому: код показывает модели КУДА смотреть, модель решает СОВПАЛО ЛИ.
# ⚠️ БЕЗ re.IGNORECASE намеренно: в ветке (б) ЗАГЛАВНАЯ буква субъекта — это и есть условие («Ламмис
# заявила», но не «он заявил»). С IGNORECASE класс [A-ZА-ЯЁ] перестаёт что-либо значить и ветка начинает
# цеплять любой глагол речи. Регистр подводок в ветке (а) разводим руками ([Пп]о, [Кк]ак).
_ATTRIBUTION_RE = re.compile(
    # (а) явная подводка: «по словам/данным/версии <кто-то>», «согласно <кто-то>», «как заявил <кто-то>».
    # Аудит 20.07 добавил «по данным/информации/версии», «согласно», глаголы предупредил/рассказал/настаивает.
    r"(?:[Пп]о\s+(?:словам|мнению|оценке|оценкам|прогнозу|прогнозам|расчётам|данным|информации|версии)|"
    r"[Сс]огласно|"
    r"[Кк]ак\s+(?:сказал|сказала|заявил|заявила|отметил|отметила|пишет|пишут|говорит|говорят|считает|"
    r"предупредил|предупредила|рассказал|рассказала|настаивает))"
    r"\s+[^,.!?;:()\n]{2,60}"
    # (б) «<Имя> заявил/прогнозирует/ожидает …» — субъект с ЗАГЛАВНОЙ + глагол речи/прогноза
    r"|(?:[A-ZА-ЯЁ][\w\-]+(?:\s+[A-ZА-ЯЁ][\w\-]+){0,2})\s+"
    r"(?:заяв|сказа|отмет|обеща|пообеща|предсказ|прогнозиру|ожида|счита|уверя|призна|подтверд|объяв|"
    r"предупре|расска|настаива|полага|допуст|опаса|предрек)\w*"
    # (в) двоеточие-цитата «<Имя>: «…»» — атрибуция БЕЗ глагола (частый пропуск, аудит 20.07). Кавычка
    # ПОСЛЕ двоеточия обязательна — иначе тег-заголовок «CLARITY Act: кому выгоден» ложно триггерил бы.
    r"|(?:[A-ZА-ЯЁ][\w\-]+(?:\s+[A-ZА-ЯЁ][\w\-]+){0,2})\s*:\s*[«\"]",
    re.UNICODE,
)


def find_attributions(post: str) -> list:
    """Фрагменты поста, где утверждение приписано конкретному лицу/организации.

    Только ОБНАРУЖЕНИЕ (куда смотреть фактчеку) — вердикт «прослеживается ли» выносит модель по брифу.
    Ложные срабатывания тут дёшевы (модель сверит и поставит ✅), пропуск — дорог, поэтому ловим широко.
    """
    seen, out = set(), []
    for m in _ATTRIBUTION_RE.finditer(post or ""):
        frag = " ".join(m.group(0).split()).strip(" ,-—")
        key = frag.lower()
        if key not in seen:
            seen.add(key)
            out.append(frag)
    return out


