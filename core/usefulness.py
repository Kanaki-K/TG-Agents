"""Гейт ПОЛЬЗА-ЭДЖ для scope (🔭 «Под прицелом») — отдельный от 2FA судья «и что?».

ЗАЧЕМ ОТДЕЛЬНО ОТ verify.py: 2FA проверяет ФАКТЫ (цифры — красная линия) и по своему контракту
НЕ судит качество и НЕ переписывает пост. Польза — другой класс дефекта: пост может быть фактически
ЧИСТЫМ и всё равно бесполезным — пересказ события без вывода для читателя. Смешать это в фактчекер =
размыть его единственную роль, поэтому гейт живёт отдельным модулем (как dedup — своя роль, свой файл).

ПОЧЕМУ ЖЁСТКИЙ (СТОП), А НЕ АВТО-ПРАВКА: польза — свойство ТЕМЫ/УГЛА, а не формулировки. Приклеить
«зачем это знать» последней строкой (что делала авто-правка) её не создаёт. Нельзя редактурой вытащить
пользу из повода, в котором её нет — можно только НЕ публиковать. Лучше пропустить прогон, чем выпустить
слабое (владелец: «нет пользы — дата не спасёт»).

УРОК ДВУХ ПРОГОНОВ 20.07 (почему гейт вообще появился):
  • пост про индекс Strategy прошёл анти-повтор + 2FA (факты чистые), но отвечал на «зачем мне это»
    одним словом в последней строке → владелец ЗАБРАКОВАЛ;
  • пост про ORANGE JUICE (та же свежесть, ~5 дней) владелец ПРИНЯЛ.
Разница НЕ в свежести, а в пользе-через-эдж. Отсюда приоритет: польза = главный ЖЁСТКИЙ гейт;
темпоральная свежесть (verify.TEMPORAL_CHECK) — МЯГКИЙ фильтр, который пользу не перебивает.

КРИТЕРИИ дистиллированы из разбора РЕДАКТУРЫ владельца (перевод РЕМЕСЛА в ПРОВЕРЯЕМЫЕ признаки).
Сами приёмы редактуры (заголовок-парадокс, ранний факт-якорь, цитата-замок) в промпт НЕ идут —
это over-engineering-ловушка (golden-baseline): гейт ловит ОТСУТСТВИЕ пользы, а не диктует КАК писать.

МОДЕЛЬ — Sonnet (как dedup-судья): это оценочное суждение, Haiku тут груб. thinking ВЫКЛ (это чек по
готовому посту, не генерация). В /test падает на дешёвую модель через runmode.resolve автоматически.
"""
from __future__ import annotations

from core import cost, llm, runmode

# Судья качества = Sonnet, ceiling=Sonnet: механическая роль, override/тест могут только удешевить.
GATE_MODEL = "claude-sonnet-4-6"

JUDGE_SYSTEM = (
    "Ты — редактор-судья канала KANAKI CRYPTO. Перед тобой ОДИН scope-пост (🔭 «Под прицелом» — "
    "короткий аналитический на свежий повод). Оцени его по ЕДИНСТВЕННОМУ вопросу: даёт ли пост "
    "читателю-долгосрочнику (копит BTC вдолгую, DCA, не трейдер) КОНКРЕТНЫЙ вывод через НЕОЧЕВИДНЫЙ "
    "угол — или это пересказ события «что случилось»?\n"
    "Ты НЕ проверяешь факты (это делает 2FA отдельным проходом) и НЕ переписываешь пост. Только вердикт.\n\n"
    "Прогони пост по трём ПРИЗНАКАМ ПРОВАЛА (хватает ОДНОГО, чтобы завернуть):\n"
    "  1) ПЕРЕСКАЗ. Пост описывает событие (кто/что/сколько), но после прочтения у читателя нет ни "
    "вывода-действия, ни сдвига оптики на его тезис. Если единственная «польза» — «будь скептичен к "
    "этому отчёту/твиту/цифре» — это ПРОВАЛ: слишком мелко для отдельного поста.\n"
    "  2) КОНТРАСТ НЕ ПОД АУДИТОРИЮ. Если пост объясняет через контраст/аналогию — она должна опираться "
    "на то, что криптан-долгосрочник УЖЕ знает (BTC-казны/MSTR, DCA, халвинг, ETF, ликвидность). "
    "Контраст с абстракцией, чужой рознице (PE-фонды, корпфинанс, банковский надзор) БЕЗ перевода на "
    "знакомое = слабый эдж, читатель не чувствует «почему это про меня».\n"
    "  3) ТЕЗИС НА АБСОЛЮТЕ. Если центральное утверждение держится на непроверяемом абсолюте («без "
    "долга», «такого ещё не делали», «впервые в истории», «никто не пробовал») — это провал ВЫБОРА "
    "тезиса: убери абсолют — и поста нет. (Заменить на честный факт той же силы — работа автора, не "
    "твоя; ты только фиксируешь дефект.)\n\n"
    "Тебе дан и БРИФ Скаута (источники) — сверься: не лежит ли в источниках более сильный угол/контраст, "
    "который автор НЕ взял (это тоже довод к провалу «взято слабейшее»).\n\n"
    "ВЫВОД строго в таком порядке:\n"
    "  • 1-3 строки разбора по признакам (какой сработал / почему чисто);\n"
    "  • строка «ВЫВОД ДЛЯ ЧИТАТЕЛЯ: <один конкретный вывод-действие или сдвиг оптики, который даёт "
    "пост>» — если сформулировать не получается, честно напиши «не нахожу»;\n"
    "  • ФИНАЛ — РОВНО одна строка: «ГЕЙТ: ПОЛЬЗА» (есть вывод через неочевидный угол) либо "
    "«ГЕЙТ: ПЕРЕСКАЗ» (пусто/мелко/контраст-абстракция/тезис-на-абсолюте).\n"
    "Пограничный случай — склоняйся к ПЕРЕСКАЗ (лучше пропустить прогон, чем выпустить слабое)."
)


def judge(post: str, brief: str = "", api_key: str | None = None, model: str | None = None) -> str:
    """Судит пользу-эдж scope-поста. Возвращает вердикт-текст (последняя строка — ГЕЙТ: ПОЛЬЗА/ПЕРЕСКАЗ)."""
    post = (post or "").split("[[SPLIT]]")[0].strip()  # только сам пост, без меты-заметки
    if not post:
        return "(нечего судить — пустой пост)\nГЕЙТ: ПЕРЕСКАЗ"
    # ceiling: механическая роль — override/тест только удешевляют, не удорожают.
    mdl = model or runmode.resolve(GATE_MODEL, ceiling=GATE_MODEL)
    cost.set_context("usefulness")
    user = (f"ПОСТ ДЛЯ ОЦЕНКИ:\n{post}\n\n"
            f"БРИФ СКАУТА (источники — нет ли в них более сильного угла, чем взял автор):\n"
            f"{brief or '(бриф не найден)'}\n\n"
            f"Прогони по трём признакам, назови вывод для читателя и вынеси ГЕЙТ.")
    try:
        # thinking ВЫКЛ (чек по готовому посту), инструментов нет → cache_system=False (one-shot).
        text, _ = llm.reply(mdl, JUDGE_SYSTEM, [], user, [], lambda n, a: "", api_key, None,
                            cache_system=False)
        return (text or "(пусто)").strip()
    except Exception as e:  # noqa: BLE001 — гейт не должен ронять конвейер (в run_pipeline фейл-открыто)
        return f"(гейт польза-эдж не удался: {e})"


def blocks(verdict: str) -> bool:
    """True — пост завёрнут (пересказ без пользы/эджа). Фейл сети/парсинга (нет строки ГЕЙТ) НЕ блокирует:
    польза — вторичная сеть после 2FA, сбой самого гейта не должен глушить публикацию (фейл-открыто)."""
    v = verdict or ""
    return "ГЕЙТ: ПЕРЕСКАЗ" in v
