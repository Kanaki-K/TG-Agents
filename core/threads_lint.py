"""Проверки постов Threads по ЗАМЕРУ виральности 09.09.2026 — код, а не текст в промпте.

ПОЧЕМУ КОДОМ. Урок золотого эталона скоупа: новое правило, дописанное в промпт, размывает
остальные — писатель начинает обслуживать инструкцию вместо повода, и качество падает (это уже
случалось, откатывали). Поэтому измеримое живёт здесь: свод правил объясняет ЗАЧЕМ, линтер ловит
ФАКТ. Претензия показывается владельцу и писателю, но текст автоматически НЕ переписывается —
чинить смысл вслепую хуже, чем не чинить.

ОТКУДА ПОРОГИ. Замер 64 заводских постов за 90 дней, охват нормирован на медиану своего месяца
(в августе просела вся лента), значения медианные — docs/THREADS_ANALYTICS_2026-09-09.md:
конфликт/потеря в заголовке ×3.6 · названная сумма ×2.4 · «ты»/назидание ÷2.8 · объяснялка в
заголовке ÷1.5 · эмодзи в начале ÷1.6 · заголовок 35–80 знаков.

ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. «Финал оставляет читателю что сказать» — главная претензия замера, но
машиной она не проверяется: закрытость вывода видна только смыслом. Такие вещи остаются в своде
правил и на суде живого прогона; выдумывать для них регулярку — значит получить ложные срабатывания,
а ложная претензия учит автора не верить линтеру ЦЕЛИКОМ, вместе с верными (урок ТГ-линтера 07.08).
"""
from __future__ import annotations

import re

MIN_HEAD, MAX_HEAD = 35, 80
MAX_PARAS = 7          # абзацев на пост: у 62 опубликованных 5-6, больше 7 — у 3 (замер 23.09.2026)

# Конфликт: кто-то теряет, ломается, разворачивается, сталкивается. Список выведен из заголовков
# 13 постов корпуса, у которых охват втрое выше типичного, — не придуман за столом.
_CONFLICT = re.compile(
    r"(ограбил|ограбл|взлом|укра[дл]|потер|убыт|минус|обвал|рухн|умер|мертв|мёртв|встал|останов|"
    r"провал|сдал|сдают|сдаются|бастуют|моргнул|разверн|кончается|кончилась|захват|подрыва|"
    r"дыра|обман|врут|нарисован|подделал|запретил|заблокир|ушли|уходит|уйдут|утекл|утечк|"
    r"дорого|дешевл|отказал|проигр|бьёт|бьет|против|спор|судит|иск\b|штраф|"
    # «ни разу не поймал», «нельзя ликвидировать», «чьих именно» — отрицание и спор о принадлежности
    r"ни разу|никогда|нельзя|не поймал|чьих|кому достан|за чей счёт|за чей счет|"
    # смена расстановки сил: одно вытесняет другое
    r"важнее|вместо|перестал|больше не|впервые|последн)", re.I)
# Ставка деньгами: сумма, процент, кратность. «110 млн$», «20%», «в 24 раза», «40 трлн».
_MONEY = re.compile(
    r"\d[\d\s.,]*\s*(млн|млрд|трлн|тыс|%|\$|раз)|\$\s*\d|\d+\s*(процент|иксов)|"
    r"\d+\s*[xхX]\b|"                                    # «100x», «24х» — кратность тоже ставка
    r"\b(миллиард|миллион|триллион|тысяч)", re.I)
_TY = re.compile(r"\b(ты|тебе|тебя|тобой|твой|твоя|твоё|твое|твои|твой|твоего|твоей|твоих)\b", re.I)
_VY = re.compile(r"\b(вы|вам|вас|вами|ваш|ваша|ваше|ваши|вашего|вашей|ваших)\b", re.I)
# Объяснялка: текст обещает разобрать устройство, а не назвать ставку.
_HOWTO = re.compile(r"(как (это )?устроен|что такое|бывает двух|есть метрика|принцип работы|"
                    r"разбира|объясня|простыми словами|берёшь|берешь|сравнива)", re.I)
_LINK = re.compile(r"https?://|t\.me/|@[a-z_0-9]{4,}", re.I)
_HASHTAG = re.compile(r"(?:^|\s)#\w+")


# ══ ЯЗЫК v3 (23.09.2026) — те же правила, что у ТГ-канала, кодом ═══════════════════════════════════
# Владелец про мини-скоуп 23.09: «Каждый перевод с биржи на личный кошелёк - это не транзакция. Это
# подпись» — «не это, а вот это; ошибка ровно та, что была у скоупа». Свод мини-скоупа запрещал
# «Это не X. Это Y» текстом (Шаг 4, чистка ИИ-паттернов) — и писатель построил на антитезе весь пост:
# заголовок, середину («вычислила не по словам - по манере») и финал («означала не "меня не найдут".
# Она означала…»). Тот же класс, что ТГ до v3: правило в промпте без кода проговаривается и обходится.
# ПОЧЕМУ НЕ «ЛЮБАЯ АНТИТЕЗА»: замер 326 постов канала — «не X, а Y» в 45% ПРИНЯТЫХ, включая флагман
# владельца «Массовую крипту тормозит не цена, а 12 слов». Переносим ровно правила ТГ v3: «Это не X.
# Это Y» — нигде; антитеза — не в заголовке и не в финале; передоз — с 2 фигур (в ТГ 3 на ~1300 знаков,
# здесь пост в 500). Раздельная форма «не X. Она Y» в заголовке/финале канала: 7 из 326, и все семь —
# ИИ-штамп («Ценность — это не хайп. Это контекст»).
# Живой прогон после первой версии проверки: писатель ушёл в соседние формы — «Вопрос не в том, знают ли
# его. В том, сколько связок» и «Решение приняли не в этот день. Его подписали…». Вторая фраза теперь
# может начинаться и с «В том / Его / Её / Их». Замер заголовков и финалов канала: 7 из 326, все — ИИ-штамп.
_SPLIT_ANTI = re.compile(r"\b(?i:не)\s+[^.!?\n]{1,60}[.!?]+\s+(?:Это|Она|Он|Оно|Они|Его|Её|Ее|Их|В том|А в том|Дело в)\b")
# «Вопрос не в том, знают ли имя. Вопрос - сколько…» (третий живой прогон): оборот «X не в том» и есть
# антитеза, чем бы ни начиналась вторая фраза. Канал: 0 заголовков и 0 финалов из 326, в теле — 5 постов.
_NE_V_TOM = re.compile(r"\b(?:вопрос|дело|суть|проблема|смысл|главное)\s+(?:тут\s+|здесь\s+)?не\s+в\s+том\b",
                       re.IGNORECASE)
# Четвёртый живой прогон: «Вопрос не "знают ли имя". Вопрос - сколько связок» и «дело не в криптографии».
# Одно и то же слово открывает обе фразы — та же антитеза. Канал: в заголовках/финалах 2 из 326, обе
# — она же («Вам не нужен каждый рост. Вам нужен результат»). «Дело/вопрос не в…»: 0 из 326.
_SAME_WORD = re.compile(r"\b([А-ЯЁ][а-яё]{2,})\s+(?:тут\s+|здесь\s+)?не\s+[^.!?\n]{1,60}[.!?]+\s+"
                        r"(?:Настоящ\w+\s+)?(?i:\1)\b")
_NE_V = re.compile(r"\b(?:дело|вопрос|суть|проблема|смысл)\s+(?:тут\s+|здесь\s+|уже\s+)?не\s+в\b", re.IGNORECASE)
# Обратный порядок (прогон после строк-битов 23.09): «Псевдоним прячет имя. Он не прячет то, как Вы думаете»
# — утверждение, затем отрицание тем же глаголом. Заголовки/финалы канала: 0 из 326.
_REV_PAIR = re.compile(r"\b([а-яё]{3,})\s+[^.!?\n]{1,60}[.!?]+\s+(?:Он|Она|Оно|Они|Это|Но)\s+не\s+(?i:\1)\b",
                       re.IGNORECASE)
# Шаблон вместо текста: тот же прогон выдал мини-флагману заголовок буквально «Не X. Это Y».
_TEMPLATE = re.compile(r"\b(?:не|это)\s+[XYХ]\b", re.IGNORECASE)
# «не взламывают - её вычисляют»: тире + местоимение/«это». Тире без местоимения не берём — замер: «Коду
# доверять не нужно - он либо пропускает…», «не дрогнул - в такие моменты…» — обычные фразы, не антитеза.
_DASH_PRON = re.compile(r"\bне\s+[^,.!?\n—–-]{1,40}?\s[-—–]\s+(?:её|ее|его|их|это)\b", re.IGNORECASE)
# «не по словам - по манере»: тот же предлог после тире — точная форма (1 из 326 постов канала)
_DASH_ANTI = re.compile(r"\bне\s+(по|в|на|за|из|от|к|у|с|о|про|для)\s+[^,.!?\n]{1,40}?\s*[-—–,]\s+\1\s",
                        re.IGNORECASE)
# Претензии ТГ-линтера про ОФОРМЛЕНИЕ канала (жирный, эмодзи-набор, футер, ссылки, длина ТГ-заголовка):
# у Threads свои нормы, и они проверяются в check() ниже.
_TG_ONLY = ("НЕ жирный", "заголовок длинный", "эмодзи-заголовок", "нет футера", "ссылка (http)",
            "бренд-домен")


def _joined(t: str) -> str:
    """Текст, где КАЖДАЯ строка — предложение. Строки-биты идут без точек (канон), и парные формы
    антитезы («Модель собирает не имя» / «Она собирает привычки») без этого теряют границу фразы."""
    lines = [ln.strip().rstrip(".") for ln in (t or "").split("\n") if ln.strip()]
    return ". ".join(lines) + ("." if lines else "")


# Служебное слово вместо текста: живой прогон 23.09 дал заголовок «Заголовок про биткоин не сдался…».
_SERVICE = re.compile(r"^\s*(?:заголовок|финал|пост|тред|строка|лид|хук)\b", re.IGNORECASE)


def _anti_count(t: str) -> int:
    from core import creator_tools as ct
    t = _joined(t)
    return (len(ct._TITLE_ANTI.findall(t)) + len(_SPLIT_ANTI.findall(t + " "))
            + len(_DASH_ANTI.findall(t)) + len(_DASH_PRON.findall(t)) + len(_NE_V_TOM.findall(t))
            + len(_SAME_WORD.findall(t)) + len(_REV_PAIR.findall(t)))


def language(text: str) -> list[str]:
    """Претензии к ЯЗЫКУ поста по правилам v3 ТГ-канала. Пустой список = чисто.

    Их чинит писатель одним кругом (threads_creator._enforce_language), остаток видит владелец."""
    from core import creator_tools as ct
    t = (text or "").strip()
    if not t:
        return []
    _, warns = ct._lint(t, "threads")
    out = [w for w in warns if not any(m in w for m in _TG_ONLY)]
    head = headline(t)
    paras = [p.strip() for p in re.split(r"\n+", t) if p.strip()]   # строка = бит, как публикуется
    if _SERVICE.search(head):
        out.append("⛔ СЛУЖЕБНОЕ СЛОВО в заголовке («Заголовок…», «Финал…») — это разметка, а не текст")
    if re.search(r"[Ээ]то не [^.!?\n]{1,60}[.!?]+\s+Это\b", _joined(t)) and not any("Это не X" in w for w in out):
        out.append("«Это не X. Это Y» — ИИ-штамп (§11.5), скажи Y прямо с фактом")
    fin = paras[-1] if len(paras) >= 2 else ""
    # Строки-биты режут финал на две короткие строки — пара «X. Он не X» оказывается по разные стороны
    # переноса. Короткая последняя строка — финал вместе с предыдущей.
    if fin and len(fin) < 70 and len(paras) >= 3:
        fin = paras[-2].rstrip(".") + ". " + fin
    if _TEMPLATE.search(t):
        out.append("⛔ ШАБЛОН ВМЕСТО ТЕКСТА («не X» / «это Y» буквами) — напиши настоящую фразу")
    # Заголовок, разрезанный строками-битами: «…никогда не была про имя» / «Она была про то…» (прогон
    # 23.09). Короткий заголовок проверяем вместе со следующей строкой — только парные формы.
    head2 = (head.rstrip(".") + ". " + paras[1]) if len(paras) >= 2 and len(head) < 70 else head
    if (ct._TITLE_ANTI.search(head) or _SPLIT_ANTI.search(head2 + " ") or _DASH_PRON.search(head)
            or _REV_PAIR.search(head2) or _SAME_WORD.search(head2)
            or _NE_V_TOM.search(head) or _NE_V.search(head) or _SAME_WORD.search(head)
            or _REV_PAIR.search(head)):
        out.append("⛔ АНТИТЕЗА В ЗАГОЛОВКЕ («не X, а Y» / «это не X. Это Y»): заголовок — одно утверждение. "
                   "Спроси, было ли отрицаемое X; не было — скажи Y прямо, с фактом")
    if fin and (ct._FIN_ANTI.search(fin) or _SPLIT_ANTI.search(fin + " ") or _DASH_ANTI.search(fin)
                or _DASH_PRON.search(fin) or _NE_V_TOM.search(fin) or _NE_V.search(fin)
                or _SAME_WORD.search(fin) or _REV_PAIR.search(fin)):
        out.append("⛔ АНТИТЕЗА В ФИНАЛЕ — конструкция вместо мысли. Финал — простое следствие обычными "
                   "словами, одно утверждение")
    # ФОРМА ПО 62 ОПУБЛИКОВАННЫМ (23.09.2026). Двоеточие: у черновиков завода в 58% постов, у
    # опубликованных — 16%, и посты с ним берут 0.65 охвата своего месяца против 1.08 без него (n=10/52).
    # Скобки: 0 из 62 опубликованных. Уточнение в скобках — либо своя строка, либо лишнее.
    # Порог — ДВА: одно двоеточие владелец сам оставил в правке 23.09 («Бутерин признал: прятать имя…»);
    # в опубликованных одно — у 8 постов, два — у 2 из 62.
    if t.count(":") >= 2:
        out.append(f"двоеточий {t.count(':')} — в опубликованных постах больше одного почти не бывает (2 из 62), "
                   "а посты с двоеточием берут 0.65 охвата против 1.08. Оставь максимум одно: перестрой в две "
                   "фразы или «что»")
    if re.search(r"\([^)]{2,}\)", t):
        out.append("уточнение в скобках — в 62 опубликованных постах скобок нет ни разу. Сделай его своей "
                   "строкой или убери")
    # МИНУСЫ ЗАМЕРА THREADS, КОТОРЫЕ ЧИНЯТСЯ КРУГОМ ПРАВКИ (23.09.2026). Отобраны те, что на 62
    # опубликованных постах почти не спорят с владельцем. «Нет ставки» сюда НЕ идёт: регулярка отметила
    # бы 39 из 62 принятых, включая его правку 23.09 («предаст» — потеря, которой нет в словаре); ложная
    # претензия в круге правки переписала бы одобренные заголовки. Ставка остаётся подсказкой (virality).
    if _LINK.search(t) or _HASHTAG.search(t):
        out.append("⛔ ссылка/хештег/упоминание — режут охват в разы (замер 5.4×), в пост не идут")
    if _TY.search(t):
        out.append("«ты» в тексте (÷2.8 охвата по замеру Threads): канал пишет на «Вы» — перестрой фразу, "
                   "а не меняй местоимение: режет охват назидательная рамка, в которой «ты» живёт")
    if _HOWTO.search(head):
        out.append("заголовок обещает объяснить устройство (÷1.5 охвата) — механику в тело, в заголовок ставку")
    if len(head) > MAX_HEAD:
        out.append(f"заголовок {len(head)} знаков при норме {MIN_HEAD}–{MAX_HEAD} — на ходу не читается")
    # ДРОБЛЕНИЕ (23.09.2026): после строк-битов писатель ушёл в обратную крайность — 9-10 абзацев по одной
    # короткой фразе. У 62 опубликованных: 5 абзацев у 40, 6 у 15, больше 7 — у 3; обрывков короче 40
    # знаков обычно 0-1 на пост.
    if len(paras) > MAX_PARAS:
        out.append(f"слишком дробно: {len(paras)} абзацев, у опубликованных постов 5-6 (больше {MAX_PARAS} — у 3 из "
                   "62). Склей соседние короткие фразы в абзац из двух предложений")
    n = _anti_count(t)
    if n >= 2:
        out.append(f"передоз антитезы: {n} фигуры «не X — Y» на пост в 500 знаков — читается как формула. "
                   "Оставь максимум одну и не в заголовке/финале")
    return out


def headline(text: str) -> str:
    for ln in (text or "").split("\n"):
        if ln.strip():
            return ln.strip()
    return ""


def check(text: str) -> list[str]:
    """Все претензии к посту Threads для отчёта владельцу: виральность (замер 09.09) + язык v3."""
    return virality(text) + language(text)


def virality(text: str) -> list[str]:
    """Претензии по замеру виральности 09.09. Пустой список = замеру пост не противоречит.

    ⚠️ Отделено от языка v3 намеренно (23.09.2026): лидер корпуса по охвату («Биржу ограбили на 110 млн$»,
    15 159 показов) кончается антитезой «Взломали не биржу. Взломали то, что ей сказали». Замер держал её
    образцом, владелец 23.09 назвал эту конструкцию ошибкой. Решение владельца сильнее замера Threads
    (VERSIONS_AUDIT §6: он меряет интерес, не пользу) — но конфликт виден, а не спрятан.

    Порядок — от того, что стоит охвата, к тому, что стоит доверия. Формулировка каждой претензии
    называет ЦЕНУ, а не только факт: «нет ставки» без «×3.6» автор проигнорирует."""
    t = (text or "").strip()
    head = headline(t)
    stake = bool(_CONFLICT.search(head) or _MONEY.search(head))
    out: list[str] = []

    if _LINK.search(t) or _HASHTAG.search(t):
        out.append("⛔ ссылка/хештег/упоминание в тексте — режут охват в разы, в тред они не идут")

    if not stake:
        out.append("⚠️ в заголовке НЕТ ставки: ни конфликта (кто теряет), ни суммы. Замер: конфликт "
                   "даёт ×3.6 охвата, названная сумма ×2.4 — это самый сильный рычаг, что у нас есть")
    if _HOWTO.search(head):
        out.append("⚠️ заголовок обещает объяснить устройство (÷1.5) — механику даём в теле, "
                   "а в заголовок выносим ставку")
    if head and not head[0].isalnum() and head[0] not in "«\"'(":
        out.append("⚠️ эмодзи/значок в НАЧАЛЕ заголовка (÷1.6) — первая позиция читается как рубрика "
                   "канала, лента рубрик не любит")
    # Короткий заголовок сам по себе НЕ грех: «20% майнеров в убытке» — 21 знак и 3128 показов,
    # втрое выше типичного. Коротким он плох ровно тем, что в него не помещается ставка, — поэтому
    # претензия только когда ставки в нём и правда нет. Иначе линтер спорил бы с лидером корпуса,
    # а ложная претензия учит автора не верить ему целиком.
    if len(head) < MIN_HEAD and not stake:
        out.append(f"⚠️ заголовок короткий ({len(head)} знаков) И БЕЗ ставки: норма {MIN_HEAD}–{MAX_HEAD} — "
                   "в такой ставка не помещается")
    elif len(head) > MAX_HEAD:
        out.append(f"⚠️ заголовок длинный ({len(head)} знаков): норма {MIN_HEAD}–{MAX_HEAD} — "
                   "на ходу такой не читается")

    # «Вы» в заголовке — норма канала (решение 12.09, замер 340 ТГ-заголовков), и владелец 23.09 сам
    # опубликовал «Приватность будущего Вас предаст, но не сегодня». Минус замера Threads — «ты».
    if _TY.search(head):
        out.append("⚠️ «ты» в ЗАГОЛОВКЕ — заголовок ставит ставку, а не заговаривает; обращение только на «Вы»")
    if _TY.search(t):
        out.append("⚠️ «ты» в тексте (÷2.8 охвата): обращение к читателю на «Вы» — как в канале; "
                   "и фразу ПЕРЕСТРОЙ, иначе выйдет вежливое назидание, а режет охват именно оно")
    return out


def check_series(posts: list[str]) -> str:
    """Отчёт по серии: претензии по постам + сводка. Пустая строка = придраться не к чему.

    Отдельно считаем, сколько постов серии БЕЗ ставки: тред без своей ставки — главный обитатель дна
    корпуса (вторые и третьи посты серий, где ставка была только у первого)."""
    rows, no_stake = [], 0
    for i, p in enumerate(posts, 1):
        problems = check(p)
        if any("НЕТ ставки" in x for x in problems):
            no_stake += 1
        if problems:
            rows.append(f"  [{i}/{len(posts)}] " + "\n           ".join(problems))
    if not rows:
        return ""
    head = "🔎 Проверка по замеру виральности и языку v3 (остаток после круга правки — решает автор):"
    tail = (f"\n  ⚠️ Постов без своей ставки: {no_stake} из {len(posts)}. У каждого треда серии "
            "ставка своя — «зеркало к первому» и есть дно корпуса." if no_stake else "")
    return head + "\n" + "\n".join(rows) + tail
