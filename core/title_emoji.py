"""Эмодзи-якорь заголовка — ПО СМЫСЛУ повода и БЕЗ повтора последних постов.

Боль (владелец 14.08): «он часто использует эмодзи для заголовка, который был до этого — хочу,
чтобы эти эмодзи ближе подходили к заголовку и контексту и не повторялись с прошлыми». Замер по
каналу это подтверждает: на 22 последних постах 📊 стоит 4 раза, 💸 — 3, а 🌐 дважды ПОДРЯД
(#472 05.08 и #473 06.08) — то есть читатель видел один ярлык два дня кряду.

Причина ровно та же, что была у обложек (см. cover_variety): у эмодзи НЕТ ПАМЯТИ. Каждый прогон
уходит к модели с чистого листа, а в промпте лежит один и тот же списочек-палитра — модель берёт
из него первый привычный. Просьба «разнообразь» в промпте это не лечит (золотое правило 13.07:
над-инженерия промпта ломает подачу, чек живёт в КОДЕ).

Лечим тем же приёмом, что и повтор кадра обложки:
  • ПАМЯТЬ = сам канал (data/channel_posts.json обновляется в начале каждого прогона) — что реально
    стояло на последних заголовках, а не что мы просили;
  • ВЕТО — эмодзи последних WINDOW постов уходят в промпт явным «в этот раз НЕЛЬЗЯ»;
  • СМЫСЛ — memory/emoji_map.md («эмодзи — когда ставить»); в промпт идут ТОЛЬКО свободные строки,
    поэтому выбор делается по смыслу из того, что не приелось. Разнообразие даёт код, уместность —
    писатель;
  • ПРОВЕРКА — линтер сверяет готовый заголовок с тем же окном и возвращает замечание автору.

Мягкая деградация: нет выгрузки канала / нет карты смыслов → блок пустой, пост пишется как раньше.
Эмодзи — оформление, ронять из-за него пост нельзя.
"""
from __future__ import annotations

import logging
import re

from core import config, io_safe

POSTS_FILE = config.ROOT / "data" / "channel_posts.json"
MAP_FILE = config.ROOT / "memory" / "emoji_map.md"

# ОКНО ПОВТОРА — одно число на весь механизм (и промпт-вето, и замечание линтера читают отсюда).
# 5 = примерно неделя канала (5 постов/нед по контент-плану): столько читатель реально помнит в
# ленте. Больше — начнём выжигать рабочую палитру (в карте смыслов ~50 строк, но по-настоящему
# ходовых на тему поста в каждый момент 3-5).
WINDOW = 5

# Эмодзи в начале строки. Один дом на весь проект: creator_tools берёт регексы отсюда, чтобы
# «что считается эмодзи-якорем» не разъезжалось между линтером и этим модулем.
LEAD_RE = re.compile(
    r"^([©®™ℹ←-⇿⌀-➿⬀-⯿"
    r"️‍\U0001F000-\U0001FAFF\U0001F3FB-\U0001F3FF]+)")
# variation-selector / ZWJ / тон кожи — невидимые хвосты, из-за которых «⚡️» и «⚡» не сходятся
VS_RE = re.compile(r"[️‍\U0001F3FB-\U0001F3FF]")


def norm(s: str) -> str:
    """Сравнимая форма эмодзи (без невидимых хвостов)."""
    return VS_RE.sub("", s or "")


def lead_emoji(text: str) -> str:
    """Эмодзи-якорь ПЕРВОЙ непустой строки текста ('' — якоря нет)."""
    head = next((ln for ln in (text or "").split("\n") if ln.strip()), "")
    m = LEAD_RE.match(head.replace("**", "").lstrip())
    return norm(m.group(1)) if m else ""


def recent(window: int = WINDOW, path=None) -> list[str]:
    """Эмодзи-якоря последних постов КАНАЛА, свежие первыми (без дублей).

    Источник — выгрузка канала (её обновляет шаг 0 пайплайна), то есть то, что читатель видел на
    самом деле. Нет файла/битый JSON → пустой список: механизм молчит, пост пишется как раньше.
    """
    posts = io_safe.load_json(path or POSTS_FILE, [])
    if not isinstance(posts, list):
        return []
    rows = [p for p in posts if isinstance(p, dict) and (p.get("text") or "").strip()]
    rows.sort(key=lambda p: str(p.get("date") or ""), reverse=True)
    out: list[str] = []
    for p in rows:
        e = lead_emoji(p.get("text") or "")
        if e and e not in out:
            out.append(e)
        if len(out) >= window:
            break
    return out


def _map_lines(path=None) -> list[tuple[str, str]]:
    """Карта смыслов из memory/emoji_map.md: [(эмодзи, «когда ставить»), …]."""
    try:
        text = (path or MAP_FILE).read_text(encoding="utf-8")
    except OSError:
        return []
    rows: list[tuple[str, str]] = []
    for ln in text.splitlines():
        s = ln.strip()
        if not s.startswith("- "):
            continue
        m = LEAD_RE.match(s[2:].lstrip())
        if not m:
            continue
        emo = norm(m.group(1))
        sense = s[2:].lstrip()[len(m.group(1)):].lstrip(" —-").strip()
        if emo and sense:
            rows.append((emo, sense))
    return rows


def block(window: int = WINDOW, posts_path=None, map_path=None) -> str:
    """Блок для промпта: что занято последними постами и из чего выбирать по смыслу.

    Пусто (''), если нет ни карты смыслов, ни выгрузки канала — тогда промпт остаётся прежним.
    """
    used = recent(window, posts_path)
    rows = _map_lines(map_path)
    if not rows and not used:
        return ""
    free = [f"{e} — {s}" for e, s in rows if e not in used]
    parts = ["## 🏷 ЭМОДЗИ-ЯКОРЬ ЗАГОЛОВКА — по смыслу повода и БЕЗ повтора последних постов"]
    if used:
        parts.append("⛔ Эти уже стоят на ПОСЛЕДНИХ заголовках канала — в этот раз НЕ бери: "
                     + " ".join(used) + ". Читатель видит ленту подряд, и одинаковый ярлык двух "
                     "постов кряду читается как «одно и то же по кругу».")
    if free:
        parts.append("Свободные — выбери ОДИН, который ТОЧНЕЕ всего описывает суть ЭТОГО повода "
                     "(не «просто про крипту», а именно этот сюжет):\n" + "\n".join(free[:40]))
    parts.append("Эмодзи — ярлык темы, а не украшение: по нему читатель за полсекунды понимает, о "
                 "чём пост. Совсем ничего не подходит по смыслу — бери из набора "
                 "data/custom_emoji.json ближайшее, но повтор из ⛔-списка не бери.")
    return "\n".join(parts) + "\n"


def repeats_recent(head: str, window: int = WINDOW, path=None) -> str:
    """Эмодзи заголовка уже стоял в окне последних постов? Вернёт сам эмодзи или ''."""
    e = lead_emoji(head)
    if not e:
        return ""
    try:
        return e if e in recent(window, path) else ""
    except Exception:      # выгрузка/парс — данные, не логика: молчим, пост не роняем
        logging.warning("title_emoji: не смог свериться с выгрузкой канала — анти-повтор пропущен")
        return ""
