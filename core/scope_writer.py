def _vision_pick(images: list, post_body: str, subject: str, key: str):
    """Vision ВЫБИРАЕТ из кандидатов ту картинку, что СВЯЗАНА с поводом (см. _MEDIA_CRITERIA). subject —
    якорь-сущности от scope (люди/компании/тикеры). Один вызов на все картинки (дёшево).

    Возвращает (Path, ярлык кадра) или None. Ярлык («лого Solana») приходит тем же вызовом и стоит
    несколько токенов — он нужен журналу обложек для анти-повтора (core/scope_cover_log)."""
    if not images:
        return None
    try:
        topic = "\n".join(l for l in post_body.splitlines() if l.strip())[:600]
        anchor = f"Повод про: {subject}\n\n" if subject else ""
        images = [p for p in images if p.stat().st_size <= _MAX_VISION_BYTES]
        if not images:
            logging.warning("scope vision: все кандидаты > %d МБ — обложку не выбираю (уйдём текстом)",
                            _MAX_VISION_BYTES // 1_000_000)
            return None
        content: list = []
        for i, p in enumerate(images, 1):
            mt = _IMG_MEDIA_TYPE.get(p.suffix.lower(), "image/jpeg")
            b64 = base64.standard_b64encode(p.read_bytes()).decode()
            content.append({"type": "text", "text": f"Картинка {i}:"})
            content.append({"type": "image", "source": {"type": "base64", "media_type": mt, "data": b64}})
        content.append({"type": "text", "text":
            f"{anchor}Тема поста 🔭 «Под прицелом»:\n{topic}\n\nВыше {len(images)} картинок-кандидатов в "
            f"ОБЛОЖКУ. {_MEDIA_CRITERIA}{scope_cover_log.avoid_hint()}\n\nВыбери НОМЕР по ПОРЯДКУ "
            "ПРЕДПОЧТЕНИЯ выше (конкретный предмет повода > генерик; генерик против угла → 0). Если ни "
            "одна не годна — 0.\nОТВЕТ строго в формате: «НОМЕР | что на кадре (2-4 слова)», напр. "
            "«2 | лого Solana» или «0 | только ИИ-рендеры». Ярлык нужен журналу обложек, чтобы "
            "следующий пост не взял такой же кадр."})
        model = runmode.resolve(VISION_PICK_MODEL, ceiling=VISION_PICK_MODEL)
        resp = Anthropic(api_key=key).messages.create(
            model=model, max_tokens=40, messages=[{"role": "user", "content": content}])
        cost.record(model, resp.usage)
        ans = "".join(b.text for b in resp.content if b.type == "text").strip()
        # Номер берём из ПЕРВОГО поля до «|»: ярлык («лого Solana 2.0») тоже содержит цифры, и поиск
        # по всей строке однажды выберет их. Формата не держится — падаем на прежнее поведение.
        head, _, tail = ans.partition("|")
        m = re.search(r"\d+", head if head.strip() else ans)
        idx = int(m.group()) if m else 0
        if not 1 <= idx <= len(images):
            return None
        return images[idx - 1], " ".join(tail.split())[:80]
    except APIError as e:  # N-11: API-семья (429/таймаут/5xx) — транзиентно, без трейсбека
        logging.warning("scope vision-выбор: Anthropic API недоступен (%s) — уйдём текстом", type(e).__name__)
        return None
    except (OSError, ValueError) as e:  # IO/чтение картинки/декод ответа — данные, не логика
        logging.warning("scope vision-выбор: картинка/ответ битые (%s) — уйдём текстом", type(e).__name__)
        return None
    except Exception:  # неожиданное = вероятный баг: громко, но публикацию НЕ роняем (уйдём текстом)
        logging.exception("scope vision-выбор: неожиданная ошибка — картинку НЕ прицепляю")
        return None


def _vision_ok(img_path, post_body: str, key: str) -> bool:
    """Дёшево (Haiku vision): годна ли картинка источника как обложка 🔭 — релевантна теме и осмысленна
    (не логотип-заглушка/баннер/18+/битый скрин). Ошибка или сомнение → False (пост уйдёт текстом)."""
    try:
        if img_path.stat().st_size > _MAX_VISION_BYTES:
            logging.warning("scope vision: обложка %s > %d МБ — не проверяю (уйдём текстом)",
                            img_path.name, _MAX_VISION_BYTES // 1_000_000)
            return False
        media_type = _IMG_MEDIA_TYPE.get(img_path.suffix.lower(), "image/jpeg")
        b64 = base64.standard_b64encode(img_path.read_bytes()).decode()
        topic = "\n".join(l for l in post_body.splitlines() if l.strip())[:600]
        model = runmode.resolve(VISION_MODEL, ceiling=VISION_MODEL)
        resp = Anthropic(api_key=key).messages.create(
            model=model, max_tokens=10,
            messages=[{"role": "user", "content": [
                {"type": "image", "source": {"type": "base64", "media_type": media_type, "data": b64}},
                {"type": "text", "text":
                    "Это картинка-кандидат в ОБЛОЖКУ Telegram-поста. Тема поста:\n" + topic +
                    "\n\nГодится ли она как обложка — визуально релевантна теме И осмысленна "
                    "(НЕ логотип-заглушка, НЕ рекламный баннер, НЕ 18+, не битый скрин)? "
                    "Ответь СТРОГО одним словом: YES или NO. При любом сомнении — NO."},
            ]}],
        )
        cost.record(model, resp.usage)  # учёт расхода (cost-дисциплина): vision-гейт тоже считаем
        ans = "".join(b.text for b in resp.content if b.type == "text").strip().upper()
        return ans.startswith("YES")
    except APIError as e:  # N-11: API-семья (429/таймаут/5xx) — транзиентно, без трейсбека
        logging.warning("scope vision-гейт: Anthropic API недоступен (%s) — уйдём текстом", type(e).__name__)
        return False
    except (OSError, ValueError) as e:  # IO/чтение картинки/декод ответа — данные, не логика
        logging.warning("scope vision-гейт: картинка/ответ битые (%s) — уйдём текстом", type(e).__name__)
        return False
    except Exception:  # неожиданное = вероятный баг: громко, но публикацию НЕ роняем (уйдём текстом)
        logging.exception("scope vision-гейт: неожиданная ошибка — картинку НЕ прицепляю")
        return False


