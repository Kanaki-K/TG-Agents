def _enforce_scope_len(text: str, cap: int = 1150) -> str:
    """ДЕТЕРМИНИРОВАННЫЙ предохранитель длины scope (страховка на случай, если редактор не порезал сам —
    промпту не верим, урок 24.07). Если тело поста >cap символов (счёт как в линтере: UTF-16 units),
    выкидываем ЦЕЛЫЕ абзацы тела ПЕРЕД футером-ссылками, пока не влезем. Заголовок (первый абзац) и футер
    (последний непустой абзац со ссылками) НЕ трогаем; тело не опустошаем ниже «заголовок + 1 абзац +
    футер». Грубо и режет с хвоста тела (не идеально по смыслу — потому это БЭКСТОП, а не основной резчик:
    в норме режет polish). Пост НЕ блокирует — только укорачивает («пост обязан быть»)."""
    body, sep, tail = text.partition("[[SPLIT]]")

    def _n(s: str) -> int:
        return len(s.encode("utf-16-le")) // 2

    if _n(body) <= cap:
        return text
    paras = body.split("\n\n")
    while _n("\n\n".join(paras)) > cap:
        if sum(1 for p in paras if p.strip()) <= 3:
            break                                    # минимум заголовок + 1 абзац + футер — не опустошаем
        last = len(paras) - 1
        while last > 0 and not paras[last].strip():  # последний непустой = футер
            last -= 1
        if last - 1 < 1:                             # перед футером только заголовок — резать нечего
            break
        del paras[last - 1]                          # абзац прямо перед футером
    return "\n\n".join(paras) + sep + tail


def polish(api_key: str | None = None) -> str:
    """Финальный РЕДАКТОРСКИЙ проход (глаз владельца) по готовому scope-драфту: стиль/композиция по
    scope_lessons — ровно то, что владелец правил РУКАМИ в чате (счёт пунктов, сарказм-огрызки, двойное
    тире, имя токена). Отдельный проход (как редактура в браузере) надёжнее, чем надежда, что генерация
    нащупает это сама за один мах (урок 22.07: пайплайн выдал пост, а принял владелец браузерно-правленную
    версию). Факты НЕ трогает (уже сверены 2FA). Цель — пост БЕЗ ручной правки владельца."""
    cfg = config.load_agent(AGENT_NAME)
    key = api_key or config.agent_api_key(cfg)
    model = runmode.resolve(SCOPE_MODEL, ceiling=SCOPE_MODEL)
    post = verify.latest_draft() or ""
    if not post.strip():
        return post
    polished = _turn(POLISH.format(post=post.split("[[SPLIT]]")[0]), model, key, SCOPE_THINKING)
    # КОД-ГЕЙТ ДЛИНЫ (страховка). Публикуется latest_draft (диск), а не возврат функции — берём то, что
    # редактор реально сохранил, и если тело всё ещё >1000, детерминированно срезаем хвостовые абзацы и
    # ПЕРЕСОхраняем (mtime обновится → publish_now возьмёт укороченную версию). В норме не срабатывает —
    # POLISH теперь сам режет; это ловит случай, когда модель проигнорила промпт (урок 24.07).
    saved = verify.latest_draft() or polished or post
    trimmed = _enforce_scope_len(saved)
    if trimmed != saved:
        n_before = len(saved.partition("[[SPLIT]]")[0].encode("utf-16-le")) // 2
        n_after = len(trimmed.partition("[[SPLIT]]")[0].encode("utf-16-le")) // 2
        logging.warning("scope код-гейт длины: тело %d>1000 → срезал хвостовые абзацы до %d (страховка, "
                        "редактор не ужал сам)", n_before, n_after)
        creator_tools.dispatch("save_draft", {"content": trimmed, "kind": "scope"})
        return trimmed
    return polished or post


