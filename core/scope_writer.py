def _attach_media(source_urls: list, post_body: str, subject: str, key: str) -> str:
    """Из СТАТЕЙ-первоисточников: с каждой тянем кадры (шапка + тело статьи) → vision ВЫБИРАЕТ подходящий
    по смыслу → пишем в SCOPE_COVER (для publish_now). Всегда сперва ОБНУЛЯЕТ SCOPE_COVER (свежесть:
    старую обложку не тащим). Возвращает путь-строку обложки или '' (нет статей / ни одного кадра /
    vision не выбрал → текстом)."""
    creator_tools.SCOPE_COVER.parent.mkdir(parents=True, exist_ok=True)
    creator_tools.SCOPE_COVER.write_text("", encoding="utf-8")
    if not source_urls:
        return ""
    imgs = []
    for i, url in enumerate(source_urls):
        try:
            got = source_media.fetch_source_images(url, name=f"scope_{i}")
        except Exception:
            logging.exception("scope: кадры со страницы не достал (%s)", url)
            got = []
        imgs.extend(got)
        if len(imgs) >= MEDIA_POOL_CAP:
            imgs = imgs[:MEDIA_POOL_CAP]
            logging.info("scope: пул кандидатов упёрся в кап %d — остальные страницы не тяну "
                         "(дальше растёт цена vision, а отдача падает)", MEDIA_POOL_CAP)
            break
    if not imgs:
        logging.info("scope: ни на одной странице нет годного кадра (%s) — уйдём текстом", source_urls)
        return ""
    picked = _vision_pick(imgs, post_body, subject, key)
    if not picked:
        logging.info("scope: vision не выбрал подходящую по смыслу картинку (%d кандидат.) — уйдём текстом",
                     len(imgs))
        return ""
    chosen, label = picked
    creator_tools.SCOPE_COVER.write_text(str(chosen), encoding="utf-8")
    scope_cover_log.record(label, _first_line(post_body))
    logging.info("scope: обложка выбрана из %d кандидат. — %s (%s)", len(imgs), chosen, label or "без ярлыка")
    return str(chosen)


def _newest_draft_stamp() -> tuple[str, float]:
    """(имя, mtime) самого свежего драфта — маркер «scope реально сохранил новый пост»."""
    d = config.ROOT / "memory" / "drafts"
    files = sorted(d.glob("*.md"), key=lambda p: p.stat().st_mtime, reverse=True) if d.exists() else []
    return (files[0].name, files[0].stat().st_mtime) if files else ("", 0.0)


def write(theme: str = "", avoid: str = "", recommend: str = "", weak: str = "",
          verify_facts: bool = True) -> str:
    """Сгенерировать 🔭-пост (своя модель/контекст) + обязательный 2FA-фактчек с правкой. Возвращает
    финальный пост (его текст уже в драфте через save_draft; публикует владелец /schedule или пайплайн).
    recommend — повод, ОТОБРАННЫЙ гейтом темы (topic_gate: свежесть+польза, ранжирован ДО письма): ведём
    письмо по нему, чтобы writer не блуждал к слабому/протухшему (баг 22.07: брал Сейлора-13.07 при сильной
    рекомендации). Это НЕ откачённый nudge 13.07 (тот толкал на СЫРОЙ recommend без суда пользы) — здесь
    повод уже отранжирован по свежести И пользе. weak — пометка гейта, чем повод слабоват (для заострения).
    avoid — направления-повторы от анти-повтора: scope их НЕ берёт (баг 30.06 — взял x402 после поста 23.06)."""
    cfg = config.load_agent(AGENT_NAME)
    key = config.agent_api_key(cfg)
    thinking = SCOPE_THINKING  # scope пишет БЕЗ мышления (см. SCOPE_THINKING: дёшево + не режет мету обложки)
    model = runmode.resolve(SCOPE_MODEL, ceiling=SCOPE_MODEL)
    task = TASK
    if avoid:  # запрет на уже вышедшие темы — scope повод выбирает сам, но не из повторов
        task += ("\n\nАНТИ-ПОВТОР (сверено со свежей выгрузкой канала): НЕ бери эти направления — они уже "
                 f"выходили на канале: {avoid}. Возьми ДРУГОЙ свежий повод по своему гейту важности+свежести.")
    if recommend:  # повод отобран гейтом темы (свежесть+польза) — ведём письмо по нему, не блуждаем
        task += (f"\n\nПОВОД ОТОБРАН ГЕЙТОМ ТЕМЫ (отранжирован по свежести+пользе ДО тебя): «{recommend}».\n"
                 "Пиши ИМЕННО про него — §2 гейт повода можешь НЕ перепроверять на свежесть/важность (уже "
                 "сделано). НЕ переключайся на другой повод из брифа и НЕ отказывайся: пост обязан быть.")
        if weak:
            task += (f"\nГЕЙТ ОТМЕТИЛ СЛАБОСТЬ повода: {weak}. Учти — ЗАОСТРИ угол / подай через долговечный "
                     "механизм-урок, а не как свежую новость. Но пост выдай.")
    if theme:
        task += f"\n\nТЕМА ОТ ВЛАДЕЛЬЦА: {theme} — пиши по ней."
    draft_before = _newest_draft_stamp()      # снимок ДО письма — чтобы поймать отказ scope
    post = _turn(task, model, key, thinking)
    # Гейт «свежий драфт ДО трат» (аудит расходов 15.07): если scope отказался писать (нет годного
    # повода — новый драфт НЕ сохранён), то 2FA и обложка жгли бы деньги на СТАРОМ драфте из
    # архива, а run_pipeline всё равно отбросил бы результат своим гейтом свежести. Выходим сразу.
    if _newest_draft_stamp() == draft_before:
        logging.info("scope: новый драфт не появился (отказ) — пропускаю 2FA и обложку")
        return post
    media_srcs = _parse_media_srcs(post)      # URL(ы) статей из меты — ДО 2FA (фикс мету срезает)
    media_subj = _parse_media_subject(post)   # якорь-сущности повода для vision (тоже до 2FA)
    # 2FA обязателен (цифры — красная линия). Свой фактчек на Sonnet, правки — своей же моделью/контекстом.
    # 2FA внутри write() — ТОЛЬКО для интерактивного пути (бот /post). В пайплайне verify_facts=False:
    # там авторитетную ВЕБ-сверку (не доверяет брифу) + правку + перепроверку делает ре-гейт run_pipeline;
    # дублировать здесь brief-2FA = лишние ~$0.3/прогон (урок стоимости 22.07). Один проход, без замыкания.
    if verify_facts:
        try:
            verdict = verify.verify_post(verify.latest_draft(), verify.latest_brief(), api_key=key,
                                         scope=True)  # +темпоральная свежесть: новостной повод не устарел
            if verify.has_issues(verdict):
                logging.info("scope 2FA: есть замечания — правлю фактами/свежестью")
                fixed = _turn(FIX.format(post=post.split("[[SPLIT]]")[0], verdict=verdict), model, key,
                              thinking)
                post = fixed or post
        except Exception:
            logging.exception("scope 2FA не удался — пост не блокирую, отдаю как есть")
    # Обложка из ПЕРВОИСТОЧНИКА — ленивая тяга ТОЛЬКО здесь (пост уже готов, повод утверждён): og:image
    # со статей-кандидатов → vision ВЫБИРАЕТ подходящую по смыслу → SCOPE_COVER. Нет годной → текстом. Пост
    # не блокируем.
    _attach_media(media_srcs, post.split("[[SPLIT]]")[0], media_subj, key)
    # БЭКСТОП ДЛИНЫ — последний рубеж, если автор проигнорировал предупреждение линтера. Срабатывает
    # только на настоящем раздувании (мини-флагман); в норме молчит, потому что длину чинит сам автор.
    saved = verify.latest_draft() or post
    trimmed = _enforce_scope_len(saved)
    if trimmed != saved:
        creator_tools.dispatch("save_draft", {"content": trimmed, "kind": "scope"})
        logging.warning("scope бэкстоп длины: пост раздулся >%d — срезал абзацы НАД финалом (заголовок, "
                        "лид и кикер целы; автор не ужал сам)", creator_tools.SCOPE_BLOAT_CAP)
        return trimmed
    return post


def fix_facts(verdict: str, api_key: str | None = None) -> str:
    """Прицельная правка ФАКТОВ scope-драфта по вердикту 2FA — своей моделью/контекстом. Вызывается из
    пайплайна, когда РЕ-ГЕЙТ 2FA нашёл остаточную невериф./конфликтную цифру (внутренняя правка в write()
    шла против ПЕРВОГО вердикта и могла её пропустить/внести; этот вердикт называет цифру прицельно).
    Контракт FIX: конфликт → значение ИЗ БРИФА дословно; невериф. → УБРАТЬ (без выдуманной точной цифры).
    Сохраняет через save_draft. Правило 22.07: 2FA САМ ставит верное/убирает — НЕ зовёт владельца, НЕ стопает.
    Возвращает исправленный пост (пустой ответ модели → исходный драфт, чтобы не потерять пост)."""
    cfg = config.load_agent(AGENT_NAME)
    key = api_key or config.agent_api_key(cfg)
    model = runmode.resolve(SCOPE_MODEL, ceiling=SCOPE_MODEL)
    post = verify.latest_draft() or ""
    before = _newest_draft_stamp()
    fixed = _turn(FIX.format(post=post.split("[[SPLIT]]")[0], verdict=verdict), model, key, SCOPE_THINKING)
    # ВОЗВРАЩАЕМ ДРАФТ, А НЕ ЧАТ-ОТВЕТ (правка 03.08). Модель регулярно предваряет пост рассуждением
    # («Линтер поймал "крупнейшем" — это факт из S&P, оставляю»), и эта преамбула попадала в `post`,
    # который пайплайн печатает владельцу как «ГОТОВЫЙ ПОСТ». В канал при этом уходит save_draft —
    # чистый текст. Сохранила новый драфт → он и есть результат; не сохранила → отдаём что было.
    saved = verify.latest_draft()
    if saved and _newest_draft_stamp() != before:
        return saved
    return fixed or post


def _enforce_scope_len(text: str, cap: int = 0) -> str:
    """ДЕТЕРМИНИРОВАННЫЙ предохранитель длины — ПОСЛЕДНИЙ рубеж, если автор проигнорировал предупреждение
    линтера. Число берём из ЕДИНСТВЕННОГО источника (creator_tools.SCOPE_BLOAT_CAP), своей копии здесь
    больше нет: семь мест с одним числом — это как раз то, из-за чего 29.07 получился обрубок.

    ПОРОГ — РАЗДУВАНИЕ, А НЕ ЦЕЛЬ (10.08). Резчик срабатывает только там, где пост реально уехал во
    флагман (SCOPE_BLOAT_CAP), а не на каждом превышении цели формата: «длинновато» лечит автор по совету
    линтера, ампутация — только против настоящего распухания. Почему это важно, видно на посте 10.08 —
    принятый владельцем вариант (1599 всего) старый порог 1250 разрезал бы на 350 знаков.

    КИКЕР НЕПРИКОСНОВЕНЕН. Резали «абзац прямо перед футером» — а это ровно ФИНАЛ, самая дорогая строка
    формата (§4.5, владелец правит её руками 10+ сессий, из-за неё же держится судья `_finale_defects`).
    То есть предохранитель длины первым делом сносил то, что все остальные механизмы защищают. Теперь
    режем абзац НАД финалом (по §6 там середина: контр-блок/масштаб — самые необязательные кости),
    заголовок, лид, финал и футер не трогаем. Пост НЕ блокирует («пост обязан быть»)."""
    cap = cap or creator_tools.SCOPE_BLOAT_CAP
    # ПОСТ-ИНСТРУКЦИЮ НЕ РЕЖЕМ ВСЛЕПУЮ (31.07). Резчик выкидывает ЦЕЛЫЕ абзацы с хвоста — а в посте,
    # который велит читателю мигрировать кошелёк, хвост это обычно «кого касается» и «что не спасает».
    # Срезать их ради 50 знаков = отправить человека делать бесполезное действие или ничего не делать.
    # Формат тут уступает безопасности: оставляем длинным и говорим владельцу.
    if creator_tools.is_advice_post(text.partition("[[SPLIT]]")[0]):
        if len(text.partition("[[SPLIT]]")[0].encode("utf-16-le")) // 2 > cap:
            logging.warning("scope: пост-ИНСТРУКЦИЯ длиннее %d — НЕ режу (хвост такого поста = «кого "
                            "касается»/«что не спасает»). Ужимай воду вручную, факты безопасности целы", cap)
        return text
    body, sep, tail = text.partition("[[SPLIT]]")

    def _n(s: str) -> int:
        return len(s.encode("utf-16-le")) // 2

    if _n(body) <= cap:
        return text
    paras = body.split("\n\n")

    def _prev_filled(i: int) -> int:
        """Индекс ближайшего непустого абзаца на позиции i или левее (пустые = артефакты разбиения)."""
        while i > 0 and not paras[i].strip():
            i -= 1
        return i

    while _n("\n\n".join(paras)) > cap:
        # минимум = заголовок + лид + финал + футер. Тоньше не режем: без лида заголовок не оплачен,
        # без финала пост обрывается — а это и есть «обрубок», от которого уходили 29.07.
        if sum(1 for p in paras if p.strip()) <= 4:
            break
        foot = _prev_filled(len(paras) - 1)          # последний непустой = футер-ссылки
        kicker = _prev_filled(foot - 1)              # непустой перед футером = ФИНАЛ, его не трогаем
        victim = _prev_filled(kicker - 1)            # режем абзац НАД финалом (середина тела)
        if victim < 2:                               # выше только заголовок и лид — резать нечего
            break
        del paras[victim]
    return "\n\n".join(paras) + sep + tail


