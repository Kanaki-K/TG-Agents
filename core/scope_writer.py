# ── СУДЬЯ, КОТОРЫЙ САМ ПРИЗНАЁТСЯ, ЧТО КАДР ПЛОХОЙ (07.09) ──────────────────────────────────────
# Второй круг запрещает ноль — и на пуле из одного мусора это выходит боком: модель послушно называет
# номер, а в ярлыке пишет, за что этот кадр браковать. Живые ответы демо-прогона 07.09:
#   «старинная церковь, не по теме. Пояснение: кадр не относится к поводу про Binance»
