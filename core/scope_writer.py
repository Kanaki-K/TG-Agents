    cost.set_context("speech")
    text, _ = llm.reply(runmode.resolve(SPEECH_MODEL, ceiling=SPEECH_MODEL), SPEECH_READ, [], body.strip(), [],
                        lambda n, a: "", key, None, cache_system=False)
    text = (text or "").strip()
    if not text or text.lower().startswith("чисто"):
        return []
    flags = []
    for ln in text.splitlines():
        s = ln.strip().lstrip("-•*0123456789.) ").strip()
        if s.startswith(("«", '"')):
            flags.append(s)
    return flags[:8]


