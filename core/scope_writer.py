    # откатывался, обрывки оставались) — до ≤1000 всё равно дожимает _enforce_scope_len ниже; 1300 ловит
    # только настоящий разнос модели, а не нормальную дострочку мыслей.
    if _n(new_body) < _n(body) * 0.6 or _n(new_body) > 1300:
        logging.warning("scope судья мыслей: правка вне envelope (%d vs исходных %d) — оставляю исходник",
                        _n(new_body), _n(body))
        return post
    if any(mk in body for mk in _FOOTER_MARK) and not any(mk in new_body for mk in _FOOTER_MARK):
        logging.warning("scope судья мыслей: в правке потерян футер — оставляю исходник")
        return post
    final = _enforce_scope_len(new_body + sep + tail)        # держим ≤1000 (страховка)
    creator_tools.dispatch("save_draft", {"content": final, "kind": "scope"})
    logging.info("scope судья мыслей: обрывки достроены до завершённых предложений (правило 27.07)")
    return final


