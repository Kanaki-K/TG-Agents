# РУКАМИ (замер: драфт против опубликованного) — машинный текст, принятый один в один, вернул бы в
# промпт свои же паттерны, ради которых всё и затевалось.
SCOPE_ANCHORS_FILE = "memory/scope_anchors.md"
SCOPE_ANCHOR_FALLBACK = [475, 456, 453, 448]
SCOPE_ANCHOR_MAX = 4


def _anchor_ids() -> list[int]:
    ids = []
    for ln in _read(SCOPE_ANCHORS_FILE).splitlines():
        s = ln.strip()
        if s.startswith("- #"):
            num = ""
            for ch in s[3:]:
                if ch.isdigit():
                    num += ch
                else:
                    break
            if num:
                ids.append(int(num))
    return (ids or SCOPE_ANCHOR_FALLBACK)[:SCOPE_ANCHOR_MAX]


def _anchors() -> str:
    parts = []
    for pid in _anchor_ids():
        try:
            t = analytics.read_post(pid)
        except Exception:
            logging.exception("scope: эталон #%s не прочитался — пропускаю (пост важнее эталона)", pid)
            continue
