"""Лёгкое сопоставление текстов по отличительным токенам — для линкера (пост ↔ флагман).

Не «похожесть» в общем смысле, а асимметричное ПОКРЫТИЕ: какая доля токенов короткого
текста (Threads-пост / тело флагмана) встречается в длинном (флагман / пост канала).
Дистилляция переиспользует ключевые слова/числа флагмана → покрытие ловит родство даже при
переписывании. Токен = число или слово ≥4 букв (лат/кир); мелочь и пунктуация отброшены.
"""
from __future__ import annotations

import re

_TOKEN_RE = re.compile(r"[0-9]+|[a-zа-яё]{4,}", re.IGNORECASE)


def tokens(text: str) -> set[str]:
    return {t.lower() for t in _TOKEN_RE.findall(text or "")}


def coverage(short_text: str, long_text: str) -> float:
    """Доля токенов КОРОТКОГО текста, покрытых длинным (0..1). Пустой короткий → 0."""
    a = tokens(short_text)
    if not a:
        return 0.0
    return len(a & tokens(long_text)) / len(a)


def post_gist(text: str) -> str:
    """Заголовок + ЛИД поста — то, по чему тему реально можно опознать (вход анти-повтора).

    БАГ 05.08 (канал получил ДВА поста об операторах сети Arc подряд). Анти-повтор отдавал гейту ТОЛЬКО
    заголовок, а заголовок хорошего поста — это крючок, а не описание темы: «BlackRock и Visa будут
    охранять чужую монету» не содержит ни «Circle», ни «Arc», ни «операторы». Гейт честно попытался
    опознать тему по нему и ошибся вслух — в прогоне до этого написал «формулировка "охранять чужую
    монету" семантически ближе к кастоди, чем к валидации блокчейна; трактую как разное». Через прогон
    он о совпадении уже не вспомнил и выбрал ровно ту же новость.
    Лид по скелету §6 — это всегда «что произошло + дата» («5 августа Circle раскрыла первых операторов
    сети Arc»), то есть именно то, что нужно для сравнения по СУТИ, как и требует контракт гейта.
    """
    head, lead = "", ""
    for ln in (text or "").splitlines():
        s = ln.strip().lstrip("*#> ").rstrip("*").strip()
        if not s or "[[" in s or s.startswith(("🖥", "▶️", "🥸", "📱")):  # мета и футер — не текст поста
            continue
        if not head:
            head = s
            continue
        lead = s
        break
    gist = head if not lead else f"{head} — {lead}"
    return gist[:260]


def clip(text: str, limit: int) -> str:
    """Обрезка для отчётов/панелей — по границе СЛОВА, с «…» на месте обрыва.

    ИТОГ-панель прогона — единственное, что владелец читает целиком, и грубый срез в ней ВРАЛ.
    Прогон 05.08: тема вышла как «…BlackRock, Visa, D», а пометка слабости — как «⚠что уже сделано»,
    хотя в вердикте стояло «строить пост на том, что УЖЕ СДЕЛАНО»: обрезка посреди фразы вывернула
    смысл наизнанку. Режем по пробелу и помечаем обрыв, чтобы недосказанность была ВИДНА.
    """
    s = " ".join((text or "").split())
    if len(s) <= limit:
        return s
    cut = s[:limit].rsplit(" ", 1)[0]
    return (cut or s[:limit]).rstrip(" ,;:-—") + "…"
