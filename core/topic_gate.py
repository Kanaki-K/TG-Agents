# Поля контракта читаем ТОЛЬКО с начала строки (допуская markdown-обёртку `**`), а не поиском по всей
# строке: разбор кандидатов выше содержит те же слова внутри текста («…; польза: как LINK зарабатывает»),
# и поиск где угодно вытащил бы кусок разбора вместо финального поля.
def _field(name: str) -> "re.Pattern":
    return re.compile(rf"^\s*\**\s*{name}\s*:\s*(.+)", re.IGNORECASE)


_CHOICE_RE = _field("ВЫБРАН")
_WEAK_RE = _field("СЛАБО")
_REJECT_RE = _field("ОТКЛОНЕНО")
_USE_RE = _field("ПОЛЬЗА")
_DATE_RE = _field(r"ДАТА\s+ДЕЙСТВИЯ")
_DIR_RE = _field("НАПРАВЛЕНИЕ")
# Заголовок направления в брифе Скаута: «## Направление 3 [X + TG/Веб]».
_BRIEF_DIR_RE = re.compile(r"^#+\s*Направление\s+(\d+)", re.IGNORECASE | re.MULTILINE)
# ── СКЛЕЙКА = СТОП (v3, 14.09.2026) ─────────────────────────────────────────────────────────────
# Гейт выбрал «Три макро-триггера на одной неделе (Clarity Act…)» — тему, которой среди направлений
# брифа не было: он собрал её из шапки «Сигнал недели» и кусков двух направлений. Пост вышел 3 в 1, и
# владелец забраковал его целиком. Правило «один повод» в промпте проверяется так же плохо, как любое
# другое, поэтому держим его кодом двумя способами: по формулировке темы и по номеру направления.
_SPLICE_RE = re.compile(
    r"\b(?:два|две|три|четыре|пять|несколько|сразу)\s+(?:\S+\s+)?(?:событи|новост|повод|триггер)\w*"
    r"|\bна\s+одной\s+неделе\b|\bза\s+одну\s+неделю\b",
    re.IGNORECASE)


def parse_direction(verdict: str) -> list[int]:
    """Номера направлений из поля НАПРАВЛЕНИЕ (последнее вхождение). Больше одного = склейка."""
    nums: list[int] = []
    for ln in (verdict or "").splitlines():
        m = _DIR_RE.match(ln)
        if m:
            nums = [int(n) for n in re.findall(r"\d+", m.group(1))]
    return nums


def brief_directions(brief: str) -> list[int]:
    """Номера направлений, которые реально есть в брифе."""
    return sorted({int(n) for n in _BRIEF_DIR_RE.findall(brief or "")})


def splice_problem(verdict: str, brief: str) -> str:
    """Выбор склеен из нескольких событий или не привязан к одному направлению брифа? Причина или ''.

    Пустой выбор здесь не судим — это сбой гейта, его обрабатывает конвейер. Бриф без размеченных
    направлений (старый формат) номер не проверяет: fail-open, чтобы не гонять пере-выбор впустую."""
    theme, _ = parse_choice(verdict or "")
    if not theme:
        return ""
    m = _SPLICE_RE.search(theme)
    if m:
        return f"тема склеена из нескольких событий («{m.group(0)}»)"
    known = brief_directions(brief)
    if not known:
        return ""
    nums = parse_direction(verdict)
    if len(nums) != 1:
        return ("названо несколько направлений брифа сразу" if nums
                else "не назван номер направления брифа")
    if nums[0] not in known:
        return f"направления №{nums[0]} в брифе нет — тема придумана"
    return ""


def _strip_val(line: str) -> str:
    """Значение поля контракта: снимаем «ёлочки»/кавычки/markdown-болд, которыми модель любит обернуть."""
    s = line.strip().strip("*").strip()
    a, b = s.find("«"), s.rfind("»")
    if a != -1 and b > a:
        return s[a + 1:b].strip()
    return s.strip('«»"\'* ').strip()


def parse_choice(verdict: str) -> tuple[str, str]:
    """(повод, пометка-слабости) из вердикта. Берём ПОСЛЕДНЕЕ вхождение полей — финал по контракту.
    Нет строки ВЫБРАН (сбой/парсинг) → ('', ''), вызывающий делает фолбэк."""
    theme = weak = ""
    for ln in (verdict or "").splitlines():
        mc = _CHOICE_RE.match(ln)
        if mc:
            theme = _strip_val(mc.group(1))
        mw = _WEAK_RE.match(ln)
        if mw:
            w = _strip_val(mw.group(1))
            weak = "" if w.lower().startswith("нет") else w
    return theme, weak


def parse_rejected(verdict: str) -> list:
    """Отклонённые поводы с причинами — списком строк. ПОКАЗЫВАЕМ ВЛАДЕЛЬЦУ в итоговой панели: это его
    предохранитель от «выбрали самое слабое». Раньше отвалившиеся кандидаты исчезали молча, и понять,
    что система выбросила сильный повод, можно было только вычитав весь лог (провал 31.07: Glassnode и
    фонд Ашенбреннера отвалились без единой строки в отчёте)."""
    for ln in (verdict or "").splitlines():
        m = _REJECT_RE.match(ln)
        if m:
            body = m.group(1).strip().strip("*").strip()
            if body.lower().startswith(("нет", "—", "-")) and len(body) < 12:
                return []
            return _split_rejected(body)
    return []


# Разделитель поводов — «;» ПЕРЕД открывающей кавычкой следующего повода, а не любая «;».
# Баг 05.08: причина отказа сама содержала «;» («продукт "coming soon"; тезис верный, но слабее Arc»),
# и наивный split по «;» разорвал её пополам — владелец увидел в отчёте ПЯТЬ отклонённых поводов вместо
# четырёх, причём один был обрывком причины предыдущего. Контракт (_SYSTEM) велит писать поводы как
# «<повод>» — причина; «<повод>» — причина, поэтому кавычка и есть надёжная граница.
_REJ_SPLIT_RE = re.compile(r";\s*(?=[«\"])")


def _split_rejected(body: str) -> list:
    """Строку ОТКЛОНЕНО → список поводов. Нет ни одной кавычки (модель не соблюла контракт) — фолбэк
    на старое поведение: лучше показать грубо разбитым, чем одной простынёй."""
    parts = _REJ_SPLIT_RE.split(body) if "«" in body or '"' in body else body.split(";")
    return [p.strip().strip("«»\"' ").strip() for p in parts if p.strip()]


def parse_usefulness(verdict: str) -> str:
    """Строка ПОЛЬЗА — что инвестор получит. Идёт писателю как ориентир и владельцу в панель.

    ПОСЛЕДНЕЕ вхождение, как и у ВЫБРАН: финал по контракту идёт в конце вердикта. Баг 12.08.2026 —
    брали первое, и в панель владельца уехала польза ОТКЛОНЁННОГО повода. Разбор кандидатов выше
    пишется свободным текстом, и модель начинает строки с «Польза: …» внутри каждого направления
    («Польза: есть (механика AI-опциона на майнинг-инфраструктуру)» — это был Riot, а выбран FETH).
    Ограничения «читаем только с начала строки» тут мало: у разбора те же строки с начала."""
    val = ""
    for ln in (verdict or "").splitlines():
        m = _USE_RE.match(ln)
        if m:
            # НЕ _strip_val: тот вынимает текст из «ёлочек», и 14.09 панель показала «польза: тормоза» —
            # слово, взятое в кавычки внутри фразы, вместо самой пользы.
            val = m.group(1).strip().strip("*").strip()
    return val


