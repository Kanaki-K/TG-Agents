_BRIDGE_RE = re.compile(
    r"(?:крипто-?\s?мост|мост|связк\w+|привязк\w+|перенос)[^.;!?]{0,70}"
    r"(?:авторск\w+|не прописан\w*|нет в источник\w*|не пишет|притян\w+|натян\w+)"
    r"|авторск\w+\s+(?:вывод|мост|связк\w+|домысел)"
    r"|(?:в источник\w+|в отч[её]те|в брифе)[^.;!?]{0,40}(?:прямо\s+)?не (?:прописан|упомян|пишет)",
    re.IGNORECASE)


def is_forced_bridge(verdict: str) -> str:
    """Гейт сам признал, что связь повода с каналом придумана? Вернёт фрагмент признания или ''.

    Смотрим ПОЛЕ СЛАБО (и только его): это место, где гейт честно пишет, чем повод плох. В остальном
    тексте те же слова встречаются в разборе отклонённых кандидатов, и ловить их там значило бы
    отклонять повод за чужие грехи."""
    _, weak = parse_choice(verdict or "")
    m = _BRIDGE_RE.search(weak or "")
