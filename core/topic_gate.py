_CHOICE_RE = re.compile(r"ПОВОД\s*:\s*(.+)", re.IGNORECASE)
_WEAK_RE = re.compile(r"СЛАБО\s*:\s*(.+)", re.IGNORECASE)


def parse_choice(verdict: str) -> tuple[str, str]:
    """(повод, пометка-слабости) из вердикта. Повод — из последней строки «ПОВОД: «...»»; слабость — из
    строки «СЛАБО: ...» (пустая, если повод сильный). Нет строки ПОВОД (сбой/парсинг) → ('', '')."""
    theme = weak = ""
    for ln in (verdict or "").splitlines():
        mc = _CHOICE_RE.search(ln)
        if mc:  # берём ПОСЛЕДНЮЮ (финал по контракту)
            line = mc.group(1).strip()
            a, b = line.find("«"), line.rfind("»")
            theme = line[a + 1:b].strip() if a != -1 and b > a else line.strip("«»\" ").strip()
        mw = _WEAK_RE.search(ln)
        if mw:
            weak = mw.group(1).strip()
    return theme, weak


def select(candidates: str, api_key: str | None = None, model: str | None = None,
           today: str | None = None) -> tuple[str, str, str]:
    """Выбрать ЛУЧШИЙ повод из разбора кандидатов дедупа ДО генерации. ВСЕГДА возвращает повод (пост
    обязан быть — правило владельца 22.07). Возвращает (повод, пометка-слабости, вердикт-текст):
      • повод != '' — ведём writer на него; пометка-слабости != '' — велим автору вытянуть слабый повод;
      • повод == '' — гейт не смог решить (сбой/парсинг) → вызывающий делает фолбэк (recommend/сам writer).
    Конвейер НЕ роняем: любой сбой → ('', '', <причина>) (фейл-открыто)."""
    candidates = (candidates or "").strip()
    if not candidates:
        return "", "", "(нет разбора кандидатов — отбирать не из чего, writer возьмёт повод сам)"
    today = today or datetime.date.today().isoformat()
    mdl = model or runmode.resolve(GATE_MODEL, ceiling=GATE_MODEL)
    cost.set_context("topic-gate")
    user = (f"СЕГОДНЯ: {today}\n\nРАЗБОР КАНДИДАТОВ-ПОВОДОВ (повторы канала помечены 🔁):\n{candidates}\n\n"
            f"Отранжируй по свежести (событие ≤{FRESH_EVENT_DAYS}д — идеал) → пользе → не-повтору и выбери "
            "ЛУЧШИЙ. Пропускать НЕЛЬЗЯ — пост обязан быть. Вынеси ПОВОД (+ СЛАБО, если он слабоват).")
    try:
        text, _ = llm.reply(mdl, _SYSTEM, [], user, [], lambda n, a: "", api_key, None,
                            cache_system=False)
        verdict = (text or "(пусто)").strip()
        theme, weak = parse_choice(verdict)
        return theme, weak, verdict
    except Exception as e:  # noqa: BLE001 — гейт не роняет конвейер (в run_pipeline фолбэк на recommend)
        logging.exception("Гейт темы (topic_gate.select) упал")
        return "", "", f"(гейт темы не удался: {e})"
