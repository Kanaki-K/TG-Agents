# КАК РАБОТАЕТ. Из выбранной темы и из каждой строки сводки канала вынимаем ИМЕНА СОБСТВЕННЫЕ (латиница
# с заглавной + кириллические аббревиатуры: Circle, Arc, BlackRock, DTCC, BUIDL, ФРС). Совпали ДВА и
# больше — это кандидат в дубли. Дальше решает контракт: гейт САМ признал повтор и назвал, что
# изменилось (🔼) — пропускаем; промолчал — пере-выбор с запретом. Код не судит качество улучшения, он
# ловит ровно молчание: тему, совпавшую с вышедшим постом при «ПОВТОР: нет».
_REPEAT_MIN_SHARED = 2  # меньше двух общих имён — совпадение случайное (один BlackRock есть в 21 посте)
# Латиница с заглавной буквы (Circle, BlackRock, USDC) + кириллические аббревиатуры (ФРС, ЦБ, РФ).
_ENTITY_RE = re.compile(r"\b[A-Z][A-Za-z0-9]{1,}\b|\b[А-ЯЁ]{2,}\b")
# Вездесущий словарь домена: эти слова есть почти в каждом посте канала и дублем не свидетельствуют.
_ENTITY_STOP = {
    "btc", "eth", "usd", "usdt", "ai", "defi", "nft", "dca", "l1", "l2", "rwa", "tradfi", "api",
    "ceo", "cfo", "cto", "ipo", "dyor", "ath", "fud", "p2p", "kyc", "aml", "web3", "id", "it",
    "сша", "ес", "рф", "ооо", "дкп", "ввп",
}
# Строка сводки: «#472 [2026-08-05] Институции | Заголовок — суть».
_DIGEST_LINE_RE = re.compile(r"^#(\d+)\s*\[(\d{4}-\d{2}-\d{2})\]\s*(.*)$")
_REPEAT_RE = _field("ПОВТОР")
_WHATS_NEW_RE = _field(r"ЧТО\s+НОВОГО")


def _entities(text: str) -> set:
    """Имена собственные строки в нижнем регистре (Circle→circle). Вездесущий словарь домена выкинут."""
    found = {m.group(0).lower() for m in _ENTITY_RE.finditer(text or "")}
    return {e for e in found if e not in _ENTITY_STOP and len(e) > 1}


def parse_repeat(verdict: str) -> tuple[str, str]:
    """(#id поста-оригинала, что изменилось) из полей ПОВТОР / ЧТО НОВОГО. ('', '') — гейт сказал «нет».

    Берём ПОСЛЕДНЕЕ вхождение полей, как у ВЫБРАН: разбор кандидатов выше содержит те же слова, и
    финалом по контракту считается конец вердикта."""
    post_id = whats_new = ""
    for ln in (verdict or "").splitlines():
        mr = _REPEAT_RE.match(ln)
        if mr:
            v = _strip_val(mr.group(1))
            m = re.search(r"#?(\d{1,5})", v)
            post_id = "" if v.lower().startswith(("нет", "—", "-")) or not m else m.group(1)
        mn = _WHATS_NEW_RE.match(ln)
        if mn:
            v = _strip_val(mn.group(1))
            # «—», «нет», «не применимо» и огрызки короче фразы за ответ не считаем: это то же молчание.
            whats_new = "" if (v.lower().startswith(("нет", "—", "-", "не примен")) or len(v) < 12) else v
    return post_id, whats_new


def closest_published(theme: str, digest: str) -> tuple[str, str, list]:
    """Ближайший вышедший пост к теме: (#id, дата, общие имена). ('', '', []) — совпадений нет.

    Сравниваем по ИМЕНАМ СОБСТВЕННЫМ, а не по словам: заголовок поста — крючок, он событие не
    называет (урок 05.08), зато имена участников переживают любую переформулировку. «Сеть Circle
    обслуживают те же…» и «Circle запустила мейннет Arc» не имеют общих слов вовсе, но дают общие
    circle+arc."""
    want = _entities(theme)
    if len(want) < _REPEAT_MIN_SHARED:
        return "", "", []
    best: tuple[str, str, list] = ("", "", [])
    for ln in (digest or "").splitlines():
        m = _DIGEST_LINE_RE.match(ln.strip())
        if not m:
            continue
        shared = sorted(want & _entities(m.group(3)))
        if len(shared) >= _REPEAT_MIN_SHARED and len(shared) > len(best[2]):
            best = (m.group(1), m.group(2), shared)
    return best


