_CHOICE_RE = re.compile(r"ПОВОД\s*:\s*(.+)", re.IGNORECASE)
_WEAK_RE = re.compile(r"СЛАБО\s*:\s*(.+)", re.IGNORECASE)


def parse_choice(verdict: str) -> tuple[str, str]:
    """(повод, пометка-слабости) из вердикта. Повод — из последней строки «ПОВОД: «...»»; слабость — из
    строки «СЛАБО: ...» (пустая, если повод сильный). Нет строки ПОВОД (сбой/парсинг) → ('', '')."""
    theme = weak = ""
    for ln in (verdict or "").splitlines():
        mc = _CHOICE_RE.search(ln)
        if mc:  # берём ПОСЛЕДНЮЮ (финал по контракту)
            line = mc.group(1).strip()
            a, b = line.find("«"), line.rfind("»")
            theme = line[a + 1:b].strip() if a != -1 and b > a else line.strip("«»\" ").strip()
        mw = _WEAK_RE.search(ln)
        if mw:
            weak = mw.group(1).strip()
    return theme, weak


def _off_brand_block() -> str:
    """Секция «Что НЕ наше» из memory/brand.md (единый источник истины бренда — не хардкод-блэклист):
    мемкоины/шиткоин-памп, сигналы, дневной шум и пр. Гружу в гейт, чтобы он РАНЖИРОВАЛ офф-бренд темы
    вниз и не выбирал их как «лучшее из худшего» (баг 24.07: гейт был слеп к бренду → опубликовал DOGE+
    SHIB, которые владелец «не пишет вообще»). Не читается/нет секции → '' (fail-open: гейт как раньше)."""
    try:
        text = (config.ROOT / "memory" / "brand.md").read_text(encoding="utf-8")
    except Exception:
        return ""
    out, grab = [], False
    for ln in text.splitlines():
        if ln.startswith("## "):
            if grab:
                break                         # дошли до следующего заголовка — секция кончилась
            grab = "не наше" in ln.lower()
            continue
        if grab and ln.strip():
            out.append(ln.strip())
    return "\n".join(out)


def is_offbrand(verdict: str) -> bool:
    """True — ЛУЧШИЙ повод гейта это ОФФ-БРЕНД тема (из «что НЕ наше» brand.md): он-бренд поводов нет.
    Сигнал: обновить разведку, а если и после неё только офф-бренд — ПРОПУСТИТЬ прогон (владелец 24.07:
    лучше нет поста, чем мемкоины/чужой жанр). Markdown-обёртку терпим (как is_exhausted)."""
    for ln in (verdict or "").splitlines():
        s = ln.upper()
        if "ОФФ-БРЕНД" in s or "ОФФ БРЕНД" in s:
            tail = s.split("БРЕНД", 1)[1][:20]   # хвост «: ДА» / «: НЕТ**»
            return "ДА" in tail
    return False


def is_exhausted(verdict: str) -> bool:
    """True — гейт нашёл только 🚫-поток/повтор/недавнее (нет свежего 💎): сигнал пайплайну обновить
    разведку (Скаут), а не публиковать слабьё. Нет строки ИСЧЕРПАНО → False (не форсим разведку зря).
    Ловим слово ГДЕ УГОДНО в строке (модель оборачивает в **markdown**: `**ИСЧЕРПАНО: да**` — баг 22.07)."""
    for ln in (verdict or "").splitlines():
        s = ln.upper()
        if "ИСЧЕРПАНО" in s:
            tail = s.split("ИСЧЕРПАНО", 1)[1][:20]   # хвост «: ДА» / «: НЕТ**» (без «НЕТ» — нет и «ДА»)
            return "ДА" in tail
    return False


