# Поля контракта читаем ТОЛЬКО с начала строки (допуская markdown-обёртку `**`), а не поиском по всей
# строке: разбор кандидатов выше содержит те же слова внутри текста («…; польза: как LINK зарабатывает»),
# и поиск где угодно вытащил бы кусок разбора вместо финального поля.
def _field(name: str) -> "re.Pattern":
    return re.compile(rf"^\s*\**\s*{name}\s*:\s*(.+)", re.IGNORECASE)


_CHOICE_RE = _field("ВЫБРАН")
_WEAK_RE = _field("СЛАБО")
_REJECT_RE = _field("ОТКЛОНЕНО")
_USE_RE = _field("ПОЛЬЗА")
_DATE_RE = _field(r"ДАТА\s+ДЕЙСТВИЯ")


def _strip_val(line: str) -> str:
    """Значение поля контракта: снимаем «ёлочки»/кавычки/markdown-болд, которыми модель любит обернуть."""
    s = line.strip().strip("*").strip()
    a, b = s.find("«"), s.rfind("»")
    if a != -1 and b > a:
        return s[a + 1:b].strip()
    return s.strip('«»"\'* ').strip()


def parse_choice(verdict: str) -> tuple[str, str]:
    """(повод, пометка-слабости) из вердикта. Берём ПОСЛЕДНЕЕ вхождение полей — финал по контракту.
    Нет строки ВЫБРАН (сбой/парсинг) → ('', ''), вызывающий делает фолбэк."""
    theme = weak = ""
    for ln in (verdict or "").splitlines():
        mc = _CHOICE_RE.match(ln)
        if mc:
            theme = _strip_val(mc.group(1))
        mw = _WEAK_RE.match(ln)
        if mw:
            w = _strip_val(mw.group(1))
            weak = "" if w.lower().startswith("нет") else w
    return theme, weak


def parse_rejected(verdict: str) -> list:
    """Отклонённые поводы с причинами — списком строк. ПОКАЗЫВАЕМ ВЛАДЕЛЬЦУ в итоговой панели: это его
    предохранитель от «выбрали самое слабое». Раньше отвалившиеся кандидаты исчезали молча, и понять,
    что система выбросила сильный повод, можно было только вычитав весь лог (провал 31.07: Glassnode и
    фонд Ашенбреннера отвалились без единой строки в отчёте)."""
    for ln in (verdict or "").splitlines():
        m = _REJECT_RE.match(ln)
        if m:
            body = m.group(1).strip().strip("*").strip()
            if body.lower().startswith(("нет", "—", "-")) and len(body) < 12:
                return []
            return _split_rejected(body)
    return []


# Разделитель поводов — «;» ПЕРЕД открывающей кавычкой следующего повода, а не любая «;».
# Баг 05.08: причина отказа сама содержала «;» («продукт "coming soon"; тезис верный, но слабее Arc»),
# и наивный split по «;» разорвал её пополам — владелец увидел в отчёте ПЯТЬ отклонённых поводов вместо
# четырёх, причём один был обрывком причины предыдущего. Контракт (_SYSTEM) велит писать поводы как
# «<повод>» — причина; «<повод>» — причина, поэтому кавычка и есть надёжная граница.
_REJ_SPLIT_RE = re.compile(r";\s*(?=[«\"])")


def _split_rejected(body: str) -> list:
    """Строку ОТКЛОНЕНО → список поводов. Нет ни одной кавычки (модель не соблюла контракт) — фолбэк
    на старое поведение: лучше показать грубо разбитым, чем одной простынёй."""
    parts = _REJ_SPLIT_RE.split(body) if "«" in body or '"' in body else body.split(";")
    return [p.strip().strip("«»\"' ").strip() for p in parts if p.strip()]


def parse_usefulness(verdict: str) -> str:
    """Строка ПОЛЬЗА — что инвестор получит. Идёт писателю как ориентир и владельцу в панель.

    ПОСЛЕДНЕЕ вхождение, как и у ВЫБРАН: финал по контракту идёт в конце вердикта. Баг 12.08.2026 —
    брали первое, и в панель владельца уехала польза ОТКЛОНЁННОГО повода. Разбор кандидатов выше
    пишется свободным текстом, и модель начинает строки с «Польза: …» внутри каждого направления
    («Польза: есть (механика AI-опциона на майнинг-инфраструктуру)» — это был Riot, а выбран FETH).
    Ограничения «читаем только с начала строки» тут мало: у разбора те же строки с начала."""
    val = ""
    for ln in (verdict or "").splitlines():
        m = _USE_RE.match(ln)
        if m:
            val = _strip_val(m.group(1))
    return val


def parse_action_date(verdict: str) -> str:
    """Дата ДЕЙСТВИЯ (не публикации отчёта о нём) — для панели и логов. '' если не определена."""
    for ln in (verdict or "").splitlines():
        m = _DATE_RE.match(ln)
        if m:
            v = _strip_val(m.group(1))
            return "" if v.lower().startswith("не опред") else v
    return ""


def _flag(verdict: str, word: str) -> bool:
    """Булев флаг контракта («ИСЧЕРПАНО: да»). Markdown-обёртку терпим: модель пишет `**ИСЧЕРПАНО: да**`."""
    for ln in (verdict or "").splitlines():
        s = ln.upper()
        if word in s:
            return "ДА" in s.split(word, 1)[1][:20]
    return False


def is_exhausted(verdict: str) -> bool:
    """True — нашлось только слабьё (поток/повтор/старьё/уже написанное): конвейер гонит разведку заново."""
    return _flag(verdict, "ИСЧЕРПАНО")


def is_offbrand(verdict: str) -> bool:
    """True — остались только чужие жанры («что НЕ наше»): бренд сильнее правила «пост обязан быть»."""
    return _flag(verdict, "ОФФ-БРЕНД") or _flag(verdict, "ОФФ БРЕНД")


def _off_brand_block() -> str:
    """Секция «Что НЕ наше» из memory/brand.md (единый источник истины бренда — не хардкод-блэклист):
    мемкоины/шиткоин-памп, сигналы, дневной шум и пр. Не читается/нет секции → '' (fail-open)."""
    try:
        text = (config.ROOT / "memory" / "brand.md").read_text(encoding="utf-8")
    except Exception:
        return ""
    out, grab = [], False
    for ln in text.splitlines():
        if ln.startswith("## "):
            if grab:
                break
            grab = "не наше" in ln.lower()
            continue
        if grab and ln.strip():
            out.append(ln.strip())
    return "\n".join(out)


def select(brief: str, api_key: str | None = None, model: str | None = None,
           today: str | None = None, recent: list | None = None, digest: str | None = None
           ) -> tuple[str, str, str]:
    """ВЫБОР ТЕМЫ — один проход по СЫРОМУ брифу Скаута (а не по чужому пересказу).

    Возвращает (повод, пометка-слабости, вердикт-текст). Повод != '' всегда, кроме сбоя: тогда ('', '',
    причина) и вызывающий пишет по брифу сам («пост обязан быть»). Конвейер не роняем ни при каких
    ошибках — ни сети, ни парсинга, ни чтения сводки канала.
    """
    brief = (brief or "").strip()
    if not brief:
        return "", "", "(брифа нет — выбирать не из чего, писатель возьмёт повод сам)"
    today = today or datetime.date.today().isoformat()
    mdl = model or runmode.resolve(GATE_MODEL, ceiling=GATE_MODEL)
    cost.set_context("topic-select")
    if digest is None:
        try:   # сводка канала — вход анти-повтора; не прочиталась → выбираем без неё, но честно скажем
            digest = analytics.topics_digest(weeks=WINDOW_WEEKS)
        except Exception:
            logging.exception("Сводка канала для анти-повтора не прочиталась — выбираю без неё")
            digest = ""
    recent_block = ""
    if recent:
        recent_block = ("\n\n⛔ НЕДАВНО УЖЕ НАПИСАНО (лежит в отложке/черновике прошлых прогонов — эти "
                        "темы НЕ бери):\n" + "\n".join(f"  • {t}" for t in recent))
    brand = _off_brand_block()
    brand_block = ("\n\n🚫 ЧТО НЕ НАШЕ (бренд-фит):\n" + brand) if brand else ""
    user = (f"СЕГОДНЯ: {today}\n\nСЫРЫЕ ПОВОДЫ ОТ РАЗВЕДКИ:\n{brief}\n\n"
            f"УЖЕ ОПУБЛИКОВАНО НА КАНАЛЕ за последние {WINDOW_WEEKS} нед (тема/заголовок/суть, свежие "
            f"сверху, с датами):\n{digest or '(сводка канала недоступна — суди только по поводам)'}"
            f"{recent_block}{brand_block}\n\n"
            "Прогони каждый повод через четыре проверки (свежесть ДЕЙСТВИЯ → повтор → польза инвестору → "
            "тип и бренд), выбери ОДИН и вынеси контракт: ВЫБРАН / ДАТА ДЕЙСТВИЯ / ПОЛЬЗА / СЛАБО / "
            "ОТКЛОНЕНО / ИСЧЕРПАНО / ОФФ-БРЕНД.")
    try:
        text, _ = llm.reply(mdl, _SYSTEM, [], user, [], lambda n, a: "", api_key, None,
                            cache_system=False)
        verdict = (text or "(пусто)").strip()
        theme, weak = parse_choice(verdict)
        return theme, weak, verdict
    except Exception as e:  # noqa: BLE001 — выбор темы не роняет конвейер (фолбэк выше по стеку)
        logging.exception("Выбор темы (topic_gate.select) упал")
        return "", "", f"(выбор темы не удался: {e})"
