# ПОЧЕМУ МОЛЧАЛИ ВСЕ СЕТКИ. Обе прошлые проверки ищут ИМЕНА СОБСТВЕННЫЕ и ЦИФРЫ. У этой темы нет ни
# того, ни другого: она вся на русских нарицательных — «средняя цена», «себестоимость», «безубыток».
# Замер: общих имён у драфта с #482 и #501 — НОЛЬ (одно `notion` из футера), общих опорных цифр — ноль
# (83 000 против 80 000-88 000). Класс тем «механизм/понятие» был для кода невидим целиком.
# КАК ЛОВИМ. По РЕДКИМ для канала словам. Стем, встречающийся не чаще чем в 6% постов, — различающее
# понятие; частотный домен («рынок», «биткоин», «цена») отсекается сам, без ручного стоп-листа.
# Меряем ДОЛЮ понятий меньшего из двух постов: иначе длинный флагман совпадал бы со всем подряд.
# ЗАМЕР порога по 427 постам канала: медиана доли 0.12, 90-й перцентиль 0.23. Порог 0.22 даёт строку
# в панель у ~11% постов и ловит разбираемый случай (0.24 против #482, 0.18 против #501).
# ЭТО ПРЕДУПРЕЖДЕНИЕ, А НЕ ГЕЙТ: понятия законно возвращаются, и решать, вторая это серия или развитие,
# может только владелец. Окно 8 недель — понятия возвращаются медленнее новостей.
CONCEPT_WINDOW_DAYS = 56
CONCEPT_MIN_SHARE = 0.22
CONCEPT_RARE_SHARE = 0.06   # стем в ≤6% постов канала = различающее понятие
_RU_STEM_RE = re.compile(r"[а-яё]{6,}")
_LINK_RE = re.compile(r"https?://\S+|\[[^\]]*\]\([^)]*\)")


def _ru_stems(text: str) -> set:
    """Усечённые русские слова от 6 букв — грубая замена лемматизации. Ссылки и футер выкинуты."""
    body = _LINK_RE.sub(" ", (text or "").partition("[[SPLIT]]")[0])
    return {w[:7] for w in _RU_STEM_RE.findall(body.lower())}


def concept_echo(post: str, posts: list | None = None, today=None) -> str:
    """Готовый пост повторяет ПОНЯТИЕ недавнего поста канала? Строка для панели или ''.

    Не блокирует и блокировать не должен: понятия возвращаются законно. Задача — не дать владельцу
    узнать о третьем посте про один механизм уже в канале."""
    if posts is None:
        try:
            posts = analytics._load_posts()
        except Exception:
            logging.exception("Сверка понятий: выгрузка канала не прочиталась — пропускаю")
            return ""
    texts = [p for p in (posts or []) if p.get("text") and p.get("date")]
    if len(texts) < 30:               # на пустой истории редкость слова не посчитать
        return ""
    freq: dict = {}
    for p in texts:
        for s in _ru_stems(p["text"]):
            freq[s] = freq.get(s, 0) + 1
    rare_cap = len(texts) * CONCEPT_RARE_SHARE
    mine = {s for s in _ru_stems(post) if freq.get(s, 0) <= rare_cap}
    if not mine:
        return ""
    today = today or datetime.date.today()
    best = (0.0, None, None, [])
    for p in texts:
        try:
            age = (today - datetime.date.fromisoformat(p["date"][:10])).days
        except ValueError:
            continue
        if not 0 <= age <= CONCEPT_WINDOW_DAYS:
            continue
        theirs = {s for s in _ru_stems(p["text"]) if freq.get(s, 0) <= rare_cap}
        if not theirs:
            continue
        shared = mine & theirs
        share = len(shared) / min(len(mine), len(theirs))
        if share > best[0]:
            best = (share, p["id"], p["date"][:10], sorted(shared, key=lambda s: freq.get(s, 0)))
    share, pid, date, shared = best
    if share < CONCEPT_MIN_SHARE or not pid:
        return ""
    return (f"про то же понятие уже был пост #{pid} от {date} — общих понятий "
            f"{share:.0%} ({', '.join(shared[:5])})")


# ── ВТОРОЙ СУДЬЯ ПОВТОРА: ПОНЯТИЕ, А НЕ СОБЫТИЕ (16.09.2026) ────────────────────────────────────
# ПОЧЕМУ ОТДЕЛЬНЫЙ ВЫЗОВ, ХОТЯ ГЕЙТ УЖЕ СУДИТ ПОВТОР. Разбор случая 16.09: гейт ВИДЕЛ в своей сводке
# обе строки — «#482 Дно рынка определяется средней ценой покупки» и «#501 Уровень безубытка ETF
# работает как сопротивление» — и всё равно написал «ПОВТОР: нет», выбрав «кластеры себестоимости».
# Данные были, правило было, последствия не было. Ровно тот класс, что мы чиним весь день.
# Статистикой не добивается: у этой темы нет ни общих имён, ни общих цифр с прошлыми постами
# (concept_echo ловит её лишь на уровне 90-го перцентиля, то есть шумно).
# РАЗДЕЛЕНИЕ ТРУДА: модель хорошо ВИДИТ смысловое совпадение, код хорошо ПРОВЕРЯЕТ, что вердикт учли.
# Поэтому — узкий судья с ОДНИМ вопросом и машинным ответом, а конвейер обязан на него отреагировать
# пере-выбором. Не советчик: советы этот проект игнорирует с 31.07.
CONCEPT_JUDGE_MODEL = "claude-sonnet-5"
_CONCEPT_JUDGE = (
    "Ты — редактор крипто-канала, который помнит, что канал уже объяснял. Тебе дают ВЫБРАННУЮ тему "
    "следующего поста и список постов за последние недели (id · дата · заголовок · суть).\n\n"
    "ОДИН вопрос: пост по этой теме будет опираться на МЕХАНИЗМ или ПОНЯТИЕ, которое канал уже "
    "разбирал в этом списке?\n\n"
    "⚠️ РЕЧЬ НЕ О СОБЫТИИ И НЕ О СЛОВАХ. Событие может быть новым, заголовок другим, цифры другими — "
    "и всё равно это третий заход на тот же механизм. Реальный случай 16.09, из-за которого ты и "
    "появился: канал объяснил «дно определяется средней ценой покупки» (#482), потом «уровень "
    "безубытка фондов работает сопротивлением» (#501), а потом взял тему «кластеры себестоимости "
    "разъехались». Три разных повода, один и тот же механизм — средняя цена покупки как уровень. "
    "Читатель получил третью серию.\n\n"
    "Отвечай ОДНОЙ строкой, строго:\n"
    "  ПОВТОР ПОНЯТИЯ: #<id> — <какой механизм повторяется, 3-6 слов>\n"
    "  либо\n"
    "  ПОВТОР ПОНЯТИЯ: нет\n\n"
    "Сомневаешься, развитие это или третий заход, — отвечай «нет»: ложная тревога стоит владельцу "
    "лишнего круга. Но если механизм тот же, назови пост, даже когда тема выглядит свежей.")
_CONCEPT_VERDICT_RE = re.compile(r"ПОВТОР\s+ПОНЯТИЯ\s*:\s*#?(\d{1,5})\s*[—\-–]?\s*(.*)", re.IGNORECASE)


def concept_repeat(theme: str, digest: str | None = None, api_key: str | None = None,
                   model: str | None = None) -> str:
    """Выбранная тема повторяет уже разобранный МЕХАНИЗМ? Причина с #id или ''.

    Сбой/пустой ответ → '' (fail-open): судья — предохранитель, а не единственная опора."""
    theme = (theme or "").strip()
    if not theme:
        return ""
    if digest is None:
        try:
            digest = analytics.topics_digest(weeks=WINDOW_WEEKS)
        except Exception:
            logging.exception("Судья понятия: сводка канала не прочиталась — пропускаю")
            return ""
    if not (digest or "").strip():
        return ""
    try:
        mdl = model or runmode.resolve(CONCEPT_JUDGE_MODEL, ceiling=CONCEPT_JUDGE_MODEL)
        cost.set_context("concept-judge")
        text, _ = llm.reply(mdl, _CONCEPT_JUDGE, [],
                            f"ВЫБРАННАЯ ТЕМА:\n{theme}\n\nЧТО КАНАЛ УЖЕ ПУБЛИКОВАЛ:\n{digest}",
                            [], lambda n, a: "", api_key, None, cache_system=False)
    except Exception:
        logging.exception("Судья понятия упал — пропускаю (не роняем прогон)")
        return ""
    m = _CONCEPT_VERDICT_RE.search(text or "")
    if not m:
        return ""
    why = " ".join((m.group(2) or "").split())[:120]
    return f"тема повторяет механизм поста #{m.group(1)}" + (f" — {why}" if why else "")


def repeat_problem(verdict: str, digest: str | None = None) -> str:
    """Выбранная тема МОЛЧА повторяет вышедший пост? Причина с #id или ''.

    Молча = код нашёл совпадение по именам, а в контракте стоит «ПОВТОР: нет» (или поля нет вовсе).
    Гейт признал повтор И назвал, что изменилось, — это заявка на 🔼, её код не судит: пропускаем и
    отдаём писателю точку отсчёта (см. run_pipeline). Сводка не читается → '' (fail-open): анти-повтор
    не должен ронять прогон, у него есть ещё и модельный слой."""
    theme, _ = parse_choice(verdict or "")
    if not theme:
        return ""   # пустой выбор — сбой гейта, его разбирает конвейер, а не эта проверка
    said_id, whats_new = parse_repeat(verdict)
    if digest is None:
        try:
            digest = analytics.topics_digest(weeks=REPEAT_SCAN_WEEKS)
        except Exception:
            logging.exception("Сводка канала для кодовой сверки повтора не прочиталась — пропускаю")
            return ""
    if said_id and _too_soon(said_id, digest):
        return (f"сюжет поста #{said_id} разбирали меньше {COOLDOWN_DAYS} дней назад — продолжение "
                "встык читается новостной лентой; сюжет закрыт для обоих форматов, пока не отлежится")
    if said_id and whats_new:
        return ""   # заявлено 🔼 по контракту и сюжет отлежался — решение за гейтом, код не спорит
    post_id, date, shared = closest_published(theme, digest)
    if not post_id:
        return ""
    names = ", ".join(shared[:4])
    if said_id:  # повтор признан, но «что нового» не названо — по контракту это 🔁, а не 🔼
        return (f"повтор поста #{said_id} признан, но не сказано, что изменилось для читателя "
                f"(совпало: {names})")
    return f"тема совпадает с вышедшим постом #{post_id} от {date} по {names}, а в контракте «ПОВТОР: нет»"


# ── ВХОД 2 «МЕХАНИЗМ» (v3 доделан 16.09.2026) ───────────────────────────────────────────────────
# Вход 2 дала v2 (10.09) и была права: с одним входом в слабый день рождается пересказ. 14.09 его
# сняли — но не потому, что он плох, а потому, что гейт по нему ВЫДУМЫВАЛ механизм и склеивал его из
# шапки брифа («три решающих события недели»). Обе причины теперь держит код: splice_problem не даёт
# взять тему вне направлений брифа, фильтр 0 режет рутинное макро. Владелец 16.09: «я блять как
# новостник уже» — один вход превращает канал в ленту.
# ЧТО МЕНЯЕТ ВХОД 2 МЕХАНИЧЕСКИ: свежесть действия к нему не применяется (механизм живёт дольше
# новости), поэтому конвейер не гонит Скаута на второй круг за свежим поводом. Всё остальное — повтор,
# склейка, мост, деньги криптана — работает одинаково на обоих входах.
_ENTRY_RE = _field("ВХОД")


def entry_kind(verdict: str) -> str:
    """'механизм' | 'сдвиг' — какой вход выбрал гейт. Поля нет (старый вердикт) → 'сдвиг': это
    прежнее поведение, то есть свежесть продолжает действовать. Фейл-безопасно в строгую сторону."""
    val = ""
    for ln in (verdict or "").splitlines():
        m = _ENTRY_RE.match(ln)
        if m:
            val = _strip_val(m.group(1)).lower()
    return "механизм" if "механизм" in val else "сдвиг"


def is_exhausted(verdict: str) -> bool:
    """True — нашлось только слабьё (поток/повтор/старьё/уже написанное): конвейер гонит разведку заново."""
    return _flag(verdict, "ИСЧЕРПАНО")


def is_offbrand(verdict: str) -> bool:
    """True — остались только чужие жанры («что НЕ наше»): бренд сильнее правила «пост обязан быть»."""
    return _flag(verdict, "ОФФ-БРЕНД") or _flag(verdict, "ОФФ БРЕНД")


def _off_brand_block() -> str:
    """Секция «Что НЕ наше» из memory/brand.md (единый источник истины бренда — не хардкод-блэклист):
    мемкоины/шиткоин-памп, сигналы, дневной шум и пр. Не читается/нет секции → '' (fail-open)."""
    try:
        text = (config.ROOT / "memory" / "brand.md").read_text(encoding="utf-8")
    except Exception:
        return ""
    out, grab = [], False
    for ln in text.splitlines():
        if ln.startswith("## "):
            if grab:
                break
            grab = "не наше" in ln.lower()
            continue
        if grab and ln.strip():
            out.append(ln.strip())
    return "\n".join(out)


def select(brief: str, api_key: str | None = None, model: str | None = None,
           today: str | None = None, recent: list | None = None, digest: str | None = None,
           forbid: str = "", forbid_why: str = "") -> tuple[str, str, str]:
    """ВЫБОР ТЕМЫ — один проход по СЫРОМУ брифу Скаута (а не по чужому пересказу).

    Возвращает (повод, пометка-слабости, вердикт-текст). Повод != '' всегда, кроме сбоя: тогда ('', '',
    причина) и вызывающий пишет по брифу сам («пост обязан быть»). Конвейер не роняем ни при каких
    ошибках — ни сети, ни парсинга, ни чтения сводки канала.
    """
    brief = (brief or "").strip()
    if not brief:
        return "", "", "(брифа нет — выбирать не из чего, писатель возьмёт повод сам)"
    today = today or datetime.date.today().isoformat()
    mdl = model or runmode.resolve(GATE_MODEL, ceiling=GATE_MODEL)
    cost.set_context("topic-select")
    if digest is None:
        try:   # сводка канала — вход анти-повтора; не прочиталась → выбираем без неё, но честно скажем
            digest = analytics.topics_digest(weeks=WINDOW_WEEKS)
        except Exception:
            logging.exception("Сводка канала для анти-повтора не прочиталась — выбираю без неё")
            digest = ""
    recent_block = ""
    if recent:
        recent_block = ("\n\n⛔ НЕДАВНО УЖЕ НАПИСАНО (лежит в отложке/черновике прошлых прогонов — эти "
                        "темы НЕ бери):\n" + "\n".join(f"  • {t}" for t in recent))
    brand = _off_brand_block()
    brand_block = ("\n\n🚫 ЧТО НЕ НАШЕ (бренд-фит):\n" + brand) if brand else ""
    # ЗАПРЕТ НА ПЕРЕ-ВЫБОРЕ: повод уже отклонён кодом — за придуманную крипто-связку (12.09) или за
    # склейку нескольких событий (14.09). Говорим об этом прямо, иначе гейт выберет его снова — он же
    # считает его лучшим из имеющихся.
    why = forbid_why or "связь с каналом придумана автором, а не найдена в источнике"
    forbid_block = (f"\n\n⛔ ЭТОТ ПОВОД УЖЕ ОТКЛОНЁН КОДОМ ({why}) — НЕ бери его:\n  • {forbid}\n"
                    "Выбери ДРУГОЕ направление брифа — одно, реальное, с его номером в НАПРАВЛЕНИЕ. "
                    "Нет идеального — лучшее из оставшихся с честным СЛАБО.") if forbid else ""
    user = (f"СЕГОДНЯ: {today}\n\nСЫРЫЕ ПОВОДЫ ОТ РАЗВЕДКИ:\n{brief}\n\n"
            f"УЖЕ ОПУБЛИКОВАНО НА КАНАЛЕ за последние {WINDOW_WEEKS} нед (тема/заголовок/суть, свежие "
            f"сверху, с датами):\n{digest or '(сводка канала недоступна — суди только по поводам)'}"
            f"{recent_block}{brand_block}{forbid_block}\n\n"
            "Прогони каждый повод: проверка 0 (про деньги криптана, не рутинное макро) → свежесть "
            "ДЕЙСТВИЯ → повтор → польза и драма → тип и бренд. Выбери ОДНО направление и вынеси контракт: "
            "НАПРАВЛЕНИЕ / ВЫБРАН / ДАТА ДЕЙСТВИЯ / ПОВТОР / ЧТО НОВОГО / ПОЛЬЗА / СЛАБО / ОТКЛОНЕНО / "
            "ИСЧЕРПАНО / ОФФ-БРЕНД.")
    try:
        text, _ = llm.reply(mdl, _SYSTEM, [], user, [], lambda n, a: "", api_key, None,
                            cache_system=False)
        verdict = (text or "(пусто)").strip()
        theme, weak = parse_choice(verdict)
        return theme, weak, verdict
    except Exception as e:  # noqa: BLE001 — выбор темы не роняет конвейер (фолбэк выше по стеку)
        logging.exception("Выбор темы (topic_gate.select) упал")
        return "", "", f"(выбор темы не удался: {e})"
