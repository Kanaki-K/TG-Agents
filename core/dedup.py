"""Анти-повтор темы — сверка нового направления с тем, что на канале УЖЕ опубликовано.

Зачем отдельный проход (как 2FA verify): Скаут/Криейтор лезут писать на тему, толком не
сверившись, — а главное, их инструмент `find_posts` сверяется с ВЫГРУЗКОЙ канала, которая
устаревает. Самый свежий пост (вчерашний) в выгрузке может отсутствовать — тогда «не найдено»
врёт, и в канал уходит дубль. Реальный кейс: пост про x402 во вторник, выгрузка от прошлой недели —
дубль не пойман, Криейтор полез писать второй раз про то же.

Поэтому модуль делает ДВА дела (это и есть «недостающий этап завода» — актуальность данных):
  1) АКТУАЛЬНОСТЬ (`refresh_if_stale`): если выгрузка канала старше CHANNEL_FRESH_HOURS — тянет
     свежие посты (collect + enrich_topics через refresh) ДО любой сверки. Зеркало гейта свежести
     брифа Скаута, только для данных канала.
  2) СВЕРКА (`check`): независимый ДЕШЁВЫЙ вызов сверяет направления-кандидаты из брифа со сводкой
     тем всех опубликованных постов и по каждому выдаёт 🆕/🔁; рекомендует сильнейшую НЕ-повторную
     тему. Все кандидаты — повторы → СТАТУС: ПОВТОР, и конвейер не выпускает дубль.

Не пишет пост и не правит текст — только вердикт (как verify). Модель — Haiku (матчинг темы со
списком дёшев и достаточен; резолвится через runmode, в /test падает на дешёвую).
"""
from __future__ import annotations

import datetime
import functools
import random
import re
import time

from core import analytics, config, llm, runmode

BANK_FILE = config.ROOT / "memory" / "flagship_topics.md"  # пул вечных тем флагмана (список '- тема — угол')
BANK_REUSE_DAYS = 180  # тема, вышедшая меньше полугода назад, в ротацию НЕ идёт; позже сама возвращается
# Помеченная строка: «- [вышло ГГГГ-ММ-ДД] тема — угол». Дата = когда тему опубликовали (рециклинг).
_USED_RE = re.compile(r"^\[вышло\s+(\d{4}-\d{2}-\d{2})\]\s*(.+)$")


def bank_topics() -> list[str]:
    """Все АКТИВНЫЕ темы банка (строки '- …' без метки [вышло]). Совместимость/обзор."""
    return [t for (_, t, d) in _bank_lines() if d is None]


def _bank_lines() -> list:
    """Разбор банка: список (сырая_строка, текст_темы, дата_вышло|None). Только строки '- '."""
    try:
        text = BANK_FILE.read_text(encoding="utf-8")
    except Exception:
        return []
    out = []
    for ln in text.splitlines():
        s = ln.strip()
        if not s.startswith("- "):
            continue
        body = s[2:].strip()
        m = _USED_RE.match(body)
        if m:
            try:
                d = datetime.date.fromisoformat(m.group(1))
            except Exception:  # noqa: BLE001 — кривая дата: из ротации вон
                continue
            out.append((ln, m.group(2).strip(), d))
        elif body.lower().startswith("[вышло"):
            continue  # помечена [вышло] БЕЗ ISO-даты — из ротации исключена (пометь датой для авто-возврата)
        else:
            out.append((ln, body, None))
    return out


def _today():
    try:
        return datetime.date.today()
    except Exception:  # noqa: BLE001
        return None


def available_bank_themes() -> list[str]:
    """Темы, ДОСТУПНЫЕ для ротации: ещё не выходившие (приоритет) / вышедшие >BANK_REUSE_DAYS назад,
    И НЕ из паузного домена (стейбл/x402/платёж… забанено — флагман их не берёт). Из них пайплайн
    выбирает по актуальности; пусто — банк пуст / всё в окне / всё на паузе."""
    lines = _bank_lines()
    if not lines:
        return []
    never = [t for (_, t, d) in lines if d is None]
    if never:
        pool = never
    else:
        today = _today()
        aged = [t for (_, t, d) in lines if d and today and (today - d).days >= BANK_REUSE_DAYS]
        if aged:
            pool = aged
        else:
            used = sorted(((t, d) for (_, t, d) in lines if d), key=lambda x: x[1])  # самая старая первой
            pool = [t for t, _ in used] or [lines[0][1]]
    return [t for t in pool if not _hits_paused(t)]  # паузный домен вон из ротации флагмана


def pick_bank_theme() -> str:
    """ОДНА тема по ротации — СЛУЧАЙНАЯ из доступных. Детерминированный фолбэк, если актуальный
    выбор (сентимент+бриф) в пайплайне недоступен/упал."""
    pool = available_bank_themes()
    return random.choice(pool) if pool else ""


def mark_theme_used(theme: str, date_iso: str = "") -> bool:
    """Пометить тему как [вышло ДАТА] в банке (рециклинг: скрыть из ротации на BANK_REUSE_DAYS).
    Зовётся ТОЛЬКО при реальной публикации (не в draft/test). True — записано."""
    theme = (theme or "").strip()
    if not theme:
        return False
    if not date_iso:
        t = _today()
        date_iso = t.isoformat() if t else ""
    if not date_iso:
        return False
    try:
        lines = BANK_FILE.read_text(encoding="utf-8").splitlines()
    except Exception:
        return False
    for i, ln in enumerate(lines):
        s = ln.strip()
        if s.startswith("- ") and s[2:].strip() == theme:  # активная строка ровно этой темы
            indent = ln[:len(ln) - len(ln.lstrip())]
            lines[i] = f"{indent}- [вышло {date_iso}] {theme}"
            try:
                BANK_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
                return True
            except Exception:
                return False
    return False

CHANNEL_FRESH_HOURS = 12  # выгрузка свежее этого — повторную тягу не запускаем (бережём время/токены)

# ДОМЕНЫ НА ПАУЗЕ — детерминированный стоп (использует ТОЛЬКО scope — у флагмана своё зрение).
# АВТО-ПАУЗЫ ПО ТЕМАМ: scope новостной, актуальность важна, но одно и то же каждую неделю — спам.
# PAUSE_WEEKS — окно: вышедшая тема авто-снимается через 3 недели (короче флагманского банка ~6 мес).
#  • PAUSED_AUTO (слово, "ГГГГ-ММ-ДД") — недавно выходило; авто-снятие через PAUSE_WEEKS. Дата = когда
#    засветилось (обычно дата поста). x402 (пост #439 от 23.06) отвяжется сам ~14.07, руками не чистить.
#  • PAUSED_STICKY — ручной оверрайд «долгая домен-усталость», не истекает, снимается руками.
PAUSE_WEEKS = 3

PAUSED_AUTO: list[tuple[str, str]] = [
    # Пусто. Формат для будущего: ("слово", "ГГГГ-ММ-ДД") — засветившийся домен авто-снимется через
    # PAUSE_WEEKS. Пример: ("смена рук", "2026-06-06"). Устаревшие записи 06.06 (#434) убраны — истекли.
]
PAUSED_STICKY: list[str] = [
    # ПУСТО осознанно (13.07.2026). Блэклист доменов (стейбл/x402/saylor/mica…) был костылём под
    # «слепого» Скаута: он не видел, что канал уже писал. Первопричина отпала —
    #  1) агенты видят покрытие канала (topics_digest) и сами судят повтор + домен-усталость;
    #  2) капремонт Скаута 13.07 (широкие источники + watermark + Haiku-воронка) снизил повторный
    #     приток затёртых доменов — писать есть из чего КРОМЕ них.
    # Хронология подтвердила: ты сам обнулял этот блэклист 07.07 (a31bf33) как «костыль под слепого
    # Скаута»; вернулся он только с откатом scope (d4615a5), не отдельным решением.
    # Механизм _hits_paused ОСТАВЛЕН как ручное вето: домен снова задолбал → впиши слово сюда одной
    # строкой (напр. "x402"), или в PAUSED_AUTO с датой для авто-снятия через 3 недели.
]


def active_paused() -> list[str]:
    """Активные паузные слова: sticky (ручные, вечные) + auto (не истёкшие за PAUSE_WEEKS)."""
    out = list(PAUSED_STICKY)
    try:
        today = datetime.date.today()
    except Exception:  # noqa: BLE001 — часы недоступны: паузим всё, безопаснее
        return out + [w for w, _ in PAUSED_AUTO]
    for word, added in PAUSED_AUTO:
        try:
            fresh = (today - datetime.date.fromisoformat(added)).days < PAUSE_WEEKS * 7
        except Exception:  # noqa: BLE001 — кривая дата: считаем активной
            fresh = True
        if fresh:
            out.append(word)
    return out


def _hits_paused(text: str) -> str:
    """Первое АКТИВНОЕ паузное слово, встреченное в тексте как ОТДЕЛЬНОЕ слово / НАЧАЛО слова
    (пусто — чисто). ГРАНИЦА СЛОВА, не голый substring: иначе «мика» (для MiCA) ловит «эконоМИКА /
    динаМИКА / полеМИКА» → ложный стоп на любом макро-посте = впустую потраченная генерация. Ведущая
    \\b оставляет стемминг (стейбл→стейблкоин/стейблы, платёж→платёжный), но режет совпадения В СЕРЕДИНЕ."""
    low = (text or "").lower()
    return next((d for d in active_paused() if _paused_re(d).search(low)), "")


@functools.lru_cache(maxsize=256)
def _paused_re(domain: str):
    """Скомпилированный «граница-слова» regex домена, кэш на процесс (N-15: не перекомпилировать
    на каждый вызов _hits_paused — домены на паузе меняются редко, шаблон детерминирован)."""
    return re.compile(r"\b" + re.escape(domain))


def paused_note() -> str:
    """Строка-запрет по активным доменам на паузе (пусто, если активных нет)."""
    active = active_paused()
    if not active:
        return ""
    return ("домены НА ПАУЗЕ (перегреты / недавно выходили — НЕ бери совсем, даже под «новым углом»): "
            + ", ".join(active))

