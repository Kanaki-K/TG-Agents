        f"{_read(fmt['manual'])}\n\n"
        f"## 🎯 ЭТАЛОНЫ ГОЛОСА — пиши В ЭТОМ голосе ({fmt['anchors']})\n"
        "Полный текст принятых владельцем постов. Голос и приём переноси ОТСЮДА (как флагман с "
