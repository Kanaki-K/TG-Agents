_LESSON_STOP = set("это что как уже его её для так но или из от до при над под чтобы перед "
                   "если когда чем тоже надо нужно есть быть всё все вот этот эта эти том".split())


def _lesson_keywords(s: str) -> set:
    """Значимые слова урока (для сверки на дубль): без хвоста-эвиденса, стоп-слов и коротышей."""
    s = re.sub(r"—\s*_из правки.*$|—\s*_.*_$", "", s.lower())   # отрезать эвиденс/курсив-хвост
    s = re.sub(r"^\-?\s*\(\d{4}-\d\d-\d\d\)\s*", "", s)          # отрезать дату-префикс строки
    return {w for w in re.findall(r"[а-яёa-z0-9]{4,}", s) if w not in _LESSON_STOP}


# ── Сверка уроков ПО СУТИ, а не по буквам (владелец 17.08: «нужно по сути сравнивать») ────────────
# ЗАМЕР 17.08 показал, что страж дублей не работал: максимальная похожесть СРЕДИ ВСЕХ пар уроков —
# 0.26 у scope (48 шт) и 0.40 у флагмана (35 шт) при пороге 0.6. То есть он не был близок к
# срабатыванию ни разу и при нынешней длине уроков сработать не мог.
# ПОЧЕМУ. Урок устроен так: ПРАВИЛО одной строкой → разбор случая (что написала машина, что сделал
# владелец, цитаты) → иногда «ПРАВИЛО: …» → провенанс. Доля считалась от ВСЕГО текста, а разбор
# случая — это 2/3 слов, и он у каждого урока свой: тот же самый закон, выведенный на другом посте,
# по словам почти не пересекается. Считали, по сути, СОВПАДЕНИЕ ИСТОРИЙ, а не совпадение правил.
# КАК ТЕПЕРЬ. Сравниваем СУТЬ — формулировку закона: первую фразу (в этих уроках она и есть правило
# одной строкой: «ЛИД — ОДНА ЦИФРА…», «СИЛЬНОЕ ТЕЛО → СИЛЬНЫЙ ФИНАЛ») плюс все клаузы «ПРАВИЛО: …».
# Разбор случая, цитаты и числа выбрасываем. Нормируем на МЕНЬШЕЕ ядро: короткое правило, повторённое
# внутри длинного урока, обязано ловиться — при нормировке на новый урок оно тонуло.
# ⚠️ ЦИТАТЫ РЕЖЕМ ТОЛЬКО В ХВОСТЕ, НЕ В ПЕРВОЙ ФРАЗЕ: в заголовке урока кавычки часто и есть предмет
# правила («НЕ A, А Б», «Это не X. Это Y», СЛОВО «раскатили» → «запустили») — вырезав их там, мы бы
# сравнивали пустые огрызки.
# ПОРОГ выбран замером по истории, а не на глаз: при (доля ≥0.20 И ≥5 общих основ) страж сработал бы
# на 7 уроках scope из 48 (15%) и ни на одном флагманском — то есть окликает ближайшего родственника,
# а не шумит на каждом. Ближайшие пары, которые он находит, реальные: «ОСЬ scope = НОВОСТЬ + ТВОЙ
# ЕДЖ» (30.06) ↔ «ГОЛАЯ НОВОСТЬ + САМОПОЗДРАВЛЕНИЕ = провал оси» (09.07) — один и тот же закон,
# записанный дважды; «ОТРИЦАНИЕ БЕЗ УТВЕРЖДЕНИЯ» (05.08) ↔ «НЕ A, А Б» (17.08) — та самая пара,
# различие которой пришлось проговаривать руками. Старая буквальная сверка ОСТАЁТСЯ вторым видом:
# она ловит перезапись слово в слово, чего сверка по сути не гарантирует.
_LESSON_NARRATIVE = set("машина машины машине владелец владельца владельцу урок урока уроке правило "
                        "пост поста посте постом текст текста такой такая такие ещё уже нет там тут "
                        "где кто раз два три".split())
_RULE_CLAUSE_RE = re.compile(r"(?:ПРАВИЛО|Правило)\s*:\s*(.*?)(?=\s[—–-]\s_|$)", re.DOTALL)
_LESSON_QUOTES_RE = re.compile(r"«[^»]*»|\"[^\"]*\"")
LESSON_CORE_MIN_SHARE = 0.20    # доля общих слов ядра (от МЕНЬШЕГО из двух)
LESSON_CORE_MIN_WORDS = 5       # …и столько общих слов минимум: на коротких ядрах доля шумит


def _lesson_core(s: str) -> str:
    """СУТЬ урока — формулировка закона без разбора случая: первая фраза + клаузы «ПРАВИЛО: …».
    Структуры нет (урок в одну фразу) → берём весь текст. Числа и цитаты хвоста выкидываем."""
    s = _LESSON_EVIDENCE_RE.sub("", (s or "").strip())
    s = re.sub(r"^-?\s*\(\d{4}-\d\d-\d\d\)\s*", "", s)
    s = re.sub(r"^[\s⭐⚠️🔧📋✅❌•]+", "", s)
    first = re.split(r"(?<=[.!?])\s+", s, maxsplit=1)[0]
    rules = " ".join(m.group(1) for m in _RULE_CLAUSE_RE.finditer(s))
    core = (first + " " + _LESSON_QUOTES_RE.sub(" ", rules)).strip()
    if len(re.sub(r"[^а-яёa-z]", "", core, flags=re.IGNORECASE)) < 40:
        core = _LESSON_QUOTES_RE.sub(" ", s)     # правило одной фразой — сравниваем как есть
    return re.sub(r"\d+[.,]?\d*", " ", core.lower())


def _lesson_core_words(s: str) -> set:
    """Значимые слова СУТИ: без стоп-слов, без слов-рассказчиков, обрезанные до основы.

    ОБРЕЗКА ДО 6 БУКВ — грубая замена морфологии: «утверждает» и «утверждать», «спрашивает» и
    «спрашивать», «заголовок» и «заголовки» — для сверки правил это одно слово, а точное сравнение
    считало их разными. Именно это и мешало ловить «то же правило, сказанное иначе»: пересказ закона
    почти всегда меняет форму глагола. Шесть букв, а не пять: на пяти начинают слипаться разные
    корни («правило»/«правка» → «прави»), замер по истории — срабатывание 23% против 15%."""
    return {w[:6] for w in re.findall(r"[а-яёa-z]{3,}", _lesson_core(s))
            if w not in _LESSON_STOP and w not in _LESSON_NARRATIVE}


def _lesson_duplicate(new: str, lessons_path: Path = LESSONS) -> tuple[str, str] | None:
    """Урок уже записан — буквально или ПО СУТИ? Вернёт (строка урока, чем похож) или None.

    Два вида сверки, срабатывает любой:
      1) буквальный — доля общих значимых слов ко ВСЕМУ новому уроку ≥0.6 (перезапись слово в слово);
      2) по сути — доля общих слов ЯДРА (правило без разбора случая) от меньшего ≥0.20 и ≥5 слов.
    lessons_path — против какого файла сверяем (флагман post_lessons / scope_lessons)."""
    if not lessons_path.exists():
        return None
    nw, nc = _lesson_keywords(new), _lesson_core_words(new)
    if len(nw) < 3:
        return None
    best = None
    for ln in lessons_path.read_text(encoding="utf-8").splitlines():
        if not ln.lstrip().startswith("- ("):
            continue
        ow = _lesson_keywords(ln)
        if ow and len(nw & ow) / len(nw) >= 0.6:
            return ln.strip(), "почти дословный повтор"
        oc = _lesson_core_words(ln)
        if not (nc and oc):
            continue
        shared = nc & oc
        share = len(shared) / min(len(nc), len(oc))
        if share >= LESSON_CORE_MIN_SHARE and len(shared) >= LESSON_CORE_MIN_WORDS:
            if best is None or share > best[0]:
                best = (share, ln.strip(), sorted(shared)[:8])
    if best:
        return best[1], "то же ПО СУТИ (общее в формулировке правила: " + ", ".join(best[2]) + ")"
    return None


# ── Уроки в контекст без «жира» (анти-обрастание — влияет на цену КАЖДОГО поста) ──────────────────
# Файлы уроков грузятся в контекст на КАЖДЫЙ пост и только растут (append-only). Провенанс-хвост
# «— _из правки: …_» — это СОРСИНГ, не правило (сам дедуп уроков его отрезает, см. _lesson_keywords).
# Стрип при ЗАГРУЗКЕ (файл на диске НЕ трогаем — там эвиденс для человека) убирает ~20-25% токенов
# уроков АВТОМАТИЧЕСКИ, на всех текущих И будущих уроках — без ручных аудитов. Модель видит ПРАВИЛО
# и все ИНЛАЙН-примеры (❌/✅/«…» в теле остаются), уходит только хвост-провенанс. Провабли без потери
# качества: срезается ровно то, что система и так не считает правилом.
STRIP_LESSON_EVIDENCE = True   # регресс подачи? → False: хвосты вернутся мгновенно, файл не тронут
# Якорим на КОНКРЕТНЫЕ провенанс-префиксы (из правки/разбора/поста · правка владельца · владелец…) —
# НЕ на любой `— _italic_` и НЕ на широкое «из ». Иначе будущий урок, чьё ПРАВИЛО кончается курсивом
# («— _из этого правила исключений нет_»), был бы срезан как «хвост» → потеря правила (нит ревью 20.07).
# Проверено: ловит все текущие хвосты (36/18), контрпример «из этого…» — не трогает.
# ⚠️ ЗАМЕР 17.08: у флагмана срезалось 35/35 хвостов (−22.4% контекста), а у scope только 40/48
# (−6.6%). Восемь хвостов писались другими словами — «похвала владельца», «уточнение владельца»,
# «разбор Coldcard-поста», «редактура владельца», «финальная редактура владельца» — и белый список
# их не знал. Это ровно тот жир, ради которого стрип и делали: сорсинг, который система сама не
# считает правилом (дедуп его отрезает), но платит за него каждый прогон. Добавлены основы слов
# (правк/разбор/редактур/похвал/уточнени) — «из» стало необязательным, потому что половина хвостов
# начинается прямо с существительного. Принцип не менялся: якорим на КОНКРЕТНЫЕ провенанс-слова, а
# не на любой `— _italic_`. После правки: scope 48/48, флагман 35/35, ложняков 0 на контрпримерах
# «— _из этого правила исключений нет_» / «— _и точка_» / курсив ВНУТРИ правила.
_LESSON_EVIDENCE_RE = re.compile(
    r"\s*[—–-]\s*_(?:из (?:правки|разбора|поста)|правк\w*|разбор\w*|редактур\w*|похвал\w*|"
    r"уточнени\w*|финальная редактура|владелец).+_\s*$")
# Lifecycle: урок, чьё правило ПРОВАБЛИ живёт в другом доме — линтер (детерминированно ПРАВИТ) или
# мануал (и так в контексте) — переносится ПОД этот маркер. Загрузчик секцию «Выпущено» в промпт НЕ
# подставляет (правило и так работает), но текст остаётся в файле → обратимо и видно историю. Так
# файл держит размер БЕЗ регулярных аудитов и БЕЗ хард-делита. NB: линтер-правило, которое лишь ФЛАЖИТ
# (суперлативы/стаккато/два-предложения-заголовка), НЕ выпускать — промпт ещё ПРЕДОТВРАЩАЕТ его.
GRADUATED_MARK = "## 📦 Выпущено"
LESSONS_WARN_CHARS = 40_000    # активные уроки крупнее — сигнал «пора выпускать/консолидировать»


def load_lessons_for_context(path: Path) -> str:
    """Текст уроков ДЛЯ ПРОМПТА: активные правила (без секции «Выпущено») и без провенанс-хвостов
    (при STRIP_LESSON_EVIDENCE). Файл на диске НЕ меняется. Логирует размер + WARN при обрастании —
    телеметрия против незаметного роста цены."""
    raw = path.read_text(encoding="utf-8") if path.exists() else ""
    if not raw.strip():
        return ""
    raw = raw.split(GRADUATED_MARK)[0]   # выпущенные уроки в контекст не идут (правило в линтере/мануале)
    if STRIP_LESSON_EVIDENCE:
        raw = "\n".join(
            _LESSON_EVIDENCE_RE.sub("", ln) if ln.lstrip().startswith("- (") else ln
            for ln in raw.split("\n"))
    n = len(raw)
    logging.info("уроки %s → контекст: %d симв, ~%d уроков", path.name, n, raw.count("\n- ("))
    if n > LESSONS_WARN_CHARS:
        logging.warning("уроки %s РАЗДУЛИСЬ до %d симв (>%d): пора выпустить устаревшее под '%s' или "
                        "консолидировать — жир бьёт по цене каждого поста", path.name, n,
                        LESSONS_WARN_CHARS, GRADUATED_MARK)
    return raw


def _covered_by_manual(new: str, manual_rel: str = "memory/content_manual.md") -> str | None:
    """Правило нового урока УЖЕ покрыто мануалом (он и так в контексте)? Тогда урок = дубль канона,
    и он платится в контексте ДВАЖДЫ каждый пост. Вернёт строку мануала или None.

    Две сверки, как у стража дублей: буквальная (доля общих слов ко всему уроку ≥0.6) и ПО СУТИ
    (ядро правила, основы слов, доля от меньшего). Замер 17.08 по живому файлу: буквальная не
    находила НИЧЕГО, сверка по сути нашла 5 уроков scope из 48, которые дословно повторяют мануал —
    напр. урок «ОСЬ scope = НОВОСТЬ + ТВОЙ ЕДЖ» против заголовка мануала «⭐ ГЛАВНАЯ ОСЬ: scope =
    НОВОСТЬ + ТВОЙ ЕДЖ». Это правила, когда-то поднятые в мануал и не убранные из уроков."""
    nw, nc = _lesson_keywords(new), _lesson_core_words(new)
    if len(nw) < 4:
        return None
    p = config.ROOT / manual_rel
    if not p.exists():
        return None
    for ln in p.read_text(encoding="utf-8").splitlines():
        s = ln.strip()
        if len(s) < 40:
            continue
        ow = {w for w in re.findall(r"[а-яёa-z0-9]{4,}", s.lower()) if w not in _LESSON_STOP}
        if ow and len(nw & ow) / len(nw) >= 0.6:
            return s[:120]
        oc = _lesson_core_words(s)
        if nc and oc:
            shared = nc & oc
            if (len(shared) >= LESSON_CORE_MIN_WORDS
                    and len(shared) / min(len(nc), len(oc)) >= LESSON_CORE_MIN_SHARE):
                return s[:120]
    return None


