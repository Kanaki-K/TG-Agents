def _title_two_sentences(head: str) -> bool:
    """Заголовок из ДВУХ предложений? Владелец (20.07, СТРОГО): ровно ОДНО — утверждение ЛИБО
    вопрос, НЕ «утв. утв.» и НЕ «факт. вопрос?». Двоеточие/тире = ОДНО предложение (тег-тему давай
    так). Тег-рубрику «🌐 LINK | …» и финальный знак не считаем; точка после инициала из одной буквы
    («T. Rowe», «U.S.») — не конец предложения (ложняк 17.07). Общий для scope и флагмана."""
    hl = head.replace("**", "").strip()
    hl = hl.split("| ", 1)[-1].strip().rstrip("?!.… ")
    hl = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", hl)   # инициал/сокращение из 1 буквы — не точка-конец
    return bool(re.search(r"[.!?]\s+\S", hl))       # внутренний конец предложения + продолжение = ДВА


def _title_dash_double(head: str) -> bool:
    """Заголовок = ДВОЙНАЯ мысль через тире («Бигтехи потеряли 800$ - биткоин не дрогнул»)? Владелец
    27.07 СТРОГО: заголовок — ОДНА мысль, «ни через тире нихуя». Тег-тему (короткий термин перед тире:
    «RWA - рельсы») НЕ трогаем — там слева 1-2 слова. Двойник = слева УЖЕ полный крючок (≥3 слов-токенов,
    т.е. подлежащее+действие или цифра-факт), а справа — вторая самостоятельная мысль. `_title_two_sentences`
    ловит двойник ТОЛЬКО через точку/!/?; тире оно намеренно считает одним предложением (для тег-тем) —
    эта функция закрывает дырку. Общий счёт слов, не грамматика (детерминированно, промпту не верим)."""
    hl = head.replace("**", "").strip().split("| ", 1)[-1].strip()   # тег-рубрику «🌐 LINK | …» не считаем
    m = re.search(r"\s[-–—]\s", hl)
    if not m:
        return False
    left = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", hl[:m.start()])        # инициал «T.»/«U.» — не слово (ложняк 17.07)
    return len(re.findall(r"\w+", left, re.UNICODE)) >= 3             # слева уже полный крючок → двойник


# ФРОНТАЛЬНОЕ ПРИДАТОЧНОЕ — ТРЕТЬЯ форма двойного заголовка, через ЗАПЯТУЮ (владелец 14.08).
# Реальный случай: «🌐 Пока биток в минусе, к нему строят мост для азиатских капиталов». Формально
# ОДНО предложение — ни точки, ни тире, поэтому оба старых детектора его пропустили. По сути же это
# опять ДВЕ мысли: сначала читателя держат в зависимой оговорке («пока», «когда», «если»), и только
# после запятой начинается то, ради чего пост. Владелец переписал в «📈 Мост в крипту для азиатских
# капиталов» — то есть выбросил ПЕРВУЮ половину и оставил ВТОРУЮ, главную. Это важно: старый резчик
# `_title_keep_first` в таком заголовке оставил бы «Пока биток в минусе» — чистый мусор.
# ЗАМЕР (14.08) на 291 заголовке банка + 60 последних постах канала: без гарда детектор дал ОДНО
# ложное — «❓ Когда фиксировать, а когда держать до упора?» (реальный флагман #286). Это не двойник,
# а ОДИН вопрос с парным «когда… а когда…», и порезать его — ровно тот вред, что уже был 07.08:
# ложная претензия учит автора не верить линтеру ЦЕЛИКОМ, вместе с верными. Поэтому заголовок-ВОПРОС
# (кончается на «?») не трогаем вовсе — по канону вопрос и есть одна законная мысль. С этим гардом
# ложных 0 из 351. Обычную запятую тоже НЕ трогаем: «Сеть Circle обслуживают те же, кто в неё вложил
# деньги», «Кофейня, которая покупает биткоин» — одна мысль с придаточным ВНУТРИ.
_TITLE_FRONT_SUB = re.compile(
    r"^(пока|когда|если|хотя|раз|поскольку|пусть|едва|стоило|после того как|по мере того как|"
    r"в то время как|тогда как|несмотря на то что)\b[^,]{3,70},\s*\S", re.IGNORECASE)


def _title_strip_lead(inner: str) -> tuple[str, str]:
    """Разделить заголовок на (эмодзи-якорь+пробелы, сам текст) — якорь при правках бережём."""
    m = re.match(r"^([^\w]*)(.*)$", inner, re.DOTALL)
    return (m.group(1), m.group(2)) if m else ("", inner)


def _title_fronted_clause(head: str) -> bool:
    """Заголовок начинается с зависимой оговорки («Пока X, Y»)? Главная мысль тогда ВТОРАЯ.

    Заголовок-ВОПРОС целиком не трогаем: «Когда фиксировать, а когда держать до упора?» — это один
    вопрос, а не двойник (см. комментарий к _TITLE_FRONT_SUB: единственный ложняк замера).
    """
    hl = head.replace("**", "").strip().split("| ", 1)[-1].strip()
    if hl.endswith("?"):
        return False
    return bool(_TITLE_FRONT_SUB.match(_title_strip_lead(hl)[1].strip()))


# АНТИТЕЗА В ЗАГОЛОВКЕ — ЧЕТВЁРТАЯ форма двойной мысли (владелец 17.08). «🌐 Stripe купил не модель,
# а рубильник для ИИ-агентов» → владелец: «🌐 Stripe купил рубильник для ИИ-агентов». Формально это одно
# предложение без тире и без фронтального придаточного, поэтому три прежних детектора его пропускают, а
# по сути в крючке снова ДВЕ мысли: сначала опровергают то, чего никто не утверждал, и только потом
# говорят по делу. В том же посте фигура стояла ещё дважды (в теле и в финале) — её ловит счётчик
# антитезы выше; здесь случай отдельный, потому что в заголовке терпимость нулевая: заголовок = один
# крючок (§4 мануала, урок 27.07 «ни через тире нихуя»).
# ПОЧЕМУ WARN, А НЕ РЕЗ. Остальные двойники режутся кодом (`_title_keep_first`) — там первая половина
# самодостаточна. Здесь наоборот: «Stripe купил не модель» — мусор, оставлять надо ВТОРУЮ половину, и
# только если X действительно выдуман. «Не ФРС, а Минфин двигает ликвидность» — законная антитеза:
# опровергается то, что читатель реально думает. Отличить чучело от настоящего спора детерминированно
# нельзя, а ложный рез заголовка — ровно тот вред, из-за которого 07.08 автор перестаёт верить линтеру
# целиком. Поэтому решает автор, а код показывает КУДА смотреть и даёт тест.
_TITLE_ANTI = re.compile(r"\bне\s+[^,.!?\n]{1,45},\s*а\s+|,\s*а\s+не\s+", re.IGNORECASE)


# КЛИПНУТАЯ АНТИТЕЗА «X, не Y» ПОСРЕДИ ФРАЗЫ (19.08) — подробности у места вызова в `_lint`.
# `_VERBISH` отсекает глагол/причастие/деепричастие после «не» («…, не договорились, когда…» — это
# обычное отрицание, а не половина антитезы). Замер на 323 постах канала: с этим фильтром ложных
# срабатываний нет вовсе.
_CLIPPED_ANTI = re.compile(r"[а-яё]{3,}\*{0,2}\s*,\s+не\s+\*{0,2}([а-яё]{3,})\*{0,2}\s*(?=[:;]|\s[-—]\s)",
                           re.IGNORECASE)
_VERBISH = re.compile(r"(ться|ть|лся|лась|лись|ли|ла|ло|ет|ёт|ит|ут|ют|ат|ят|ешь|ишь|ся|сь)$", re.IGNORECASE)

# САМО-ПРИЗНАНИЕ «предыдущий блок не главное» ПОСЛЕДНЕЙ СТРОКОЙ АБЗАЦА (19.08) — подробности у места
# вызова. Ловим только конец абзаца: тот же оборот в середине («Но важнее другое: …») — обычный переход.
_SELF_DISMISS = re.compile(r"(не главное|не так важно|дело не в|важнее другое|не в этом суть)[^\n]{0,20}$",
                           re.IGNORECASE)


def _title_antithesis(head: str) -> bool:
    """Заголовок построен на «не A, а Б» (или «Б, а не A»)? Тег-рубрику «🌐 LINK | …» не считаем."""
    hl = head.replace("**", "").strip().split("| ", 1)[-1].strip()
    return bool(_TITLE_ANTI.search(hl))


