            # ОТКУДА РАСХОЖДЕНИЕ: 19.08 первым блоком промпта встали ЖИВЫЕ эталоны с пометкой «важнее
            # любого отдельного правила». Тексты идут из выгрузки канала, а Telegram хранит ссылки
