            # Пост уехал в отложку с футером БЕЗ эмодзи: `[Канал](…) | [Медиа](…) | …`. Проверка выше
            # ищет ЛЮБУЮ из меток `_FOOTER_MARK`, а `[Канал]` и `t.me/` — это сразу две, значит «футер
