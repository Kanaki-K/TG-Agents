def _record_lesson(args: dict, lessons_path: Path = LESSONS) -> str:
    """Записать урок в файл уроков. lessons_path выбирает дом: флагман (post_lessons) или scope
    (scope_lessons) — «один факт — один дом», ветки не смешиваются."""
    lesson = str(args.get("lesson", "") or "").strip()
    if not lesson:
        return "Пустой урок — нечего записывать."
    ev_raw = str(args.get("evidence", "") or "").strip()
    framed = untrusted.reject_if_framed(lesson, ev_raw)  # N-6: не отмывать внешний контент в память
    if framed:
        return framed
    rel = f"memory/{lessons_path.name}"
    dup = _lesson_duplicate(lesson, lessons_path)
    if dup and not args.get("confirm_new"):
        dup_line, why = dup
        return ("⚠ Такое правило похоже уже есть — " + why + ":\n  " + dup_line + "\n\n"
                "Если это ТО ЖЕ правило, сказанное иначе — НЕ дублируй (оно уже грузится в контекст "
                f"каждый пост; правило, которое уже в мануале/линтере, в {rel} тоже не нужно). "
                "Если твой урок правда НОВЫЙ или УТОЧНЯЕТ старый — так и напиши прямо в тексте "
                "урока, ЧЕМ он отличается от найденного (одной фразой, как в уроках 05.08/17.08 "
                "про отрицание), и вызови снова с confirm_new=true. Тогда в файле будет видно "
                "границу между двумя близкими правилами, а не два похожих урока подряд.")
    # Страж против МАНУАЛА: мануал (content_manual/scope_manual) и так грузится в контекст — урок,
    # повторяющий его правило, платится дважды каждый пост (обрастание жиром). Ловим ДО записи.
    manual_rel = "memory/content_manual.md" if lessons_path.name == "post_lessons.md" else "memory/scope_manual.md"
    man = _covered_by_manual(lesson, manual_rel)
    if man and not args.get("confirm_new"):
        return ("⚠ Это правило уже покрыто МАНУАЛОМ (" + manual_rel.split("/")[-1] + "):\n  " + man +
                "\n\nМануал и так в контексте — дублировать урок незачем (жир бьёт по цене каждого "
                "поста). Правда УТОЧНЯЕШЬ мануал? Переформулируй, ЧЕМ отличается, и вызови снова с "
                "confirm_new=true.")
    lessons_path.parent.mkdir(parents=True, exist_ok=True)
    if not lessons_path.exists():
        lessons_path.write_text(
            _LESSONS_SEED.get(lessons_path.name, f"# Уроки ({lessons_path.name})\n\n"),
            encoding="utf-8", newline="\n")
    ev = ev_raw
    line = f"- ({date.today().isoformat()}) {lesson}" + (f" — _из правки: {ev}_" if ev else "") + "\n"
    with open(lessons_path, "a", encoding="utf-8", newline="\n") as f:
        f.write(line)
    return (f"Урок записан в {rel} — учту в следующих постах. "
            "Отчитайся владельцу одной строкой, что усвоил.")


def _propose_standard(args: dict) -> str:
    content = str(args.get("content", "") or "").strip()
    if not content:
        return "Пустой стандарт — нечего предлагать."
    framed = untrusted.reject_if_framed(content)  # N-6: не отмывать внешний контент в стандарт
    if framed:
        return framed
    STANDARD_PROPOSED.parent.mkdir(parents=True, exist_ok=True)
    STANDARD_PROPOSED.write_text(content, encoding="utf-8", newline="\n")
    return ("Предложение записано: memory/post_standard.proposed.md (живой стандарт НЕ тронут). "
            "Покажи владельцу суть изменений; одобрит — применит командой /apply_standard.")


def _apply_standard() -> str:
    # Гейт в коде: применяем ТОЛЬКО ранее предложенный .proposed-файл (не произвольный текст).
    if not STANDARD_PROPOSED.exists():
        return "Нет предложенного стандарта (post_standard.proposed.md). Сначала /derive."
    HISTORY.mkdir(parents=True, exist_ok=True)
    if STANDARD.exists():
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        (HISTORY / f"post_standard-{stamp}.md").write_text(
            STANDARD.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    STANDARD.write_text(STANDARD_PROPOSED.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    STANDARD_PROPOSED.unlink()
    return ("Стандарт обновлён: memory/post_standard.md (старый — в memory/.history/ для отката). "
            "Предложение очищено.")


def _publish_now(args: dict | None = None) -> str:
    """Поставить ПОСЛЕДНИЙ готовый пост (последний драфт + обложка) в отложенные канала на слот
    контент-плана и уведомить мейн владельца. Детерминированно: текст берётся ДОСЛОВНО из сохранённого
    драфта, не переписывается. Формат берём из сохранённого kind драфта (или явного args['kind']), НЕ
    угадываем по длине. Обложку цепляем ТОЛЬКО флагману — короткий/scope уходит ТЕКСТОМ. /schedule."""
    args = args or {}
    channel = config.get_optional("PUBLISH_CHANNEL")
    if not channel:
        return "PUBLISH_CHANNEL не задан в .env — некуда планировать."
    drafts = _md_files(DRAFTS_DIR)
    if not drafts:
        return "Нет сохранённого драфта (memory/drafts/ пуст) — сначала напиши пост (/post)."
    text = drafts[0].read_text(encoding="utf-8").strip()
    if not text:
        return "Последний драфт пустой — нечего планировать."
    # ЗАЩИТА КАНАЛА: в пост идёт ТОЛЬКО тело. Всё после [[SPLIT]] — внутренняя мета владельцу (оценка,
    # [ПРОВЕРИТЬ]-флаги), в канал НЕ уходит. Плюс режем случайные строки [ПРОВЕРИТЬ…], если просочились в тело.
    text = text.split("[[SPLIT]]")[0]
    text = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("[ПРОВЕРИТЬ")).strip()
    if not text:
        return "После вырезания меты драфт пуст — нечего планировать (проверь формат поста)."
    # Формат: явный аргумент → сохранённый kind драфта → фолбэк-эвристика по длине.
    raw = str(args.get("kind", "") or "").strip().lower()
    if not raw and LAST_KIND.exists():
        raw = LAST_KIND.read_text(encoding="utf-8").strip().lower()
    if raw:
        kind = "flagship" if any(s in raw for s in ("флагман", "flagman", "flagship")) else "short"
    else:
        kind = content_plan.infer_kind(text)
    # Обложка — ТОЛЬКО для флагмана. Короткий/scope = текст-онли, даже если LAST_COVER от прошлого
    # флагмана висит в data/ (иначе короткий пост уйдёт с чужой картинкой «из сохранёнок»).
    # И для флагмана обложка должна принадлежать ИМЕННО этому драфту: cover не старше драфта. Иначе
    # make_image в этом прогоне упал/не вызывался, LAST_COVER хранит картинку ПРОШЛОГО флагмана —
    # лучше уйти ТЕКСТОМ (владелец увидит в «Отложенных» и перегенерит), чем прицепить чужую обложку.
    cover = ""
    cover_note = ""
    # Явная обложка ЭТОГО прогона (пайплайн передаёт путь) — берём её БЕЗ mtime-гейта: её собрал этот же
    # прогон. Работает для ЛЮБОГО формата: флагман-GPT (аутбокс) ИЛИ scope-картинка из первоисточника
    # (SCOPE_COVER). 2FA-фикс пересохраняет драфт ПОЗЖЕ картинки, и гейт «cover ≥ draft» ронял валидную.
    forced = str(args.get("cover", "") or "").strip()
    if forced and Path(forced).exists():
        cover = forced
    elif kind == "flagship":
        # Фолбэк флагмана: персистентная LAST_COVER, но только если принадлежит ЭТОМУ драфту (mtime-гейт).
        # Иначе make_image в этом прогоне упал/не вызывался и LAST_COVER хранит картинку ПРОШЛОГО флагмана —
        # лучше уйти ТЕКСТОМ (владелец увидит в «Отложенных» и перегенерит), чем прицепить чужую обложку.
        c = LAST_COVER.read_text(encoding="utf-8").strip() if LAST_COVER.exists() else ""
        if c and Path(c).exists() and LAST_COVER.stat().st_mtime + 2 >= drafts[0].stat().st_mtime:
            cover = c
        else:
            cover_note = (" ⚠️ Обложку НЕ прицепил: актуальной картинки для ЭТОГО поста нет "
                          "(make_image не сработал в этом прогоне / LAST_COVER от прошлого флагмана). "
                          "Флагман ушёл ТЕКСТОМ — сгенерь обложку и поставь заново, если нужна.")
    else:
        # short/scope: обложка из ПЕРВОИСТОЧНИКА (SCOPE_COVER, кладёт scope_writer) — но только если она
        # принадлежит ЭТОМУ драфту (mtime-гейт), иначе это картинка прошлого 🔭 → лучше текстом. Так scope
        # получает обложку и в бот-флоу (/schedule без явного cover), не только когда путь передал пайплайн.
        sc = SCOPE_COVER.read_text(encoding="utf-8").strip() if SCOPE_COVER.exists() else ""
        if sc and Path(sc).exists() and SCOPE_COVER.stat().st_mtime + 2 >= drafts[0].stat().st_mtime:
            cover = sc
    try:
        busy = {dt.astimezone(content_plan.tz()).date() for dt in publish.scheduled_times(channel)}
    except Exception:
        busy = set()
    slot = content_plan.next_slot(kind, busy_dates=busy)
    res = publish.publish(channel, text, cover or None, slot)
    if not res.get("ok"):
        return f"❌ Не поставил в отложенные: {res.get('error', '?')}. Драфт цел — поправь причину и снова /schedule."
    when = content_plan.human(slot)
    note = ""
    target = config.get_optional("PUBLISH_NOTIFY")
    if target:
        n = publish.notify(target, f"✅ Пост запланирован в канал на {when} "
                                   f"({content_plan.kind_label(kind)}). Проверь в «Отложенных» канала.")
        note = " Уведомил мейн владельца." if n.get("ok") else f" (уведомление на мейн не ушло: {n.get('error', '?')})"
    # ПРОВЕРКА: читаем отложенные обратно — подтвердить, что пост реально лёг (а не «ok» вхолостую).
    try:
        n_sched = len(publish.scheduled_times(channel))
        check = f" Проверка: в «Отложенных» канала сейчас {n_sched} сообщ."
    except Exception:
        check = " (проверку отложенных сделать не вышло)"
    return (f"✅ Поставил в отложенные канала: {content_plan.kind_label(kind)} на {when} "
            f"(режим: {res.get('mode', '?')}).{note}{check}{cover_note}\n"
            f"Сообщи владельцу слот; проверить/поправить/отменить — в нативных «Отложенных» канала.")


def _rhythm_note(changes: dict) -> str:
    """Предупреждение о рассинхроне с памятью, если меняли ДНИ выхода.

    Ритм недели описан ещё и в memory/post_standard.md — его читает ПИСАТЕЛЬ. Файл памяти молча не
    правлю (это канон, его ведёт владелец), но и промолчать нельзя: иначе код и стандарт разъедутся,
    а писатель будет считать, что канал выходит по-старому.
    """
    if not any(k.endswith("_days") for k in changes):
        return ""
    return ("\n\n📌 Учти: ритм недели описан и в memory/post_standard.md (его читаю я, когда пишу). "
            "Сам файл памяти я не правил — скажи, если синхронизировать.")


def _autopilot(args: dict | None = None) -> str:
    """Пульт автопилота ИЗ ЧАТА: посмотреть расписание, поменять параметры, включить/выключить.

    Продукт-решение владельца 11.08: всё, что можно, настраивается разговором с Криейтором — код это
    бэкенд. Поэтому значения приходят от МОДЕЛИ, и весь контроль — в коде (core/schedule):
    диапазоны, перекрёстная проверка «окно не пустое», отчёт «было → стало». Модель тут — только
    переводчик с человеческого; решение о записи принимает валидатор.
    """
    from core import os_task, schedule   # ленивый импорт: боту они нужны редко

    args = args or {}
    action = str(args.get("action", "status")).strip().lower()
    # Настройки, названные В ТОЙ ЖЕ фразе, применяем ДО включения. Владелец говорит одним предложением
    # («включи автопилот для флагмана вт/чт на 16:00 по берлину») — разбивать это на два шага значит
    # вернуть ему нашу внутреннюю кухню. Ошибка в параметре ⇒ НЕ включаем: пусть лучше уточнит.
    changes = {k: args[k] for k in ("flagship_time", "flagship_days", "scope_time", "scope_days",
                                    "lead_hours", "margin_minutes", "timezone")
               if args.get(k) not in (None, "")}
    applied = ""
    if changes and action in ("set", "on"):
        res = schedule.apply_params(changes, by="чат Криейтора")
        if not res["ok"]:
            return (f"⛔ Ничего не менял и НЕ включал: {res['error']}\n"
                    f"Уточни этот параметр — остальное я запомнил.\n\n{schedule.status_all()}")
        applied = "\n".join(f"  • {schedule.param_label(k)}: было «{was}» → стало «{now}»"
                            for k, was, now in res["diff"])
    if action in ("status", "", "show"):
        return schedule.status_all()
    if action in ("on", "off"):
        # ФОРМАТ обязателен и для on, и для off: включение = посты в канал без «ок» владельца, а
        # выключение он ждёт мгновенным. Угадать тут — значит либо включить лишнее, либо оставить
        # работать то, что он считал выключенным. Оба промаха дороже одного уточняющего вопроса.
        try:
            kinds = schedule.parse_kinds(args.get("format"))
        except ValueError as e:
            # Настройки из этой же фразы уже записаны (они были валидны) — говорим об этом прямо,
            # иначе владелец решит, что не применилось вообще ничего, и продиктует их заново.
            saved = f"⚙️ Настройки я записал:\n{applied}\n\n" if applied else ""
            return (f"{saved}Уточни формат: {e}\n"
                    f"Флагман и скоуп включаются и выключаются отдельно.\n\n{schedule.status_all()}")
    if action == "off":
        return _autopilot_off(kinds, os_task, schedule)
    if action == "on":
        return _autopilot_on(kinds, args, changes, applied, os_task, schedule)
    if action == "set":
        if not applied:
            return (f"Не понял, что менять. Скажи словами: «выход в 16:00», «скоуп по пн и пт», "
                    f"«старт за 3 часа», «по франкфурту».\n\n{schedule.status_all()}")
        return (f"✅ Расписание обновлено:\n{applied}\n\n"
                f"{schedule.status_all()}{_rhythm_note(changes)}")
    return (f"Не понял действие «{action}». Умею: status (показать), set (поменять параметр), "
            f"on/off (включить/выключить автозапуск формата).")


def _autopilot_off(kinds: list, os_task, schedule) -> str:
    """Выключить автопилот НАЗВАННЫХ форматов. Будильник снимаем, только если не осталось включённых."""
    words = " и ".join(content_plan.kind_word(k) for k in kinds)
    try:
        for k in kinds:
            schedule.turn_off(k)
    except OSError as e:   # диск/права: владелец должен УЗНАТЬ, что стоп-кран не сработал
        return (f"❌ НЕ смог выключить ({words}): {e}\n"
                f"Он остался ВКЛЮЧЁННЫМ. Скажи ещё раз или удали файлы data/autopilot_on_*.")
    left = schedule.enabled_kinds()
    if left:
        # Будильник ОБЩИЙ на оба формата — снять его сейчас значило бы выключить и то, что осталось.
        tail = (f"\n🔔 Будильник оставил: ещё работает "
                f"{' и '.join(content_plan.kind_word(k) for k in left)}.")
    else:
        alarm = os_task.remove()
        tail = ("\n🔔 Будильник снят — просыпаться больше некому." if alarm["ok"]
                else f"\n⚠️ Будильник снять не удалось ({alarm['detail']}), но без разрешения "
                     f"автопилот всё равно ничего не сделает.")
    return (f"⏸ Автопилот ВЫКЛЮЧЕН: {words}. Сам больше не запускается — посты только по твоей команде.\n"
            f"Пост, который УЖЕ стоит в «Отложенных», это не убирает — удали его в канале, если не нужен."
            + tail + "\n\n" + schedule.status_all())


def _autopilot_on(kinds: list, args: dict, changes: dict, applied: str, os_task, schedule) -> str:
    """Включить автопилот НАЗВАННЫХ форматов: разрешение + будильник в ОС, одним шагом."""
    reason = str(args.get("reason", "")).strip()
    if not reason:
        return ("Скажи одной фразой, зачем включаем (пишу её в файл — потом будет видно, зачем): "
                "например «обкатка в тестовом канале».")
    words = " и ".join(content_plan.kind_word(k) for k in kinds)
    try:
        for k in kinds:
            schedule.turn_on(k, f"{reason} (из чата Криейтора)")
    except OSError as e:
        return f"❌ НЕ смог включить ({words}): не записался файл-выключатель: {e}"
    # И СРАЗУ БУДИЛЬНИК: «включи автопилот» = один шаг, дальше само. Иначе владелец получал бы
    # «включено», но в нужный час никто не проснулся бы (его слова: «1 запуск = ожидаемый результат»).
    alarm = os_task.install()
    if not alarm["ok"]:
        return (f"⚠️ Разрешение поставил ({words}), но БУДИЛЬНИК не встал: {alarm['detail']}\n"
                f"Значит сам он не запустится. Скажи мне это сообщение целиком — разберёмся; "
                f"пока прогон только вручную (/run, /run_scope).\n\n{schedule.status_all()}")
    warn = ""
    if runmode.get()["mode"] == "test":
        warn = "\n⚠️ Завод в режиме 🧪 /test — автопилот публикацию НЕ сделает. Верни /main.\n"
    if "scope" in kinds:
        # Честно про единственное отличие скоупа: он может законно не выйти. Сказать это ПРИ включении
        # дешевле, чем объяснять потом, почему в пятницу тишина — владелец пойдёт чинить работающее.
        warn += ("\n🔭 Про скоуп: ему нужен свежий повод (гейт ≤3 дней). Если повода в этот день нет — "
                 "поста не будет, и я сразу напишу об этом сюда. Это норма, а не поломка.\n")
    setup = f"⚙️ Заодно записал, что ты назвал:\n{applied}\n" if applied else ""
    slots = "; ".join(f"{content_plan.kind_word(k)} — {content_plan.human(content_plan.next_slot(k))}"
                      for k in kinds)
    return (f"✅ Готово. Автопилот включён ({words}), будильник поставлен ({alarm['detail']}) — больше "
            f"ничего делать не нужно.\n" + setup +
            f"🗓 Следующие выходы: {slots}. Прогон начнётся за {schedule.lead_hours():g} ч до слота, "
            f"пост встанет в «Отложенные», я напишу сюда.\n"
            f"⚠️ Посты пойдут в канал БЕЗ твоего «ок» — у тебя есть окно вето в «Отложенных». "
            f"Выключить мгновенно: скажи «выключи автопилот для флагмана» / «…для скоупа» / «…для обоих».\n"
            + warn + "\n" + schedule.status_all() + _rhythm_note(changes))


def dispatch(name: str, args: dict) -> str:
    shared = analytics_tools.handle(name, args)  # общие read-only аналитич. инструменты (дедуп)
    if shared is not None:
        return shared
    priced = market_tools.handle(name, args)     # живая цена (market_price) — общий ценовой бэкенд
    if priced is not None:
        return priced
    if name == "publish_now":
        return _publish_now(args)
    if name == "autopilot":
        return _autopilot(args)
    if name == "list_briefs":
        return _list_md(BRIEFS_DIR, "Брифы Скаута (свежие сверху):",
                        "Брифов Скаута пока нет (memory/briefs/ пуст). Напиши из присланного "
                        "направления или попроси Скаута /scan.", int(args.get("n", 8)))
    if name == "read_brief":
        return untrusted.wrap(
            _read_md(BRIEFS_DIR, args.get("which", "latest"),
                     "Брифов Скаута нет (memory/briefs/ пуст). Пиши из присланного направления "
                     "или попроси Скаута /scan.",
                     f"Бриф по запросу «{args.get('which', '')}» не найден. Доступны:"),
            "бриф разведки Скаута (составлен из внешних источников)")
    if name == "list_drafts":
        return _list_md(DRAFTS_DIR, "Твои драфты (свежие сверху):",
                        "Драфтов пока нет (memory/drafts/ пуст).", int(args.get("n", 8)))
    if name == "read_draft":
        return _read_md(DRAFTS_DIR, args.get("which", "latest"),
                        "Драфтов пока нет (memory/drafts/ пуст).",
                        f"Драфт по запросу «{args.get('which', '')}» не найден. Доступны:")
    if name == "read_post":
        return analytics.read_post(int(args["id"]))
    if name == "save_draft":
        return _save_draft(args)
    if name == "make_image":
        return _make_image(args)
    if name == "record_lesson":
        return _record_lesson(args)
    if name == "record_scope_lesson":   # scope-ветка пишет в СВОЙ файл уроков (scope_lessons.md)
        return _record_lesson(args, SCOPE_LESSONS)
    if name == "top_posts":
        return analytics.top_posts(args.get("metric", "er"),
                                   int(args.get("n", 10)), args.get("content_type", ""))
    if name == "propose_standard":
        return _propose_standard(args)
    if name == "apply_standard":
        return _apply_standard()
    return f"Неизвестный инструмент: {name}"
