def _md_files(d) -> list:
    if not d.exists():
        return []
    # только реальные драфты: имя YYYY-MM-DD-*.md (так их пишет _save_draft). Посторонний .md, случайно
    # попавший в папку, НЕ станет постом и не собьёт гейт «свежий драфт этого прогона» (N-19).
    return sorted((p for p in d.glob("*.md") if re.match(r"\d{4}-\d{2}-\d{2}-", p.name)),
                  key=lambda p: p.stat().st_mtime, reverse=True)


def _first_heading(text: str) -> str:
    for line in text.splitlines():
        s = line.strip().lstrip("#").strip()
        if s:
            return s[:120]
    return "(пусто)"


def _list_md(d, label: str, empty: str, n: int = 8) -> str:
    files = _md_files(d)
    if not files:
        return empty
    out = [label]
    for p in files[:max(1, n)]:
        out.append(f"- {p.name} — {_first_heading(p.read_text(encoding='utf-8'))}")
    return "\n".join(out)


def _read_md(d, which: str, empty: str, not_found: str) -> str:
    files = _md_files(d)
    if not files:
        return empty
    q = (which or "latest").strip().lower()
    if q in ("", "latest", "последний", "свежий"):
        target = files[0]
    else:
        matches = [p for p in files if q in p.name.lower()]
        if not matches:
            avail = "\n".join(f"- {p.name}" for p in files[:8])
            return f"{not_found}\n{avail}"
        target = matches[0]  # самый свежий из совпавших (files уже отсортирован)
    text = target.read_text(encoding="utf-8")
    cap = 40000  # кап на контекст: файл большой, всё в одну сессию не тащим
    body = text[:cap] + ("\n\n… (обрезано)" if len(text) > cap else "")
    return f"=== {target.name} ===\n{body}"


# Набор кастом-эмодзи (data/custom_emoji.json): заголовки берут эмодзи ТОЛЬКО отсюда, иначе Telegram
# рендерит обычный эмодзи вместо кастомного. Нормализуем (снимаем variation-selector/ZWJ/тон кожи).
_EMOJI_VS = re.compile(r"[️‍\U0001F3FB-\U0001F3FF]")
_EMOJI_LEAD = re.compile(
    r"^([©®™ℹ←-⇿⌀-➿⬀-⯿"
    r"️‍\U0001F000-\U0001FAFF\U0001F3FB-\U0001F3FF]+)")
_allowed_emoji_cache: set | None = None


def _emoji_norm(s: str) -> str:
    return _EMOJI_VS.sub("", s)


def _allowed_emoji() -> set:
    global _allowed_emoji_cache
    if _allowed_emoji_cache is None:
        data = io_safe.load_json(config.ROOT / "data" / "custom_emoji.json", {})
        _allowed_emoji_cache = {_emoji_norm(k) for k in data}
    return _allowed_emoji_cache


def _title_two_sentences(head: str) -> bool:
    """Заголовок из ДВУХ предложений? Владелец (20.07, СТРОГО): ровно ОДНО — утверждение ЛИБО
    вопрос, НЕ «утв. утв.» и НЕ «факт. вопрос?». Двоеточие/тире = ОДНО предложение (тег-тему давай
    так). Тег-рубрику «🌐 LINK | …» и финальный знак не считаем; точка после инициала из одной буквы
    («T. Rowe», «U.S.») — не конец предложения (ложняк 17.07). Общий для scope и флагмана."""
    hl = head.replace("**", "").strip()
    hl = hl.split("| ", 1)[-1].strip().rstrip("?!.… ")
    hl = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", hl)   # инициал/сокращение из 1 буквы — не точка-конец
    return bool(re.search(r"[.!?]\s+\S", hl))       # внутренний конец предложения + продолжение = ДВА


def _title_dash_double(head: str) -> bool:
    """Заголовок = ДВОЙНАЯ мысль через тире («Бигтехи потеряли 800$ - биткоин не дрогнул»)? Владелец
    27.07 СТРОГО: заголовок — ОДНА мысль, «ни через тире нихуя». Тег-тему (короткий термин перед тире:
    «RWA - рельсы») НЕ трогаем — там слева 1-2 слова. Двойник = слева УЖЕ полный крючок (≥3 слов-токенов,
    т.е. подлежащее+действие или цифра-факт), а справа — вторая самостоятельная мысль. `_title_two_sentences`
    ловит двойник ТОЛЬКО через точку/!/?; тире оно намеренно считает одним предложением (для тег-тем) —
    эта функция закрывает дырку. Общий счёт слов, не грамматика (детерминированно, промпту не верим)."""
    hl = head.replace("**", "").strip().split("| ", 1)[-1].strip()   # тег-рубрику «🌐 LINK | …» не считаем
    m = re.search(r"\s[-–—]\s", hl)
    if not m:
        return False
    left = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", hl[:m.start()])        # инициал «T.»/«U.» — не слово (ложняк 17.07)
    return len(re.findall(r"\w+", left, re.UNICODE)) >= 3             # слева уже полный крючок → двойник


