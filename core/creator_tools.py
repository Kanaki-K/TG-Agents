def _sentences(text: str) -> int:
    """Сколько предложений в абзаце. Инициал/сокращение из одной буквы («T. Rowe», «U.S.») концом
    предложения не считаем — тот же ложняк, что чинили в заголовке 17.07."""
    t = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", (text or "").strip().rstrip("?!.… "))
    return len(re.findall(r"[.!?]\s+\S", t)) + 1


def _finale_para(clean: str) -> str:
    """Последний абзац ПЕРЕД футером — это и есть финал поста. Футера нет → '' (структуру не угадать)."""
    paras = [p for p in (clean or "").split("[[SPLIT]]")[0].split("\n\n") if p.strip()]
    foot = next((i for i, p in enumerate(paras) if any(m in p for m in _FOOTER_MARK)), None)
    return paras[foot - 1].strip() if foot and foot >= 1 else ""


def _finale_defects(fin: str) -> list:
    """Претензии к ФОРМЕ финала — детерминированно, кодом (переработка 31.07).

    БЫЛО: форму финала судила отдельная модель (scope_writer.fix_finale) и ПЕРЕПИСЫВАЛА концовку сама.
    Она же 31.07 продублировала абзац, и она же вместе с двумя другими судьями стачивала авторский
    голос — четыре чужих переписывания подряд. СТАЛО: форму меряет код и возвращает претензию АВТОРУ,
    пока он ещё в контексте. Правит тот, кто писал, — голос остаётся его.

    Меряем ТОЛЬКО форму, а не силу мысли: вопрос вместо вывода, хедж, слипшийся с оговоркой абзац,
    простыня вместо кикера. «Хороший ли это кикер» код не решает — это работа автора и глаз владельца.
    """
    out = []
    if not fin:
        return out
    body = fin.replace("**", "").strip()
    if body.endswith("?"):
        out.append("финал-ВОПРОС — рубрика кончается ВЫВОДОМ, а не вопросом к читателю (§4.5). "
                   "Дай утверждение, которое стоит само")
    low = body.lower()
    hedge = next((h for h in _HEDGE if h in low), "")
    if hedge:
        out.append(f"финал-ХЕДЖ (нашёл «{hedge}») — это не концовка, а уход от вывода. Скажи, что из "
                   "этого следует для холдера")
    n = _sentences(body)
    if n > 2:
        out.append(f"финал из {n} предложений — кикер это 1-2. Лишнее унеси абзацем выше, финал оставь "
                   "коротким и самостоятельным")
    if n > 1 and any(t in low[low.find(" "):] for t in _TURN):
        out.append("финал СЛИПСЯ С ОГОВОРКОЙ — вывод спрятан внутри абзаца после разворота («Но…», "
                   "«Зато…»), читатель не видит, где концовка. Разведи на ДВА абзаца: оговорка выше, "
                   "кикер — последней строкой (§6, инвариант завершения)")
    return out


def _title_keep_first(head: str) -> str:
    """Оставить в заголовке РОВНО ПЕРВУЮ мысль (владелец 20.07/27.07 СТРОГО: одно утверждение ЛИБО
    вопрос, без двойника — ни через точку, ни через тире). Раньше правило было только warn — модель его
    РЕГУЛЯРНО переспоривала («авторское решение, не режу», прогоны 24.07). Режем ДЕТЕРМИНИРОВАННО в КОДЕ,
    как тире/кавычки: промпту тут не верим. Бережём жирную обёртку **…**, ведущий эмодзи-якорь, тег-рубрику
    «🌐 LINK | …» (режем только текст ПОСЛЕ разделителя) и инициал «T. Rowe»/«U.S.». Чисто — вернём head."""
    raw = head.strip()
    bold = raw.startswith("**") and raw.endswith("**") and len(raw) > 4
    inner = raw[2:-2].strip() if bold else raw
    prefix = ""
    if "| " in inner:                                    # тег-рубрику сохраняем целиком
        prefix, inner = inner.split("| ", 1)
        prefix += "| "
    masked = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", lambda m: " " * len(m.group()), inner)  # маска инициала, позиции целы
    m = re.search(r"[.!?]\s+\S", masked)                 # конец 1-го предложения + продолжение = ДВА
    if m:
        inner = inner[:m.start() + 1].rstrip()           # включаем сам знак конца предложения
        if inner.endswith(".") and not inner.endswith(".."):  # точка в конце заголовка не ставится (§5)
            inner = inner[:-1].rstrip()
    md = re.search(r"\s[-–—]\s", inner)                  # ДВОЙНИК через тире (слева ≥3 слов) → левую мысль
    if md:
        _left = re.sub(r"\b[A-Za-zА-Яа-яЁё]\.", "", inner[:md.start()])   # инициал «T.» — не слово
        if len(re.findall(r"\w+", _left, re.UNICODE)) >= 3:
            inner = inner[:md.start()].rstrip()
    out = prefix + inner
    out = f"**{out}**" if bold else out
    return out if out != head else head


def _lint(content: str, kind: str = "") -> tuple:
    """Код-гейт типографики/размера (детерминированно, не на доверии к модели).

    Авто-чинит механику (тире/кавычки к канону мануала §5). Возвращает (чистый_текст, список
    предупреждений) для того, что нельзя править вслепую (валюта, размер, футер, «является»).
    """
    clean = content or ""
    # Разметка цитат веб-поиска (<cite index="1-4">…</cite>) протекает в текст у слабых моделей —
    # срезаем теги, сохраняя содержимое (это служебная аннотация поиска, не часть поста).
    clean = re.sub(r"</?cite[^>]*>", "", clean)
    # ДУБЛЬ-АБЗАЦ (баг Strategy 31.07: «Тезис на BTC не сломался» ушёл в отложку ДВАЖДЫ подряд). Дословный
    # повтор целого абзаца — всегда сбой сплайса (судьи финала/мыслей режут и вставляют абзацы), а не приём.
    # Ловим ДЕТЕРМИНИРОВАННО и на общем пути сохранения: какой бы пасс это ни породил, в файл драфта и в
    # канал дубль не уйдёт. Оставляем ПЕРВОЕ вхождение. Короткие строки (<15 знаков) не трогаем — там
    # повтор может быть намеренным (рефрен/разделитель).
    _seen_p, _kept, _dropped = set(), [], 0
    for _p in clean.split("\n\n"):
        _key = re.sub(r"\s+", " ", re.sub(r"[*_`«»\"'“”„.,;:!?()\[\]—–-]+", " ", _p.lower())).strip()
        if len(_key) >= 15 and _key in _seen_p:
            _dropped += 1
            continue
        if len(_key) >= 15:
            _seen_p.add(_key)
        _kept.append(_p)
    if _dropped:
        clean = "\n\n".join(_kept)
    for d in ("—", "–", "―"):          # длинные тире → обычный дефис
        clean = clean.replace(d, "-")
    for q in ("«", "»", "“", "”", "„", "‟"):  # ёлочки/фигурные кавычки → прямые
        clean = clean.replace(q, '"')
    # §5/voice_core §2: ТОЧКА в конце СТРОКИ не ставится — фирменный маркер канала (93% концовок автора
    # без точки), действует на ВСЕ форматы (флагман тоже). Срезаем ДЕТЕРМИНИРОВАННО только когда строка
    # ЗАканчивается одиночной точкой. Если после точки на строке есть ПРОДОЛЖЕНИЕ (точка между
    # предложениями) — строка на «.» не оканчивается, её не трогаем. Бережём «...» (троеточие), «?»/«!».
    _pl = []
    for _ln in clean.split("\n"):
        _r = _ln.rstrip()
        if _r.endswith(".") and not _r.endswith(".."):   # одиночная точка в КОНЦЕ строки, не троеточие
            _r = _r[:-1].rstrip()
        _pl.append(_r)
    clean = "\n".join(_pl)
    # Заголовок поста (1-я непустая строка) ДОЛЖЕН быть жирным (§5). Модель регулярно забывает разметку
    # (см. §5-детектор ниже) — чиним ДЕТЕРМИНИРОВАННО, а не только предупреждаем: короткую титульную
    # строку без ** оборачиваем в **…** (эмодзи-якорь остаётся ВНУТРИ жирного, как в эталонах канала).
    # 'light' (Ф3, чистый текст) пропускаем — у него заголовка-строки может не быть, а длинную (>80
    # знаков) первую строку не трогаем (это не заголовок, а абзац-хук).
    if "light" not in (kind or "").lower():
        _kk = (kind or "").lower()
        # подзаголовки-разделы жирним только у флагмана (у короткого/scope разделов-вывесок нет)
        _sub_ok = "scope" not in _kk and "коротк" not in _kk and "short" not in _kk
        _ls = clean.split("\n")
        _title_done = False
        for _i, _ln in enumerate(_ls):
            if not _ln.strip():
                continue
            _vis = re.sub(r"^[^\wА-Яа-яЁё]+", "", _ln.replace("**", "")).strip()
            if not _title_done:   # ЗАГОЛОВОК поста — первая непустая строка
                if "**" not in _ln and 0 < len(_vis) <= 80:
                    _ind = _ln[:len(_ln) - len(_ln.lstrip())]
                    _ls[_i] = f"{_ind}**{_ln.strip()}**"
                _title_done = True
                if not _sub_ok:
                    break
                continue
            # ПОДЗАГОЛОВКИ-РАЗДЕЛЫ флагмана (§5: ВСЕ заголовки/подзаголовки жирные). Признак вывески:
            # эмодзи-якорь в начале + короткая строка (≤50 видимых), НЕ футер (без http/|), НЕ уже жирная.
            # Тело флагмана с эмодзи не начинается — ложных срабатываний практически нет.
            _raw = _ln.strip()
            if ("**" not in _ln and _EMOJI_LEAD.match(_raw) and 0 < len(_vis) <= 50
                    and "http" not in _raw and "|" not in _raw):
                _ind = _ln[:len(_ln) - len(_ln.lstrip())]
                _ls[_i] = f"{_ind}**{_raw}**"
        clean = "\n".join(_ls)
    warns = []
    if _dropped:
        warns.append(f"дословный ПОВТОР абзаца ({_dropped} шт.) — вырезал автоматически (сбой сплайса "
                     "судьи финала/мыслей). Проверь, что мысль не потерялась и переход читается")
    cur = len(re.findall(r"\$\s?\d", clean))
    if cur:
        warns.append(f"валюта ПЕРЕД числом — {cur} шт (нужно ПОСЛЕ: 73 млн$, не $73 млн)")
    yav = len(re.findall(r"явля[ею]", clean, re.IGNORECASE))
    if yav:
        warns.append(f"«является/являются» — {yav} шт (убрать, §7)")
    # Англицизмы-маркеры «писала ИИшка» — авто-warn (высокий сигнал, мало ложных; §7)
    # «рецесс» (recess) добавлен 15.07: калька прямо из англоязычного источника — владелец правил на «перерыв».
    # 29.07: добавлен финжаргон-латиница + залётные англ. слова (владелец: пост тяжёлый от терминов).
    # Это СЕТЬ-предупреждение (видно в консоли) — правит АВТОР по возврату линтера; имена/тикеры/компании
    # латиницей (Ethereum, BNY, Goldman Sachs) НОРМА, их тут НЕТ, ловим только переводимое.
    angl = {"фрейм": "каркас/рамка", "юзер": "пользователь", "сетап": "расклад",
            "кейс": "пример/случай", "b2b": "между компаниями",
            "рецесс": "перерыв/каникулы",
            "tradfi": "традиционные финансы", "defi": "децентрализованные финансы",
            "mmf": "фонды денежного рынка", "on-chain": "на блокчейне",
            "british": "британский"}  # «хайп» — фирменное, не трогаем
    found_angl = [f"«{w}»→{repl}" for w, repl in angl.items()
                  if re.search(rf"\b{re.escape(w)}", clean, re.IGNORECASE)]
    if found_angl:
        warns.append("англицизмы (§7): " + ", ".join(found_angl))
    # Имена ЛЮДЕЙ латиницей в русском теле — след англоязычного источника, протёкший в пост (баг 15.07:
    # «Trump задекларировал 1.4 млрд$», владелец правил на «Трамп»). Список ТОЧЕЧНЫЙ, только люди: бренды
    # латиницей для канала НОРМА (Chainlink, SpaceX, Visa, BlackRock — прямо в эталонах §8.1), их не трогаем.
    lat_persons = {"trump": "Трамп", "biden": "Байден", "powell": "Пауэлл", "yellen": "Йеллен",
                   "saylor": "Сэйлор", "musk": "Маск", "lummis": "Ламмис", "gensler": "Генслер",
                   "atkins": "Аткинс", "dimon": "Даймон", "buterin": "Бутерин", "hayes": "Хейс"}
    found_lat = [f"«{w.capitalize()}»→«{repl}»" for w, repl in lat_persons.items()
                 if re.search(rf"\b{w}\b", clean, re.IGNORECASE)]
    if found_lat:
        warns.append("имя человека ЛАТИНИЦЕЙ в русском тексте (§7): " + ", ".join(found_lat)
                     + " — пиши кириллицей (бренды латиницей — норма, люди — нет)")
    # Стаккато-триады (manufactured staccato drama, §11.5): 3+ УТВЕРДИТЕЛЬНЫХ обрубка ≤3 слов подряд =
    # след ИИ-редактора. Считаем только фрагменты НА ТОЧКЕ (вопросы-списки «Монополия LINK?» — приём, не
    # сюда) и делим по пунктуация+пробел, чтобы НЕ резать десятичные «0.31$».
    run = mx = 0
    for s in re.split(r"(?<=[.!?])\s+", clean):
        s = s.strip()
        if s.endswith(".") and len(re.sub(r"[^\w\s]", " ", s).split()) <= 3:
            run += 1
            mx = max(mx, run)
        else:
            run = 0
    if mx >= 3:
        warns.append(f"стаккато-ритм: {mx} обрубка-утверждения ≤3 слов подряд (ИИ-подача, §11.5) — "
                     f"слей в живую фразу")
    # «Это не X. Это Y» — ИИ-пул-квота (§11.5, владелец требует убирать насовсем). Ловим парную форму.
    eto = re.findall(r"Это не [^.!?\n]{1,60}[.!?]+\s+Это\b", clean)
    if eto:
        warns.append(f"«Это не X. Это Y» — {len(eto)} шт (ИИ-пул-квота §11.5, скажи Y прямо с фактом)")
    # --- AI-ритм: детерминированные детекторы (модель СЛЕПА к своему стаккато — ловим КОДОМ, не доверием) ---
    low = clean.lower()
    # Передоз антитезы «не X, а Y»: ОДНА центральная ок, 3+ = ИИ-ритм (§11.10). Считаем ТОЛЬКО ПРЯМУЮ
    # форму. Обратную «X, а не Y» УБРАЛИ из счёта (урок 14.07 + аудит линтера 20.07): она ловила ПРОСТОЙ
    # контраст («исключение, а не правило», «вероятности, а не станок»), из-за чего модель клипала
    # «а не»→«не» ради ухода из-под порога → телеграфно-обрубленный тон ХУЖЕ исходного. Детектор
    # активно портил подачу — теперь ловит только риторическую параллель, а не всякий союз «а не».
    anti = len(re.findall(r"\bне\s+[^,.!?\n]{1,45},\s*а\s+", low))
    if anti >= 3:
        warns.append(f"передоз антитезы «не X, а Y» — ~{anti} шт: оставь МАКС 1 центральную (в 💡), "
                     f"остальные перепиши ПРЯМЫМ утверждением (§11.5)")
    # Триплет-двойное отрицание «не А, не Б …» (типа «не торговал, не спекулировал») — ИИ-симметрия (§11.10).
    dbl = re.findall(r"\bне\s+\w+[^.!?\n]{0,30},\s*не\s+\w+", low)
    if dbl:
        warns.append(f"триплет «не А, не Б — В» — {len(dbl)} шт: один сильный образ, не три параллельных (§11.5)")
    # Фразы-анонсы важности — не объявляй словами, покажи позицией/жирным (урок 22.06).
    announce = [p for p in ("вот это и есть", "важно другое", "а теперь главное", "вот в чём",
                            "самое интересное", "вот что важно") if p in low]
    if announce:
        warns.append("фраза-анонс важности (резать): " + ", ".join(f"«{p}»" for p in announce))
    # Бан-клише заголовков (вечный бан + анти-самоповтор флагманов).
    if "розов" in low and "очк" in low:
        warns.append("БАН-фраза «розовые очки» (клише+самоповтор) — назови раздел по СУТИ блока")
    # «рельсы»/«крипто-рельсы» — костыль-повтор из поста в пост (владелец забанил 29.07).
    if "рельс" in low:
        warns.append("БАН-слово «рельсы»/«крипто-рельсы» (костыль-повтор канала, владелец 29.07) — "
                     "замени: инфраструктура/каналы/система расчётов/трубы/сеть — или переформулируй")
    # Недоказуемые суперлативы — слабые слова (урок 22.06).
    sup = re.findall(r"сам[ыио]\w*\b[^.!?\n]{0,40}\bв мире|крупнейш\w+|перв\w+ в истории|беспрецедент\w*", low)
    if sup:
        warns.append(f"недоказуемый суперлатив — {len(sup)} шт («самые…в мире»/«крупнейший»/«первый в "
                     f"истории»): смягчи или убери")
    # «хедж» как англицизм-страховка (но «хедж-фонд» как организация — оставляем).
    if re.search(r"\bхедж(?![- ]?фонд)", low):
        warns.append("«хедж» → «страховка» (англицизм §7; «хедж-фонд» как организацию — оставь)")
    # --- Заголовок (1-я непустая строка): олицетворение неживого + длина (учим на реальных заголовках) ---
    head = next((s.strip() for s in clean.split("\n") if s.strip()), "")
    if re.search(r"\b(что|как|кого|чего|куда|зачем)\s+(увид|поня|реши|дума|почувств|захот|боит|смотр)\w+"
                 r"\s+(?:[^\s]+\s+){0,2}(пенси\w+|фонд\w*|рынок|рынк\w+|экономик\w+|биткоин\w*|доллар\w*|капитал\w*)\b",
                 head, re.IGNORECASE):
        warns.append("заголовок: олицетворение неживого («что увидела пенсия/фонд» — предметы не видят/думают) "
                     "— переформулируй от живого субъекта или утверждением")
    # Заголовок: вымученный разговорный глагол-метафора («кто ВЫПИЛ ликвидность», «рынок СОЖРАЛ»). Данные
    # (топ канала по репостам) — сильные заголовки строятся «факт/число + ЧИСТЫЙ вопрос-флип», без насилия
    # над глаголом. Ловим ДО make_image (шаг 8 линт идёт перед шагом 9): не жжём малый лимит картинок на
    # сыром заголовке. Бан-лист растёт уроками (как «розовые очки»).
    hverb = re.findall(r"\b(выпил\w*|сожр\w+|слопал\w*|схарчил\w*|проглот\w+|заглот\w+|высос\w+|"
                       r"выкач\w+|пожрал\w*)\b", head.lower())
    if hverb:
        warns.append(f"заголовок: вымученный глагол-метафора «{hverb[0]}» — для канала это палево. Сильные "
                     f"заголовки = факт/число + чистый вопрос («20% майнеров в убытке. Поломка или уборка?», "
                     f"«ФРС сменила главу. Почему это важнее, чем ставка?»). Переформулируй БЕЗ разговорной "
                     f"метафоры-глагола. И почини заголовок ДО make_image — лимит картинок мал, не трать на сырой")
    hvis = re.sub(r"^[^\wА-Яа-яЁё]+", "", head.replace("*", "")).strip()  # без ведущих эмодзи и жирного
    if len(hvis) > 80:
        warns.append(f"заголовок длинный (~{len(hvis)}зн): сильные заголовки канала короткие (~4–9 слов) — подожми")
    # Заголовок поста ДОЛЖЕН быть жирным (§5: все заголовки/подзаголовки жирные).
    if head and "**" not in head:
        warns.append("заголовок поста НЕ жирный — оберни в **…** (ВСЕ заголовки и подзаголовки жирные, §5)")
    # Ссылки/бренд-домены в ТЕЛЕ (кроме футера) — запрещены (в тексте ссылок нет, только футер).
    _footmark = ("🖥", "▶️", "🥸", "📱", "t.me/", "linktr", "notion.so")
    body_nf = "\n".join(ln for ln in clean.split("\n") if not any(m in ln for m in _footmark))
    if re.search(r"https?://", body_nf):
        warns.append("ссылка (http) в ТЕЛЕ поста — в тексте ссылок НЕ ставим, только в футере")
    dom = re.findall(r"\b[\w-]+\.(?:com|io|org|net|app|xyz|finance|exchange)\b", body_nf, re.IGNORECASE)
    if dom:
        warns.append(f"бренд-домен в теле — {dom[:3]}: Telegram авто-линкует в ссылку (в тело ссылок нельзя) — "
                     f"переформулируй (напр. «биржа Crypto…»)")
    # Эмодзи ЗАГОЛОВКОВ — ТОЛЬКО из набора (data/custom_emoji.json): чужой (🤖) рендерится обычным, не кастом.
    allowed = _allowed_emoji()
    if allowed:
        bad = []
        for ln in clean.split("\n"):
            mm = _EMOJI_LEAD.match(ln.replace("**", "").lstrip())
            if mm:
                lead = _emoji_norm(mm.group(1))
                if lead and lead not in allowed and lead not in bad:
                    bad.append(lead)
        if bad:
            warns.append("эмодзи-заголовок НЕ из набора (рендерится обычным, не кастом): "
                         + " ".join(bad) + " — возьми из data/custom_emoji.json (93 шт)")
    # Якорный жирный (§5): плотность 10–15%. Считаем долю символов внутри **…** от видимого текста.
    # >18% = «выделил слишком много» (жирное обесценивается); <4% или <2 выделений = «жирного НЕТ»
    # (пост не сканируется — частый промах: модель забывает разметку, хотя §5 этого требует).
    k = (kind or "").lower()
    bold_spans = re.findall(r"\*\*(.+?)\*\*", clean, re.DOTALL)
    bold_chars = sum(len(b) for b in bold_spans)
    vis = len(clean.replace("**", "")) or 1
    dens = bold_chars / vis
    if dens > 0.18:
        warns.append(f"жирного слишком много: ~{round(100 * dens)}% текста (норма 10–15%, §5) — "
                     f"сними лишнее (skim-тест: только несущие слова), иначе жирное перестаёт работать")
    elif "light" not in k and (dens < 0.04 or len(bold_spans) < 2):
        warns.append("НЕТ якорного жирного (§5): размечай через **…** ЗАГОЛОВКИ-разделы и несущие слова "
                     "(имена, ключевые цифры, повороты, развязку) — плотность 10–15%, skim-слой. Сейчас "
                     "пост не сканируется (это обязательный приём, а не опция)")
    if "флагман" in k or "flagman" in k:
        n = len(clean.encode("utf-16-le")) // 2  # точный счёт Telegram (UTF-16 units = лимит 4096), не байты
        if n < 2800:
            warns.append(f"флагман КОРОТКИЙ: {n} знаков (норма 2800–4096) — добери плотности фактов")
        elif n > 4096:
            warns.append(f"⛔ флагман НЕ ВЛЕЗАЕТ в одно сообщение Telegram: {n} знаков > 4096 — "
                         f"режь до ≤4096 (Telegram порвёт на 2 сообщения, хвост читается как «дописала ИИ»)")
        elif n > 3900:
            warns.append(f"флагман у СТЕНЫ: {n} знаков (лимит 4096, идеал 3000–3800) — подожми, "
                         f"оставь запас под футер")
        if "notion" not in clean.lower() and "🖥" not in clean:
            warns.append("нет футера (🖥 Медиа | 🥸 Мемы | 📱 Notion)")
        # ЗАГОЛОВОК флагмана: эмодзи-якорь ОБЯЗАТЕЛЕН (баг 20.07 — флагман вышел без эмодзи; чужой/не-из-
        # набора уже ловит детектор эмодзи-заголовков выше, тут — случай «эмодзи нет вовсе»).
        if not _EMOJI_LEAD.match(head.replace("**", "").lstrip()):
            warns.append("заголовок флагмана БЕЗ эмодзи-якоря — начни с эмодзи ИЗ НАБОРА "
                         "(data/custom_emoji.json): напр. 📊 📉 🔔 ⚙️ 🌐. Без него заголовок-баннер голый")
        # ЗАГОЛОВОК флагмана — РОВНО ОДНО предложение ИЛИ один вопрос (владелец 20.07, СТРОГО). «Факт.
        # вопрос?» БОЛЬШЕ НЕ формула канала. Тег-тему давай через ДВОЕТОЧИЕ/тире («RWA: …»), не точку.
        if _title_two_sentences(head):
            warns.append("заголовок флагмана из ДВУХ предложений — оставь РОВНО ОДНО (утверждение ЛИБО "
                         "вопрос, владелец 20.07). ❌ «Рынок вытряхивает трейдеров. Долгосрочника - нечем», "
                         "❌ «Факт. Вопрос?». Тег-тему давай через ДВОЕТОЧИЕ («RWA: …»), не точку. Почини ДО "
                         "make_image — лимит картинок мал")
    if "scope" in k or "коротк" in k:
        n = len(clean.encode("utf-16-le")) // 2
        # Числа — из SCOPE_* выше (единственный источник). Замер принятых постов (Chainlink 1079 / SWIFT
        # 1203 / BNY 1216 / Orange 1276 всего) и правило владельца «тело 600-1000, ориентир ~950» — это
        # одно и то же, просто считали с футером и без него.
        if n > SCOPE_TOTAL_CAP and is_advice_post(clean):
            # Пост велит читателю действие — формат уступает безопасности (случай Coldcard 31.07).
            warns.append(f"scope длиннее потолка ({n} > {SCOPE_TOTAL_CAP}), но это пост-ИНСТРУКЦИЯ: режь "
                         f"ТОЛЬКО воду и повторы. НЕ выкидывай «кого касается», номера версий, «что не "
                         f"спасает» и «кого НЕ касается» — на этих строках человек принимает решение о "
                         f"своих деньгах. Не влезает без потери такой строки — оставь длинным")
        elif n > SCOPE_TOTAL_CAP:
            warns.append(f"⛔ scope ДЛИННЫЙ: {n} знаков — потолок {SCOPE_TOTAL_CAP} всего (тело "
                         f"{SCOPE_BODY_MIN}-{SCOPE_BODY_MAX} + футер ~{SCOPE_FOOTER_LEN}): это мини-пост, "
                         f"не мини-флагман. Срежь ВОДУ/лекцию/повтор — но НЕ едж и не спину поста")
        elif n < SCOPE_TOTAL_MIN:
            warns.append(f"scope коротковат: {n} знаков — телеграмма (нужно от {SCOPE_TOTAL_MIN} всего, "
                         f"тело от {SCOPE_BODY_MIN}). Доведи механику (было→стало) + поворот + "
                         f"самостоятельный финал — на такой длине суть теряется")
        # ЗАГОЛОВОК — РОВНО ОДНО ПРЕДЛОЖЕНИЕ (владелец 20.07, СТРОГО). Раньше был только warn — модель его
        # переспоривала («авторское решение, не режу», прогоны 24.07). Теперь режем ДЕТЕРМИНИРОВАННО в коде
        # (как тире/кавычки): оставляем первое предложение. ТОЛЬКО scope — флагман-заголовок 23.07 залочен,
        # там остаётся warn (:543). Пост НЕ блокируем: заголовок правится на месте, «пост обязан быть».
        if _title_two_sentences(head) or _title_dash_double(head):
            _one = _title_keep_first(head)
            if _one and _one != head:
                _ls2 = clean.split("\n")
                for _j, _l2 in enumerate(_ls2):
                    if _l2.strip() == head:
                        _ind2 = _l2[:len(_l2) - len(_l2.lstrip())]
                        _ls2[_j] = _ind2 + _one
                        break
                clean = "\n".join(_ls2)
                head = _one
                warns.append("scope: заголовок был ДВОЙНЫМ (через точку ИЛИ тире) — оставил РОВНО первую "
                             "мысль (детерминированно, владелец 20.07/27.07). Проверь, что крючок не потерялся.")
        if "💭" in clean or "Вопрос к Вам" in clean:
            warns.append("scope: УБЕРИ флагман-закрытие 💭 «Вопрос к Вам» — в коротком финал это обычная "
                         "строка-вывод, а не отдельный раздел-вопрос")
        if "💡" in clean:
            warns.append("scope: УБЕРИ 💡-раздел с афоризмом (флагман-фурнитура) — встрой мысль в текст "
                         "обычным предложением")
        # Едж-правило §5: линза/честный риск ВПЛЕТАЮТСЯ живой строкой, а не ярлыком-разделом «методички».
        for label in ("риск честно", "что значит долгосрочнику", "что это значит долгосрочнику",
                      "главное для инвестора", "что значит для долгосрочника"):
            if label in clean.lower():
                warns.append("scope: УБЕРИ ярлык-раздел (нашёл «" + label + ":») — линзу долгосрочника и "
                             "честный риск ВПЛЕТАЙ живой строкой в текст, а не методичкой-рубрикой (§5). "
                             "Отдельный ярлык = недофлагман, главный признак бота.")
                break
        # ПЛОСКИЙ ЖУРНАЛИСТСКИЙ ТОН — главный враг подачи scope (scope = НОВОСТЬ + ТВОЙ ЕДЖ, а не пересказ
        # новости). Ловим: 1) отстранённый пересказ («лента/СМИ/эксперты прочитали/отметили/сообщается»);
        # 2) канцелярит («фирма прописала, что делать»); 3) филлеры-подводки («важнее чем кажется»).
        # Ты ВЛАДЕЕШЬ фактом и говоришь СВОИМ голосом, а не «как написали в ленте».
        scl = clean.lower()
        relay = [p for p in ("лента прочитала", "лента читает", "сми пишут", "сми сообщ", "эксперты отмеч",
                             "эксперты счит", "аналитики отмеч", "сообщается", "стало известно",
                             "как пишут", "прописала, что делать", "прописал, что делать") if p in scl]
        if relay:
            warns.append("scope: ПЛОСКИЙ ЖУРНАЛИСТСКИЙ ТОН (нашёл «" + relay[0] + "») — ты ВЛАДЕЕШЬ фактом, "
                         "не пересказываешь новость. Скажи прямо от себя: «Saylor разрешил продавать», "
                         "не «лента прочитала это как». scope = новость + ТВОЙ едж, а не сводка.")
        # ШАБЛОННЫЕ СВЯЗКИ-«ИИшки» (разбор Strategy 31.07: «подача как всегда ИИшная»). Это не стиль, а
        # каркас-разметка, которой модель склеивает абзацы вместо того, чтобы просто СКАЗАТЬ. Узнаются
        # мгновенно и делают пост ботом. Ловим кодом, а не правилом в промпт (золотое правило 13.07:
        # над-инженерия промпта ломает подачу, чек в линтере — нет).
        tmpl = [p for p in ("заголовки кричат", "реальная новость", "механика проста", "механика вот в чём",
                            "механика такая", "суть проста", "что здесь важно", "и вот почему",
                            "разберём по порядку", "давайте разберём", "если коротко") if p in scl]
        if tmpl:
            warns.append("scope: ШАБЛОННАЯ ИИ-СВЯЗКА (нашёл «" + tmpl[0] + "») — это каркас-разметка, а не "
                         "речь. УБЕРИ связку и скажи мысль напрямую: не «Механика проста: X», а сразу «X». "
                         "Такие склейки — главный признак поста-бота.")
        # ФИНАЛ — форма проверяется КОДОМ и возвращается АВТОРУ (переработка 31.07). Раньше это делал
        # отдельный судья-модель, который переписывал концовку сам; он же дублировал абзацы и вместе с
        # двумя другими судьями стачивал голос. Теперь правит тот, кто писал.
        for _d in _finale_defects(_finale_para(clean)):
            warns.append("scope: " + _d)
        filler = [p for p in ("важнее, чем кажется", "важнее чем кажется", "стоит отметить",
                              "интересно, что", "интересно то, что", "нельзя не отметить") if p in scl]
        if filler:
            warns.append("scope: ФИЛЛЕР-ПОДВОДКА (нашёл «" + filler[0] + "») — режь, давай суть сразу. "
                         "Подача scope — без раскачки и канцелярских подводок.")
    return clean, warns


def _save_draft(args: dict) -> str:
    DRAFTS_DIR.mkdir(parents=True, exist_ok=True)
    kind = str(args.get("kind", "") or "").strip().lower()
    clean, warns = _lint(args.get("content", ""), kind)
    base = "-".join(x for x in (args.get("slug", "") or "post", kind) if x)
    slug = re.sub(r"[^a-z0-9-]+", "-", base.lower()).strip("-") or "post"
    fname = f"{date.today().isoformat()}-{slug}.md"
    (DRAFTS_DIR / fname).write_text(clean, encoding="utf-8", newline="\n")
    try:  # запоминаем формат — publish_now возьмёт его, а не будет гадать по длине текста
        LAST_KIND.parent.mkdir(parents=True, exist_ok=True)
        LAST_KIND.write_text(kind, encoding="utf-8")
    except Exception:
        # Аудит флагмана 20.07: НЕ глотать молча — если формат не записался, publish_now гадает по
        # длине (infer_kind) и флагман под порогом может стать 'short' → потеря обложки. Пусть видно.
        logging.warning("Не удалось записать LAST_KIND=%s — publish_now будет гадать формат по длине", kind)
    msg = f"Драфт сохранён: memory/drafts/{fname}. Типографику привёл к канону (тире/кавычки, точки в конце строк убраны)."
    if warns:
        msg += " ⚠ ИСПРАВЬ перед выдачей: " + "; ".join(warns) + "."
    else:
        msg += " Линтер чистый."
    msg += ("\n\n--- ВЫДАЙ В ЧАТ ИМЕННО ЭТУ ВЕРСИЮ (с учётом правок выше; это драфт, публикует владелец) ---\n"
            + clean)
    return msg


