"""Второй объектив петли: УГОЛ/ПОДАЧА поста (не «про что», а «как подано»).

Тема отвечает «какой РАЗРЯД заходит», угол — «какая ПОДАЧА заходит». Нужен, чтобы отличить
«психология выигрывает как тема» от «личный угол выигрывает, а психология просто чаще личная».
Если спред по углам круче спреда по темам — решает подача, и слабую тему (рынок) может спасти
смена угла. Это ИНСАЙТ владельцу, в пикер НЕ вписан (подача залочена) — только диагностика.
"""
from __future__ import annotations

ANGLES = {
    "личный": "Личный опыт / от первого лица",
    "механика": "Механика / как это работает",
    "контринтуитив": "Контринтуитив / развенчание мифа",
    "новость": "Новость / реакция на событие",
    "мнение": "Мнение / позиция автора",
}
UNKNOWN = "прочее"


def label(slug: str) -> str:
    return ANGLES.get(slug, slug)


def all_slugs() -> list[str]:
    return list(ANGLES)
