"""ТОК ПОСТА (17.09.2026) — правки владельца по посту про биткоин-резерв США (H.R. 8957).

ЗАЧЕМ. Пост был верен по фактам и забракован за подачу: «много обрывистых мыслей, несвязанных
абзацев, незавершённых мыслей <…> хочется более связано всё чтобы всё читалось легко, а тут блин
каждый раз как деревянное, как топором». Абзацы стояли кирпичами: каждый описывал отдельное
свойство закона, и их можно было перетасовать без потери смысла.

ЧТО ЗАМЕР СКАЗАЛ ПРОТИВ ОЧЕВИДНОГО ПРАВИЛА. «Каждый абзац обязан цепляться за предыдущий» кодом
не меряется: доля абзацев, начинающихся «с чистого листа» (нет связки в начале И нет общего слова
с предыдущим), у САМОГО владельца — медиана 0.62 по 103 коротким постам канала, у забракованного
драфта — 0.57. Порог на «холодные старты» флажил бы автора чаще машины. Поэтому кодом ловим ровно
два признака, которых у автора НЕТ, а третий (порядок мыслей) ушёл к читателю речи:
  1. списочная склейка в начале абзаца — 0 срабатываний на 427 постах канала;
  2. повод с датой стоит НЕ в лиде — в принятых постах 2026 года дата события в лиде в 92%.

Запуск: python -m pytest tests/test_scope_flow.py"""
from __future__ import annotations

import json

from core import config, creator_tools as ct, scope_writer

# Реальный драфт 17.09 (сокращён до сути дефекта): лид — цитата из документа, повод с датой
# четвёртым абзацем, склейка-перечислитель «Главное отличие».
BAD = """**⚠️ Государство обязалось доказывать свои биткоины**

В тексте **H.R. 8957** - законопроекта, который переводит биткоин-резерв США из указа президента в закон - записана вещь, которой не было ни в одном указе

Минфин обязан **раз в квартал публиковать отчёт** - сколько монет, какие операции и доказательство, что ключи у него. Проверяет независимый аудитор

Запасы золота США так не показывают: полная инвентаризация Форт-Нокса последний раз была в прошлом веке

16 сентября профильный комитет Палаты представителей **одобрил документ голосованием 28-21**. Дальше голосование всей Палаты, потом Сенат и подпись президента

Главное отличие - в сроке действия. Резерв в статусе указа держится до следующего президента, который отменит его таким же указом

Первая настоящая проверка - **первый квартальный отчёт с подтверждением ключей**. До него резерв держится на слове президента

🖥 [Канал](https://t.me/x) | ▶️ [Медиа](https://linktr.ee/x)
"""

# Тот же пост после правки: событие в лиде, склейка заменена живым переходом.
GOOD = BAD.replace(
    "В тексте **H.R. 8957** - законопроекта, который переводит биткоин-резерв США из указа президента в закон - записана вещь, которой не было ни в одном указе",
    "16 сентября профильный комитет Палаты представителей **одобрил H.R. 8957 голосованием 28-21**. Законопроект переводит биткоин-резерв США из указа президента в закон - и вписывает вещь, которой не было ни в одном указе",
).replace(
    "16 сентября профильный комитет Палаты представителей **одобрил документ голосованием 28-21**. Дальше голосование всей Палаты, потом Сенат и подпись президента",
    "Дальше голосование всей Палаты, потом Сенат и подпись президента",
).replace("Главное отличие - в сроке действия.", "Но главное отличие даже не в проверке, а в сроке.")


def _warns(text: str) -> list:
    return ct._lint(text, kind="scope")[1]


# ── списочная склейка ───────────────────────────────────────────────────────────────────────────

def test_real_defect_17_09_glue_is_caught():
    assert any("СКЛЕЙКА" in w for w in _warns(BAD)), "«Главное отличие -» снова уехало бы в канал"


def test_glue_variants():
    for v in ("Что ещё записано: закон", "Кроме того, Минфин", "Также стоит сказать",
              "Главное отличие - в сроке", "Ещё один момент: ключи"):
        assert ct._LIST_GLUE.search(v), v


def test_glue_only_at_paragraph_start():
    """«Кроме того» ВНУТРИ фразы — обычная речь, не склейка-перечислитель."""
    assert not ct._LIST_GLUE.search("резерв растёт, и кроме того его нельзя продать")


def test_channel_never_starts_a_paragraph_that_way():
    """Замер-замок: 427 постов канала, ноль срабатываний. Разойдётся — правило ловит автора."""
    posts = json.load(open(config.ROOT / "data" / "channel_posts.json", encoding="utf-8"))
    hits = [p["id"] for p in posts if ct._LIST_GLUE.search(p.get("text") or "")]
    assert not hits, f"ложные срабатывания на принятых постах: {hits[:5]}"


# ── повод закопан ───────────────────────────────────────────────────────────────────────────────

def test_real_defect_17_09_buried_event_is_caught():
    assert any("СОБЫТИЕ ЗАКОПАНО" in w for w in _warns(BAD))
    assert ct.buried_event(BAD)[0] == 4, "номер абзаца в пометке должен совпадать с реальным"


def test_event_in_lead_is_clean():
    assert not ct.buried_event(GOOD)
    assert not any("СОБЫТИЕ ЗАКОПАНО" in w for w in _warns(GOOD))


def test_past_case_with_year_is_not_an_event():
    """Кость «ТАК УЖЕ БЫЛО» (§6) стоит в середине по правилам — её трогать нельзя."""
    post = GOOD.replace("Запасы золота США так не показывают:",
                        "В декабре 2017 SEC приняла такое же правило, и оно ничего не изменило. "
                        "Запасы золота США так не показывают:")
    assert not ct.buried_event(post)


def test_short_post_is_not_judged():
    """Мелкий повод живёт на 3-4 абзацах — порядка там нет, судить нечего."""
    assert not ct.buried_event("**Заголовок**\n\nлид без даты\n\n16 сентября комитет одобрил закон")


def test_channel_2026_is_clean():
    """Замер: на принятых постах 2026 года правило молчит (дата события у автора и так в лиде)."""
    posts = json.load(open(config.ROOT / "data" / "channel_posts.json", encoding="utf-8"))
    fresh = [p for p in posts if p.get("date", "") >= "2026-06"]
    assert fresh
    hits = [p["id"] for p in fresh if ct.buried_event(p.get("text") or "")]
    assert len(hits) <= 2, f"правило разошлось с подачей автора: {hits}"


# ── читатель речи: переходы ─────────────────────────────────────────────────────────────────────

def test_speech_reader_asks_about_transitions():
    assert "ПЕРЕХОДЫ" in scope_writer.SPEECH_READ
    assert "топором" in scope_writer.SPEECH_READ, "без реального случая задача читается как абстракция"


def test_speech_reader_does_not_demand_a_bridge_everywhere():
    """Замер 103 постов: у автора половина абзацев начинается с нового факта — это норма."""
    assert "НЕ требуй связки в КАЖДОМ абзаце" in scope_writer.SPEECH_READ


def test_speech_fix_may_reorder_but_not_rewrite():
    assert "ПОЛСВЯЗКОЙ" in scope_writer.SPEECH_FIX and "переставь абзац" in scope_writer.SPEECH_FIX
    assert "НЕ переписывай" in scope_writer.SPEECH_FIX
