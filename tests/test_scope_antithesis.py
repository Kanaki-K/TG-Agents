"""Антитеза «не A, а Б» в коротком посте — правка владельца 17.08 (пост Stripe/OpenRouter).

Владелец снёс фигуру ТРИЖДЫ: из заголовка («купил не модель, а рубильник»), из середины
(«7 млрд$, а не грант на пилот») и из финала («дошёл не человек, а его агент»). Линтер молчал:
считал только ПРЯМУЮ форму и только от 3 шт, а прямых было 2. Здесь закрыты обе дырки —
у scope в счёт идёт и обратная форма, а в заголовке фигура помечается всегда (терпимость 0).
Флагман не трогаем: обратную форму убрали оттуда 20.07 намеренно (ловила простой контраст).
Запуск: python -m pytest tests/test_scope_antithesis.py"""
from core import creator_tools as ct

TITLE = "**🌐 Stripe купил не модель, а рубильник для ИИ-агентов**"

# Тело поста 17.08 в сокращении: те же три фигуры, что снёс владелец.
POST = (
    TITLE + "\n\n"
    "16 августа Stripe договорился о покупке OpenRouter за более 7 млрд$\n\n"
    "Долгосрочному холдеру тут важно вот что. Платёжный гигант голосует деньгами за то, что "
    "расчёты между машинами пойдут по блокчейну. И платит за это 7 млрд$, а не грант на пилот\n\n"
    "Инфраструктуру под криптоплатежи годами строили под людей. Первым до кассы дошёл не человек, "
    "а его агент\n"
)


def _anti_warn(warns):
    return [w for w in warns if "передоз антитезы" in w]


def _title_warn(warns):
    return [w for w in warns if "заголовок построен на АНТИТЕЗЕ" in w]


# --- счётчик в теле: у scope обе формы в одном счёте ---

def test_scope_counts_both_forms():
    # 2 прямых + 1 обратная = 3 → срабатывает (раньше считались только прямые = 2, молчал)
    _, warns = ct._lint(POST, "scope")
    assert _anti_warn(warns), "три фигуры в мини-посте должны дать предупреждение"


def test_flagship_counter_unchanged():
    # у флагмана обратная форма в счёт НЕ идёт (решение 20.07: ловила простой контраст) → 2 < 3
    _, warns = ct._lint(POST, "флагман")
    assert not _anti_warn(warns), "порог флагмана трогать не собирались"


def test_scope_two_direct_still_silent():
    # порог остался 3: две фигуры — не передоз, ложняков не плодим
    body = (
        "**🌐 Заголовок про рубильник**\n\n"
        "Stripe купил не модель, а маршрутизатор\n\n"
        "Читателю важно не обещание, а работающий канал расчётов\n"
    )
    _, warns = ct._lint(body, "scope")
    assert not _anti_warn(warns)


# --- заголовок: терпимость нулевая, но это WARN, а не рез ---

def test_title_antithesis_detected():
    assert ct._title_antithesis("**🌐 Stripe купил не модель, а рубильник для ИИ-агентов**") is True
    assert ct._title_antithesis("🌐 Платит рынок, а не регулятор") is True


def test_title_plain_not_flagged():
    # то, что оставил владелец, — чистое утверждение, претензии быть не должно
    assert ct._title_antithesis("🌐 Stripe купил рубильник для ИИ-агентов") is False
    assert ct._title_antithesis("📊 Пенсионные деньги американцев дотянулись до крипты") is False


def test_title_tag_theme_not_flagged():
    # тег-рубрику «🌐 LINK | …» не считаем частью крючка (как в соседних детекторах заголовка)
    assert ct._title_antithesis("🌐 LINK | Мост в крипту для азиатских капиталов") is False


def test_title_warn_but_not_cut():
    # заголовок помечаем, но НЕ режем: отличить чучело от реального спора код не может,
    # а ложный рез заголовка — тот самый вред, из-за которого автор перестаёт верить линтеру
    clean, warns = ct._lint(POST, "scope")
    assert _title_warn(warns), "фигура в заголовке должна быть помечена всегда"
    assert "не модель, а рубильник" in clean, "заголовок правит автор, код только показывает"


# --- валюта при СЛОВЕСНОМ числе (та же правка 17.08) ---

def test_word_currency_fixed():
    clean, warns = ct._lint("**🌐 Заголовок**\n\nвся машинная экономика - десятки миллионов$ оборота\n",
                            "scope")
    assert "десятки миллионов дол." in clean
    assert any("приклеена к СЛОВУ" in w for w in warns)


def test_digit_currency_untouched():
    # канон §2 «валюта ПОСЛЕ числа» — 7 млрд$ / 73 млн$ не трогаем
    clean, warns = ct._lint("**🌐 Заголовок**\n\nStripe заплатил более 7 млрд$ и ещё 73 млн$ сверху\n",
                            "scope")
    assert "7 млрд$" in clean and "73 млн$" in clean
    assert not any("приклеена к СЛОВУ" in w for w in warns)
