"""Ским-слой поста: якорный жирный (§5) — проверки линтера от 10.09.2026.

ОТКУДА. Владелец доразметил вышедший флагман руками, и сравнение с заводским драфтом дало правила,
которых раньше не было в коде: плотность 8.6% выглядела нормой, но набрали её жирные ВЫВЕСКИ —
в теле было 4 акцента на 13 абзацев, а «💡 Главное» осталось без выделения вовсе. В ручной же
разметке жирными ушли ВСЕ числа подряд, включая исходные данные вычисления, и ским (чтение только
жирного) складывался в таблицу цифр вместо мысли. Тесты держат оба края.
"""
from core import creator_tools as ct

FOOT = "🖥 [Канал](https://t.me/x)"


def _post(body: str, finale: str = "Доходности не складываются, а **перемножаются** — дорога из ямы длиннее ямы") -> str:
    return (f"**💸 Заголовок поста**\n\n{body}\n\n**💡 Главное**\n\n{finale}\n\n"
            f"**💭 Вопрос к Вам**\n\nКакой рост нужен, чтобы отыграть просадку?\n\n{FOOT}")


def _has(warns, needle):
    return any(needle in w for w in warns)


def test_flat_body_under_fat_headers():
    """Плотность в норме за счёт вывесок, а тело плоское — ловим (кейс 10.09)."""
    # Как в жизни: пара акцентов в теле всё же есть, поэтому по плотности пост проходит —
    # ловит его именно ПОКРЫТИЕ (2 размеченных абзаца из 6).
    paras = [f"Абзац номер {i} про рынок, деньги и проценты — двести знаков ровного текста "
             f"без единого выделения, ровно так выглядел заводской драфт." for i in range(6)]
    paras[1] = paras[1].replace("двести знаков", "**двести знаков**")
    paras[4] = paras[4].replace("ровный текст", "текст").replace("заводской драфт", "**заводской драфт**")
    flat = "\n\n".join(paras)
    warns = ct._bold_warns(_post(flat), "flagship")
    assert _has(warns, "на ВЫВЕСКАХ")


def test_numbers_only_skim_reads_as_table():
    """Жирные голые числа = ским читается таблицей цифр, а не конспектом."""
    body = ("Возьмите **1000$**. Плюс 50% — это **1500$**. Теперь минус 50% от полутора тысяч, и на "
            "счету остаётся **750$**. Ровно **25%** потерь, которых никто не заметил и не считал")
    warns = ct._bold_warns(_post(body), "flagship")
    assert _has(warns, "таблица чисел")


def test_number_with_word_is_not_a_table():
    """Тот же смысл, но выделен ИТОГ вместе со словами — претензии нет."""
    body = ("Возьмите 1000$. Плюс 50% — это 1500$. Теперь минус 50% от полутора тысяч, и **на счету "
            "остаётся 750$**. Это **потеря четверти счёта**, которой никто не заметил в уме")
    assert not _has(ct._bold_warns(_post(body), "flagship"), "таблица чисел")


def test_torn_bold_inside_one_phrase():
    """Два акцента в одной фразе через пару слов — глаз собирает обрывок."""
    body = ("Волатильность **наказывает тех**, кто **выскочил на дне**, и вознаграждает тех, кто "
            "остался в позиции до конца цикла без единой перекладки")
    assert _has(ct._bold_warns(_post(body), "flagship"), "рваный жирный")


def test_three_accents_in_one_paragraph():
    body = ("**Солана** сегодня стоит 99$, её пик — **294$ в январе 2025**, и чтобы вернуться на "
            "прежнюю вершину, ей нужно **почти утроиться**, то есть плюс 197% от текущих уровней")
    assert _has(ct._bold_warns(_post(body), "flagship"), "акцентов в одном абзаце")


def test_finale_without_accent():
    """Самое сильное место поста не может быть визуально плоским."""
    body = "Механика простая: **проценты перемножаются**, а не складываются, и качели съедают счёт"
    warns = ct._bold_warns(_post(body, finale="Доходности не складываются, а перемножаются — "
                                              "дорога из ямы всегда длиннее самой ямы"), "flagship")
    assert _has(warns, "вывод БЕЗ акцента")


def test_list_block_needs_no_accent():
    """Таблица отыгрыша держится структурой — требовать в ней жирное неправильно."""
    table = "\n".join(["−10% отыгрывает +11%", "−33% требует уже +50%", "−50% требует +100%",
                       "−80% требует +400%", "−90% требует +900%"])
    body = (f"Падение и рост несимметричны — чтобы отыграть просадку, нужен **непропорционально "
            f"больший плюс**\n\n{table}")
    assert not _has(ct._bold_warns(_post(body), "flagship"), "на ВЫВЕСКАХ")


def test_clean_post_is_silent():
    """Контроль: размеченный по §5 пост не должен ловить ни одной претензии."""
    paras = [f"Абзац номер {i} про рынок и деньги — ровный текст на двести с лишним знаков, в "
             f"котором выделен **один несущий кусок**, как того и требует свод, а всё остальное "
             f"идёт обычным начертанием и глаз по нему не спотыкается." for i in range(6)]
    assert ct._bold_warns(_post("\n\n".join(paras)), "flagship") == []


def test_threads_has_no_bold_at_all():
    """В Threads жирного нет — линтер не должен требовать разметку."""
    assert ct._bold_warns("Плоский тред без разметки.\n\nВторая строка мысли.", "threads_flagship") == []
